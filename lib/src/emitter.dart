import 'ast.dart';
import 'constants.dart';
import 'semantics.dart';
import 'source.dart';

class DartEmitter {
  DartEmitter(this.model);
  final SemanticModel model;
  final _out = StringBuffer('// Generated by Quds MVP-0. Do not edit.\n');
  final _constNames = <String>{};
  final _topLevelConsts = <String>{};
  final _usedNames = <String>{};
  var _useBoolHelper = false;
  var _useRange = false;
  var _useNumRange = false;
  var _useOptional = false;
  var _useResult = false;
  var _useConversion = false;
  var _useReturn = false;
  var _inDo = false;
  String? _matched;
  StringBuffer? _redirect;
  final _unions = <String>{};
  int _depth = 0;
  int _temps = 0;
  SourceSpan? _span;
  final mappings = <(int, SourceSpan)>[];
  final _imports = <String>[];
  var _classes = <String, ClassDeclaration>{};
  var _useState = false;
  var _useComputed = false;
  var _useWatch = false;
  Map<String, String> _names = const {};
  void line(String text) {
    if (_redirect != null) {
      _redirect!.writeln('${'  ' * _depth}$text');
      return;
    }
    if (_span != null) {
      final generatedLine = '\n'.allMatches(_out.toString()).length + 1;
      mappings.add((generatedLine, _span!));
    }
    _out.writeln('${'  ' * _depth}$text');
  }

  String emit(Program program) {
    for (final node in program.statements) {
      if (node is ImportDeclaration) {
        final uri = node.uri.endsWith('.quds')
            ? '${node.uri.substring(0, node.uri.length - 5)}.dart'
            : node.uri;
        final prefix = node.prefix == null ? '' : ' as ${node.prefix}';
        _imports.add("import '$uri'$prefix;");
      }
    }
    _classes = {
      for (final node in program.statements)
        if (node is ClassDeclaration) node.name: node
    };
    for (final node in program.statements) {
      if (node is ClassDeclaration) emitClass(node);
      if (node is ExtensionDeclaration) emitExtension(node);
    }
    for (final node in program.statements) {
      _out.writeln();
      if (node is FunctionDeclaration) {
        emitFunction(node);
      } else if (node is! ImportDeclaration &&
          node is! ClassDeclaration &&
          node is! ExtensionDeclaration) {
        statement(node);
      }
    }
    final source = _suppressUnreadConsts(_withHelpers(_out.toString()));
    if (!_useBoolHelper) return source;
    // Dart treats a const bool as unreachable in `if` and `&&`/`||`. The
    // identity call keeps Quds's read-once short-circuit behavior while
    // leaving the generated condition a runtime value.
    return source.replaceFirst(
      '// Generated by Quds MVP-0. Do not edit.\n',
      '// Generated by Quds MVP-0. Do not edit.\n\n'
          'bool _qBool(bool value) => value;\n',
    );
  }

  /// Logical const folding can remove the only read of a const. Keep the
  /// binding and silence Dart's unused warning for that declaration.
  String _suppressUnreadConsts(String source) {
    final unread = _constNames.difference(_usedNames);
    if (unread.isEmpty) return source;
    final lines = source.split('\n');
    final rewritten = <String>[];
    for (final line in lines) {
      final trimmed = line.trimLeft();
      String? lint;
      for (final name in unread) {
        if (trimmed.startsWith('const ') && trimmed.contains(' $name =')) {
          lint = _topLevelConsts.contains(name)
              ? 'unused_element'
              : 'unused_local_variable';
          break;
        }
      }
      if (lint != null) {
        final indent = line.substring(0, line.length - trimmed.length);
        rewritten.add('$indent// ignore: $lint');
      }
      rewritten.add(line);
    }
    return rewritten.join('\n');
  }

  void statements(List<Statement> body) {
    for (final node in body) {
      statement(node);
    }
  }

  String _withHelpers(String source) {
    final helpers = StringBuffer();
    if (_useRange) {
      helpers.writeln(
          'Iterable<int> _qRange(int start, int end, bool inclusive) sync* {\n'
          '  final down = start > end;\n'
          '  for (var value = start; down ? (inclusive ? value >= end : value > end) : (inclusive ? value <= end : value < end); value += down ? -1 : 1) {\n'
          '    yield value;\n'
          '  }\n'
          '}');
    }
    if (_useNumRange) {
      helpers.writeln(
          'Iterable<num> _qNumRange(num start, num end, bool inclusive) sync* {\n'
          '  final down = start > end;\n'
          '  for (var value = start; down ? (inclusive ? value >= end : value > end) : (inclusive ? value <= end : value < end); value += down ? -1 : 1) {\n'
          '    yield value;\n'
          '  }\n'
          '}');
    }
    if (_useOptional) {
      helpers.writeln('class Optional<T> {\n'
          '  final bool isPresent;\n'
          '  final T? value;\n'
          '  const Optional.missing() : isPresent = false, value = null;\n'
          '  const Optional.present(this.value) : isPresent = true;\n'
          '}\n'
          'const missing = Optional<Never>.missing();');
    }
    if (_useResult) {
      helpers.writeln('sealed class Result<T, E> { const Result(); }\n'
          'class Ok<T, E> extends Result<T, E> {\n'
          '  final T value;\n'
          '  const Ok(this.value);\n'
          '}\n'
          'class Error<T, E> extends Result<T, E> {\n'
          '  final E error;\n'
          '  const Error(this.error);\n'
          '}\n'
          'class _QudsPropagate implements Exception {\n'
          '  final Result<Object?, Object?> result;\n'
          '  _QudsPropagate(this.result);\n'
          '}');
    }
    if (_useConversion) {
      helpers.writeln('class ConversionError implements Exception {\n'
          '  ConversionError(this.message);\n'
          '  final String message;\n'
          '  String toString() => \'ConversionError: \$message\';\n'
          '}\n'
          'Object? _qConvert(Object? value, String target, bool safe) {\n'
          '  try {\n'
          '    switch (target) {\n'
          "      case 'String': return value.toString();\n"
          "      case 'bool':\n"
          '        if (value is bool) return value;\n'
          "        if (value == 'true') return true;\n"
          "        if (value == 'false') return false;\n"
          '        break;\n'
          "      case 'int':\n"
          '        if (value is int) return value;\n'
          '        if (value is double && value.isFinite && value == value.truncateToDouble()) return value.toInt();\n'
          '        if (value is String) return int.parse(value);\n'
          '        break;\n'
          "      case 'double':\n"
          '        if (value is double) return value;\n'
          '        if (value is int) return value.toDouble();\n'
          '        if (value is String) return double.parse(value);\n'
          '        break;\n'
          "      case 'num':\n"
          '        if (value is num) return value;\n'
          '        if (value is String) return num.parse(value);\n'
          '        break;\n'
          '    }\n'
          '    throw ConversionError(\'\$value to \$target\');\n'
          '  } catch (error) {\n'
          '    if (safe) return null;\n'
          '    if (error is ConversionError) throw error;\n'
          '    throw ConversionError(\'\$value to \$target\');\n'
          '  }\n'
          '}');
    }
    if (_useReturn) {
      helpers.writeln('class _QudsReturn {\n'
          '  _QudsReturn(this.value);\n'
          '  final Object? value;\n'
          '}');
    }
    for (final union in _unions) {
      final name = _unionClass(union);
      final parts = union.split(' | ').map((part) => part.trim());
      helpers.writeln('sealed class $name { const $name(); }');
      for (final part in parts) {
        final alt = _alt(part);
        helpers.writeln('class ${name}_$alt extends $name {\n'
            '  final ${_dartType(part)} value;\n'
            '  const ${name}_$alt(this.value);\n'
            '}');
      }
    }
    final prelude = StringBuffer();
    for (final item in _imports) {
      prelude.writeln(item);
    }
    if (_useState || _useWatch) {
      helpers.writeln('class _QudsState<T> {\n'
          '  _QudsState(this._value);\n'
          '  T _value;\n'
          '  final List<void Function()> _listeners = [];\n'
          '  static Set<Object>? tracking;\n'
          '  T get value {\n'
          '    final seen = tracking;\n'
          '    if (seen != null) seen.add(this);\n'
          '    return _value;\n'
          '  }\n'
          '  set value(T next) {\n'
          '    if (_value == next) return;\n'
          '    _value = next;\n'
          '    for (final listener in List<void Function()>.of(_listeners)) {\n'
          '      listener();\n'
          '    }\n'
          '  }\n'
          '  void _listen(void Function() listener) {\n'
          '    _listeners.remove(listener);\n'
          '    _listeners.add(listener);\n'
          '  }\n'
          '}');
    }
    if (_useComputed) {
      helpers.writeln('class _QudsComputed<T> {\n'
          '  _QudsComputed(this._read);\n'
          '  final T Function() _read;\n'
          '  T get value => _read();\n'
          '}');
    }
    if (_useWatch) {
      helpers.writeln('void _qWatch(void Function() body) {\n'
          '  var running = false;\n'
          '  void run() {\n'
          '    if (running) return;\n'
          '    running = true;\n'
          '    final previous = _QudsState.tracking;\n'
          '    final seen = <Object>{};\n'
          '    _QudsState.tracking = seen;\n'
          '    try {\n'
          '      body();\n'
          '    } finally {\n'
          '      _QudsState.tracking = previous;\n'
          '      running = false;\n'
          '    }\n'
          '    for (final state in seen) {\n'
          '      (state as _QudsState<Object?>)._listen(run);\n'
          '    }\n'
          '  }\n'
          '  run();\n'
          '}');
    }
    if (helpers.isNotEmpty) prelude.writeln(helpers.toString());
    if (prelude.isEmpty) return source;
    return source.replaceFirst(
      '// Generated by Quds MVP-0. Do not edit.\n',
      '// Generated by Quds MVP-0. Do not edit.\n\n${prelude.toString()}',
    );
  }

  void emitFunction(FunctionDeclaration node) {
    _span = node.span;
    final symbol = model.declarations[node]!;
    final parameters = node.parameters.map((p) {
      final declared = model.declarations[p]!.type;
      return '${_dartType(declared)} ${model.declarations[p]!.dartName}';
    }).join(', ');
    final async = node.generator == 'sync'
        ? 'sync* '
        : node.generator == 'async'
            ? 'async* '
            : node.isAsync
                ? 'async '
                : '';
    final propagate = node.body != null && _containsPropagate(node.body!);
    final doReturn = node.body != null && _containsDoReturn(node.body!);
    if (node.expressionBody case final value?) {
      line(
          '${_dartType(symbol.type)} ${symbol.dartName}($parameters) ${async}=> ${expression(value)};');
    } else {
      line('${_dartType(symbol.type)} ${symbol.dartName}($parameters) $async{');
      _depth++;
      if (propagate || doReturn) {
        line('try {');
        _depth++;
      }
      statements(node.body!);
      if (propagate || doReturn) {
        _depth--;
        if (propagate) {
          line('} on _QudsPropagate catch (propagation) {');
          line('  return propagation.result as ${_dartType(symbol.type)};');
        }
        if (doReturn) {
          _useReturn = true;
          line(propagate
              ? '} on _QudsReturn catch (returned) {'
              : '} on _QudsReturn catch (returned) {');
          line(symbol.type == 'void'
              ? '  return;'
              : '  return returned.value as ${_dartType(symbol.type)};');
        }
        line('}');
      }
      _depth--;
      line('}');
    }
  }

  String _dartType(String type) {
    if (type.startsWith('readonly ')) return _dartType(type.substring(9));
    if (type.contains(' | ')) return _unionClass(type);
    if (type.startsWith('(') && type.contains('->')) {
      final arrow = type.lastIndexOf('->');
      final parameters = type.substring(1, type.indexOf(')'));
      final returns = type.substring(arrow + 3).trim();
      final args = parameters.trim().isEmpty
          ? ''
          : parameters
              .split(',')
              .map((item) => _dartType(item.trim()))
              .join(', ');
      return '${_dartType(returns)} Function($args)';
    }
    if (type.startsWith('Range<')) return 'Iterable<num>';
    return type;
  }

  bool _containsPropagate(List<Statement> body) {
    for (final statement in body) {
      if (_statementPropagates(statement)) return true;
    }
    return false;
  }

  bool _statementPropagates(Statement node) => switch (node) {
        Binding() => _expressionPropagates(node.value),
        ReturnStatement() =>
          node.value != null && _expressionPropagates(node.value!),
        ExpressionStatement() => _expressionPropagates(node.expression),
        IfStatement() => _containsPropagate(node.thenBody) ||
            _containsPropagate(node.elseBody),
        ForStatement() => _containsPropagate(node.body),
        WhileStatement() => _containsPropagate(node.body),
        LabelStatement() => _statementPropagates(node.statement),
        MatchStatement() =>
          node.arms.any((arm) => _containsPropagate(arm.body)),
        _ => false,
      };

  bool _expressionPropagates(Expression node) => switch (node) {
        PropagateExpression() => true,
        UnaryExpression() => _expressionPropagates(node.operand),
        BinaryExpression() =>
          _expressionPropagates(node.left) || _expressionPropagates(node.right),
        CallExpression() =>
          node.arguments.any((a) => _expressionPropagates(a.value)),
        AwaitExpression() => _expressionPropagates(node.operand),
        _ => false,
      };

  void emitClass(ClassDeclaration node) {
    _span = node.span;
    if (node.kind == 'enum') {
      final values = node.cases.map((item) => item.name).join(', ');
      line('enum ${node.name} { $values }');
      return;
    }
    if (node.kind == 'interface') {
      line('abstract interface class ${node.name} {');
      for (final field in node.fields) {
        line('  ${_dartType(field.type)} get ${field.name};');
      }
      line('}');
      return;
    }
    final sealed = node.kind == 'sealed' || node.kind == 'sealedType';
    final header = node.kind == 'mixin'
        ? 'mixin'
        : node.kind == 'mixinClass'
            ? 'mixin class'
            : sealed
                ? 'sealed class'
                : 'class';
    final tail = [
      if (node.onType != null) 'on ${node.onType}',
      if (node.superclass != null) 'extends ${node.superclass}',
      if (node.mixins.isNotEmpty) 'with ${node.mixins.join(', ')}',
      if (node.interfaces.isNotEmpty)
        'implements ${node.interfaces.join(', ')}',
    ].join(' ');
    if (node.kind == 'sealedType') {
      line('$header ${node.name} {');
      line('  const ${node.name}();');
      line('}');
      for (final item in node.cases) {
        final parameters = item.fields
            .map((field) => 'required this.${field.name}')
            .join(', ');
        final constructor = parameters.isEmpty
            ? 'const ${item.name}();'
            : 'const ${item.name}({$parameters});';
        line('class ${item.name} extends ${node.name} {');
        line('  $constructor');
        for (final field in item.fields) {
          line('  final ${field.type} ${field.name};');
        }
        line('}');
      }
      return;
    }
    line('$header ${node.name}${tail.isEmpty ? '' : ' $tail'} {');
    _depth++;
    if (node.kind == 'mixin') {
      for (final method in node.methods) {
        emitFunction(method);
      }
      _depth--;
      line('}');
      return;
    }
    final inherited = _inherited(node);
    final params = [
      ...inherited.map((field) => 'required super.${field.name}'),
      for (final field in node.fields)
        () {
          final required = field.requiredField && field.initializer == null
              ? 'required '
              : '';
          final value = field.initializer == null
              ? ''
              : ' = ${expression(field.initializer!)}';
          return '$required${'this.${field.name}$value'}';
        }(),
    ].join(', ');
    line('${node.name}({$params});');
    for (final field in node.fields) {
      final modifier = field.mutable ? '' : 'final ';
      line('$modifier${field.type} ${field.name};');
    }
    for (final method in node.methods) {
      if (node.annotations.contains('macro') && method.name == 'define') {
        continue;
      }
      emitFunction(method);
    }
    if (node.kind == 'value') {
      final names = node.fields.map((field) => field.name).join(', ');
      final compare = node.fields
          .map((field) => '${field.name} == other.${field.name}')
          .join(' && ');
      line('@override');
      line(
          'bool operator ==(Object other) => other is ${node.name} && ${compare.isEmpty ? 'true' : compare};');
      line('@override');
      line('int get hashCode => Object.hashAll(<Object?>[$names]);');
    }
    _depth--;
    line('}');
  }

  List<FieldDeclaration> _inherited(ClassDeclaration node) {
    final fields = <FieldDeclaration>[];
    var name = node.superclass;
    while (name != null) {
      final parent = _classes[name];
      if (parent == null) break;
      fields.insertAll(0, parent.fields);
      name = parent.superclass;
    }
    return fields;
  }

  void emitExtension(ExtensionDeclaration node) {
    _span = node.span;
    final title = node.name == null ? 'extension' : 'extension ${node.name}';
    line('$title on ${node.target} {');
    _depth++;
    for (final method in node.methods) {
      emitFunction(method);
    }
    _depth--;
    line('}');
  }

  void statement(Statement node) {
    _span = node.span;
    switch (node) {
      case Binding():
        if (model.assignments.contains(node)) {
          line(
              '${_cell(model.references[node]!)} ${node.operator} ${expression(node.value)};');
        } else {
          final symbol = model.declarations[node]!;
          if (symbol.reactive == 'state' || symbol.reactive == 'computed') {
            final computed = symbol.reactive == 'computed';
            if (computed) {
              _useComputed = true;
            } else {
              _useState = true;
            }
            final wrapper = computed ? '_QudsComputed' : '_QudsState';
            final type = _dartType(symbol.type);
            if (computed) {
              line('late $wrapper<$type> ${symbol.dartName};');
              line(
                  '${symbol.dartName} = $wrapper<$type>(() => ${expression(node.value)});');
            } else {
              line(
                  'final ${symbol.dartName} = $wrapper<$type>(${expression(node.value)});');
            }
            return;
          }
          final modifier = symbol.late
              ? (symbol.mutable ? 'late ' : 'late final ')
              : symbol.constant
                  ? 'const '
                  : symbol.mutable
                      ? ''
                      : 'final ';
          if (node.open) {
            line('$modifier${_dartType(symbol.type)} ${symbol.dartName};');
            return;
          }
          if (symbol.constant) {
            _constNames.add(symbol.dartName);
            if (_depth == 0) _topLevelConsts.add(symbol.dartName);
          }
          final initializer =
              expression(node.value, constantContext: symbol.constant);
          line(
              '$modifier${_dartType(symbol.type)} ${symbol.dartName} = $initializer;');
        }
      case ReturnStatement():
        if (_inDo) {
          _useReturn = true;
          line(node.value == null
              ? 'throw _QudsReturn(null);'
              : 'throw _QudsReturn(${expression(node.value!)});');
        } else {
          line(node.value == null
              ? 'return;'
              : 'return ${expression(node.value!)};');
        }
      case ResultStatement():
        line('return ${expression(node.value)};');
      case CForStatement():
        final init = node.init as Binding;
        final symbol = model.declarations[init]!;
        final step = node.step == null ? '' : _runtimeStep(node.step!);
        final keyword = symbol.mutable ? '' : 'final ';
        line(
            'for ($keyword${_dartType(symbol.type)} ${symbol.dartName} = ${expression(init.value)}; ${expression(node.condition)}; $step) {');
        _depth++;
        statements(node.body);
        _depth--;
        line('}');
      case TryStatement():
        line('try {');
        _depth++;
        statements(node.body);
        _depth--;
        for (final clause in node.catches) {
          final caught = model.declarations[clause]!;
          final trace = model.traces[clause];
          final names = trace == null
              ? caught.dartName
              : '${caught.dartName}, ${trace.dartName}';
          line(clause.type == null
              ? '} catch ($names) {'
              : '} on ${clause.type} catch ($names) {');
          _depth++;
          statements(clause.body);
          _depth--;
        }
        if (node.finallyBody.isNotEmpty) {
          line('} finally {');
          _depth++;
          statements(node.finallyBody);
          _depth--;
        }
        line('}');
      case ThrowStatement():
        line('throw ${expression(node.value)};');
      case RethrowStatement():
        line('rethrow;');
      case YieldStatement():
        line('${node.star ? 'yield*' : 'yield'} ${expression(node.value)};');
      case WatchStatement():
        _useState = true;
        _useWatch = true;
        line('_qWatch(() {');
        _depth++;
        line(
            '(() { final watched = ${expression(node.value)}; return watched; })();');
        statements(node.body);
        _depth--;
        line('});');
      case RepeatStatement():
        line('do {');
        _depth++;
        statements(node.body);
        _depth--;
        line('} while (${expression(node.condition)});');
      case TestDeclaration():
        final tested = model.declarations[node]!;
        line('void ${tested.dartName}() {');
        _depth++;
        for (final child in node.body) {
          statement(child);
          if (child is TestDeclaration) {
            line('${model.declarations[child]!.dartName}();');
          }
        }
        _depth--;
        line('}');
      case ExpressionStatement():
        line('${expression(node.expression)};');
      case IfStatement():
        line('if (${expression(node.condition, opaqueBool: true)}) {');
        _depth++;
        statements(node.thenBody);
        _depth--;
        if (node.elseBody.isNotEmpty) {
          line('} else {');
          _depth++;
          statements(node.elseBody);
          _depth--;
        }
        line('}');
      case ForStatement():
        final symbol = model.declarations[node]!;
        final iterable = node.iterable is RangeExpression
            ? _range(node.iterable as RangeExpression)
            : expression(node.iterable);
        line(
            '${node.awaiting ? 'await ' : ''}for (final ${_dartType(symbol.type)} ${symbol.dartName} in $iterable) {');
        _depth++;
        statements(node.body);
        _depth--;
        line('}');
      case WhileStatement():
        line('while (${expression(node.condition, opaqueBool: true)}) {');
        _depth++;
        statements(node.body);
        _depth--;
        line('}');
      case BreakStatement():
        line(node.label == null ? 'break;' : 'break ${node.label};');
      case ContinueStatement():
        line(node.label == null ? 'continue;' : 'continue ${node.label};');
      case LabelStatement():
        line('${node.name}:');
        statement(node.statement);
      case MatchStatement():
        _matched = model.types[node.value];
        if (_matched != null && _matched!.contains(' | '))
          _unions.add(_matched!);
        line('switch (${expression(node.value)}) {');
        _depth++;
        for (final arm in node.arms) {
          final guard =
              arm.guard == null ? '' : ' when ${expression(arm.guard!)}';
          line('case ${_pattern(arm.pattern)}$guard:');
          _depth++;
          statements(arm.body);
          _depth--;
        }
        if (model.warnings.any((warning) =>
            warning.code == 'W001' && identical(warning.span, node.span))) {
          line('default:');
          line('  break;');
        }
        _depth--;
        line('}');
      case DestructureStatement():
        final temp = '_qt${_temps++}';
        line('final $temp = ${expression(node.value)};');
        _destructure(node.pattern, temp, 1);
      case FunctionDeclaration():
        emitFunction(node);
      case ClassDeclaration():
      case ExtensionDeclaration():
      case ImportDeclaration():
        break;
    }
  }

  String _range(RangeExpression node) {
    final integer = model.types[node] == 'Range<int>';
    if (integer) {
      _useRange = true;
    } else {
      _useNumRange = true;
    }
    final name = integer ? '_qRange' : '_qNumRange';
    return '$name(${expression(node.start)}, ${expression(node.end)}, ${node.inclusive})';
  }

  String _pattern(Pattern pattern) {
    final matched = _matched;
    return switch (pattern) {
      WildcardPattern() => '_',
      TypedPattern() => matched != null && matched.contains(' | ')
          ? _unionPattern(matched, pattern)
          : pattern.name == null
              ? pattern.type
              : 'final ${model.declarations[pattern]!.dartName}',
      BindingPattern() => model.references[pattern]?.classCase != null
          ? (model.enumNames
                  .contains(model.references[pattern]!.classDeclaration!.name)
              ? model.references[pattern]!.dartName
              : '${model.references[pattern]!.dartName}()')
          : 'final ${model.declarations[pattern]!.dartName}',
      LiteralPattern() => expression(pattern.literal),
      ListPattern() => '[${pattern.elements.map(_pattern).join(', ')}]',
      ConstructorPattern() => pattern.typeName.isEmpty
          ? '(${pattern.fields.map(_pattern).join(', ')})'
          : '${pattern.typeName}(${[
              for (var i = 0; i < pattern.fields.length; i++)
                pattern.names[i] == null
                    ? _pattern(pattern.fields[i])
                    : '${pattern.names[i]}: ${_pattern(pattern.fields[i])}'
            ].join(', ')})',
    };
  }

  void _destructure(Pattern pattern, String source, int position) {
    switch (pattern) {
      case WildcardPattern():
      case TypedPattern():
        if (pattern is TypedPattern &&
            pattern.name != null &&
            model.declarations[pattern] != null) {
          final declared = model.declarations[pattern]!;
          line('final ${declared.type} ${declared.dartName} = $source;');
        }
        return;
      case BindingPattern():
        final declared = model.declarations[pattern];
        if (declared != null) {
          line('final ${declared.type} ${declared.dartName} = $source;');
        }
      case ListPattern():
        for (var i = 0; i < pattern.elements.length; i++) {
          _destructure(pattern.elements[i], '$source[$i]', position);
        }
      case ConstructorPattern():
        for (var i = 0; i < pattern.fields.length; i++) {
          final field = pattern.names[i];
          final child = field == null ? '$source.\$${i + 1}' : '$source.$field';
          _destructure(pattern.fields[i], child, position);
        }
      case LiteralPattern():
        return;
    }
  }

  String quote(String value) => quoteDartString(value);
  String expression(Expression node,
      {bool constantContext = false, bool opaqueBool = false}) {
    // Folding only logical const operators avoids Dart's dead_code warning
    // while leaving other const operations for Dart to evaluate again.
    if (constantContext &&
        node is BinaryExpression &&
        (node.operator == 'and' || node.operator == 'or')) {
      final value = model.constants[node];
      if (value is! ConstBool) {
        throw StateError('Logical const was not evaluated');
      }
      return value.dartSource;
    }
    // A const or literal bool is reachable to Dart's analyzer when it is
    // hidden behind an identity call. The operand is still read once.
    if (model.wrapAs[node] case final union?) {
      model.wrapAs.remove(node);
      final innerType = model.types[node]!;
      final inner = expression(node,
          constantContext: constantContext, opaqueBool: opaqueBool);
      _unions.add(union);
      return '${_unionClass(union)}_${_alt(innerType)}($inner)';
    }
    if (opaqueBool && !constantContext && _opaqueBoolLeaf(node)) {
      _useBoolHelper = true;
      return '_qBool(${expression(node, constantContext: constantContext)})';
    }
    final logic = node is BinaryExpression &&
        (node.operator == 'and' || node.operator == 'or');
    final childOpaque = !constantContext && (opaqueBool || logic);
    return switch (node) {
      Literal() =>
        node.value is String ? quote(node.value as String) : '${node.value}',
      Identifier() => _identifier(node),
      // Dart has no prefix +. Quds unary + is numeric identity.
      UnaryExpression() => switch (node.operator) {
          'not' =>
            '(!${expression(node.operand, constantContext: constantContext, opaqueBool: childOpaque)})',
          '+' => expression(node.operand, constantContext: constantContext),
          '!' =>
            '(${expression(node.operand, constantContext: constantContext)}!)',
          _ =>
            '(${node.operator}${expression(node.operand, constantContext: constantContext)})',
        },
      BinaryExpression() =>
        '(${expression(node.left, constantContext: constantContext, opaqueBool: childOpaque)} ${switch (node.operator) {
          'and' => '&&',
          'or' => '||',
          _ => node.operator
        }} ${expression(node.right, constantContext: constantContext, opaqueBool: childOpaque)})',
      ListExpression() => _list(node),
      CallExpression() => call(node, constantContext: constantContext),
      InterpolatedString() =>
        '[${node.parts.map((part) => expression(part, constantContext: constantContext)).join(', ')}].join()',
      Lambda() => _lambda(node),
      MemberAccess() =>
        '${expression(node.object, constantContext: constantContext)}${node.nullAware ? '?.' : '.'}${node.name}',
      IndexExpression() =>
        '${expression(node.object, constantContext: constantContext)}[${expression(node.index, constantContext: constantContext)}]',
      MapExpression() => _map(node),
      SetExpression() => _set(node),
      RecordExpression() =>
        '(${node.fields.map((field) => expression(field)).join(', ')})',
      RangeExpression() => _range(node),
      AwaitExpression() =>
        '(await ${expression(node.operand, constantContext: constantContext)})',
      PropagateExpression() => _propagate(node),
      DoExpression() => _do(node),
      CaptureExpression() => _capture(node),
      ConversionExpression() => _convert(node),
      WithExpression() => _with(node),
      DotShorthand() => _dot(node),
      AssignExpression() =>
        '${_cell(model.references[node]!)} ${node.operator} ${expression(node.value, constantContext: constantContext)}',
      ThisExpression() => 'this',
      SpreadElement() =>
        '${node.nullAware ? '...?' : '...'}${expression(node.operand, constantContext: constantContext)}',
      IfExpression() => _if(node),
      MatchExpression() => _match(node),
      TryExpression() =>
        '(() { try { return ${expression(node.operand)}; } catch (error) { return ${expression(node.fallback)}; } })()',
      MapComprehension() => _mapEntry(node, node, 'Object', 'Object'),
      NullAwareElement() => '?(${expression(node.value)})',
      CollectionIf() => _piece(node, 'Object', false),
      CollectionFor() => _piece(node, 'Object', false),
    };
  }

  bool _opaqueBoolLeaf(Expression node) {
    if (node is Literal) return node.value is bool;
    if (node is Identifier) {
      final symbol = model.references[node];
      return symbol != null && symbol.type == 'bool' && symbol.function == null;
    }
    return false;
  }

  String _identifier(Identifier node) {
    if (model.implicitThis.contains(node)) return 'this.${node.name}';
    final symbol = model.references[node];
    if (symbol?.name == 'missing') _useOptional = true;
    if (symbol != null &&
        (symbol.reactive == 'state' || symbol.reactive == 'computed')) {
      return _cell(symbol);
    }
    final dart = _use(node);
    return _names[dart] ?? dart;
  }

  String _cell(Symbol symbol) {
    if (symbol.reactive == 'state' || symbol.reactive == 'computed') {
      if (symbol.reactive == 'state') {
        _useState = true;
      } else {
        _useComputed = true;
      }
      return '${symbol.dartName}.value';
    }
    return symbol.dartName;
  }

  String _use(Identifier node) {
    final name = model.references[node]!.dartName;
    _usedNames.add(name);
    return name;
  }

  String _lambda(Lambda node) {
    final parameters = node.parameters
        .map((p) =>
            '${model.declarations[p]!.type} ${model.declarations[p]!.dartName}')
        .join(', ');
    if (node.expressionBody case final value?) {
      return '(($parameters) => ${expression(value)})';
    }
    final buffer = StringBuffer('(($parameters) { ');
    return '$buffer})';
  }

  String _map(MapExpression node) {
    final type = model.types[node]!;
    final inner = type.substring(4, type.length - 1);
    final splitAt = inner.indexOf(',');
    final keyType = inner.substring(0, splitAt).trim();
    final valueType = inner.substring(splitAt + 1).trim();
    return '<$keyType, $valueType>{${_mapEntries(node, keyType, valueType)}}';
  }

  String _mapEntries(MapExpression node, String keyType, String valueType) => [
        for (var i = 0; i < node.keys.length; i++)
          _mapEntry(node.keys[i], node.values[i], keyType, valueType)
      ].join(', ');

  String _mapEntry(
      Expression key, Expression value, String keyType, String valueType) {
    if (key is SpreadElement) {
      final text = expression(key.operand);
      return key.nullAware ? '...?$text' : '...$text';
    }
    if (key is MapComprehension) {
      if (key.name != null) {
        final symbol = model.declarations[key]!;
        return 'for (final ${_dartType(symbol.type)} ${symbol.dartName} in ${expression(key.iterable!)}) ...<$keyType, $valueType>{${_mapEntries(key.thenMap, keyType, valueType)}}';
      }
      final tail = key.elseMap == null
          ? ''
          : ' else ...<$keyType, $valueType>{${_mapEntries(key.elseMap!, keyType, valueType)}}';
      return 'if (${expression(key.condition!, opaqueBool: true)}) ...<$keyType, $valueType>{${_mapEntries(key.thenMap, keyType, valueType)}}$tail';
    }
    return '${expression(key)}: ${expression(value)}';
  }

  String _if(IfExpression node) {
    String chain(Expression branch) {
      if (branch is IfExpression) {
        return ' else if (${expression(branch.condition, opaqueBool: true)}) { return ${expression(branch.thenValue)}; }${chain(branch.elseValue)}';
      }
      return ' else { return ${expression(branch)}; }';
    }

    return '(() { if (${expression(node.condition, opaqueBool: true)}) { return ${expression(node.thenValue)}; }${chain(node.elseValue)} })()';
  }

  String _match(MatchExpression node) {
    final saved = _matched;
    _matched = model.types[node.value];
    if (_matched != null && _matched!.contains(' | ')) _unions.add(_matched!);
    final arms = node.arms.map((arm) {
      final guard = arm.guard == null ? '' : ' when ${expression(arm.guard!)}';
      return 'case ${_pattern(arm.pattern)}$guard: return ${expression(arm.result)};';
    }).join(' ');
    _matched = saved;
    return '(() { switch (${expression(node.value)}) { $arms } })()';
  }

  String _runtimeStep(Expression step) {
    if (step is AssignExpression &&
        (step.operator == '+=' || step.operator == '-=') &&
        step.value is! Literal) {
      final target = model.references[step]!.dartName;
      final temp = '_qs${_temps++}';
      final op = step.operator == '+=' ? '+=' : '-=';
      return '(() { final $temp = ${expression(step.value)}; if ($temp == 0) throw StateError(\'A loop step cannot be zero\'); $target $op $temp; })()';
    }
    return expression(step);
  }

  String _propagate(PropagateExpression node) {
    _useResult = true;
    final temp = '_qr${_temps++}';
    final value = expression(node.operand);
    return '(() { final $temp = $value; if ($temp is Error) throw _QudsPropagate($temp); return ($temp as Ok).value; })()';
  }

  String call(CallExpression node, {bool constantContext = false}) {
    final targetSymbol = model.references[node.callee]!;
    if (targetSymbol.name == 'missing') _useOptional = true;
    if (targetSymbol.name == 'present') {
      _useOptional = true;
      return 'Optional.present(${expression(node.arguments.single.value, constantContext: constantContext)})';
    }
    if (targetSymbol.name == 'Ok' || targetSymbol.name == 'Error') {
      _useResult = true;
      final value = expression(node.arguments.single.value,
          constantContext: constantContext);
      final type = model.types[node] ?? 'Result<Object, Object>';
      final inner = type.startsWith('Result<')
          ? type.substring(7, type.length - 1)
          : 'Object, Object';
      final splitAt = inner.indexOf(',');
      final success = inner.substring(0, splitAt).trim();
      final error = inner.substring(splitAt + 1).trim();
      return '${targetSymbol.name}<$success, $error>($value)';
    }
    if (targetSymbol.classDeclaration != null) {
      final fields = targetSymbol.classCase?.fields ??
          [
            ..._inherited(targetSymbol.classDeclaration!),
            ...targetSymbol.classDeclaration!.fields
          ];
      final ctor =
          targetSymbol.classCase?.name ?? targetSymbol.classDeclaration!.name;
      final order = model.argumentOrder[node] ?? const <int>[];
      final parts = <String>[];
      for (var i = 0; i < fields.length && i < order.length; i++) {
        final index = order[i];
        if (index < 0) continue;
        parts.add(
            '${fields[i].name}: ${expression(node.arguments[index].value, constantContext: constantContext)}');
      }
      if (node.arguments.length <= 1) {
        return '$ctor(${parts.join(', ')})';
      }
      final declarations = <String>[];
      final named = <String>[];
      for (var i = 0; i < node.arguments.length; i++) {
        declarations.add(
            'final _qa$i = ${expression(node.arguments[i].value, constantContext: constantContext)};');
      }
      for (var i = 0; i < fields.length && i < order.length; i++) {
        final index = order[i];
        if (index < 0) continue;
        named.add('${fields[i].name}: _qa$index');
      }
      return '(() { ${declarations.join(' ')} return $ctor(${named.join(', ')}); })()';
    }
    final member =
        node.callee is MemberAccess ? node.callee as MemberAccess : null;
    final target = member != null
        ? '${expression(member.object, constantContext: constantContext)}.${member.name}'
        : node.callee is Identifier &&
                model.implicitThis.contains(node.callee as Identifier)
            ? 'this.${targetSymbol.name}'
            : targetSymbol.dartName;
    final parameters = targetSymbol.function?.parameters ?? const <Parameter>[];
    final variadic = parameters.indexWhere((parameter) => parameter.variadic);
    if (variadic >= 0) {
      final order = model.argumentOrder[node] ?? const <int>[];
      final fixed = <String>[];
      for (var i = 0; i < variadic; i++) {
        final index = i < order.length ? order[i] : -1;
        if (index >= 0) {
          fixed.add(expression(node.arguments[index].value,
              constantContext: constantContext));
        }
      }
      final pieces = <String>[];
      for (final index in model.variadicArguments[node] ?? const <int>[]) {
        final value = node.arguments[index].value;
        if (value is SpreadElement) {
          final text =
              expression(value.operand, constantContext: constantContext);
          pieces.add(value.nullAware ? '...?$text' : '...$text');
        } else {
          pieces.add(expression(value, constantContext: constantContext));
        }
      }
      final list =
          '<${_dartType(parameters[variadic].type)}>[${pieces.join(', ')}]';
      return '$target(${[...fixed, list].join(', ')})';
    }
    final order = model.argumentOrder[node];
    final holes = node.arguments.where((a) => _isHole(a.value)).length;
    final simple = holes == 0 &&
        (order == null || !order.contains(-1)) &&
        node.arguments.every((a) => a.name == null);
    if (simple) {
      return '$target(${node.arguments.map((a) => expression(a.value, constantContext: constantContext)).join(', ')})';
    }
    // Evaluate written arguments exactly once, left to right, before arranging
    // them in declaration order for Dart's positional ABI.
    final declarations = <String>[];
    final values = <String>[];
    final holeNames = <String>[];
    final holeTypes = <String>[];
    final subst = <String, String>{};
    for (var i = 0; i < node.arguments.length; i++) {
      if (_isHole(node.arguments[i].value)) continue;
      declarations.add(
          'final _qa$i = ${expression(node.arguments[i].value, constantContext: constantContext)};');
    }
    final arranged = order ?? List.generate(node.arguments.length, (i) => i);
    for (var i = 0; i < arranged.length; i++) {
      final index = arranged[i];
      if (index >= 0 && !_isHole(node.arguments[index].value)) {
        values.add('_qa$index');
        if (i < parameters.length) {
          subst[model.declarations[parameters[i]]!.dartName] = '_qa$index';
        }
      } else if (index >= 0 && _isHole(node.arguments[index].value)) {
        final hole = '_qh${holeNames.length}';
        holeNames.add(hole);
        holeTypes.add(i < parameters.length ? parameters[i].type : 'Object');
        values.add(hole);
      } else if (i < parameters.length && parameters[i].defaultValue != null) {
        final saved = _names;
        _names = subst;
        final value = expression(parameters[i].defaultValue!);
        _names = saved;
        declarations.add('final _qd$i = $value;');
        values.add('_qd$i');
        subst[model.declarations[parameters[i]]!.dartName] = '_qd$i';
      }
    }
    final invocation = '$target(${values.join(', ')})';
    if (holeNames.isNotEmpty) {
      final signature = [
        for (var i = 0; i < holeNames.length; i++)
          '${holeTypes[i]} ${holeNames[i]}'
      ].join(', ');
      return '(($signature) { ${declarations.join(' ')} return $invocation; })';
    }
    return '(() { ${declarations.join(' ')} return $invocation; })()';
  }

  bool _isHole(Expression node) => node is Identifier && node.name == '_';

  bool _containsDoReturn(List<Statement> body) {
    for (final statement in body) {
      if (_doReturns(statement)) return true;
    }
    return false;
  }

  bool _doReturns(Statement node) => switch (node) {
        IfStatement() =>
          node.thenBody.any(_doReturns) || node.elseBody.any(_doReturns),
        ForStatement() => node.body.any(_doReturns),
        WhileStatement() => node.body.any(_doReturns),
        RepeatStatement() => node.body.any(_doReturns),
        CForStatement() => node.body.any(_doReturns),
        LabelStatement() => _doReturns(node.statement),
        MatchStatement() => node.arms.any((arm) => arm.body.any(_doReturns)),
        ExpressionStatement() => node.expression is DoExpression &&
            _containsFunctionReturn((node.expression as DoExpression).body),
        Binding() => node.value is DoExpression &&
            _containsFunctionReturn((node.value as DoExpression).body),
        _ => false,
      };

  bool _containsFunctionReturn(List<Statement> body) {
    for (final statement in body) {
      if (statement is ReturnStatement) return true;
      if (statement is IfStatement &&
          (_containsFunctionReturn(statement.thenBody) ||
              _containsFunctionReturn(statement.elseBody))) {
        return true;
      }
    }
    return false;
  }

  String _captureBlock(void Function() emit) {
    final saved = _redirect;
    final buffer = StringBuffer();
    _redirect = buffer;
    emit();
    _redirect = saved;
    return buffer.toString();
  }

  String _do(DoExpression node) {
    final saved = _inDo;
    _inDo = true;
    final body = _captureBlock(() {
      for (final statement in node.body) {
        this.statement(statement);
      }
    });
    _inDo = saved;
    return '(() {\n$body})()';
  }

  String _capture(CaptureExpression node) {
    final copies = model.captures[node] ?? const [];
    final saved = copies
        .map((copy) =>
            'final ${_dartType(copy.$2.type)} ${copy.$2.dartName} = ${copy.$1.dartName};')
        .join(' ');
    return '(() { $saved return () => (${expression(node.body)}); })()';
  }

  String _convert(ConversionExpression node) {
    _useConversion = true;
    final target = node.type.endsWith('?')
        ? node.type.substring(0, node.type.length - 1)
        : node.type;
    return '_qConvert(${expression(node.operand)}, ${quote(target)}, ${node.safe}) as ${_dartType(node.safe ? (node.type.endsWith('?') ? node.type : '${node.type}?') : node.type)}';
  }

  String _with(WithExpression node) {
    final type = model.types[node.receiver]!;
    final bare = type.endsWith('?') ? type.substring(0, type.length - 1) : type;
    final names = model.shapes[node] ?? node.fields;
    final written = {
      for (var i = 0; i < node.fields.length; i++)
        node.fields[i]: node.values[i]
    };
    final receiver = '_qw${_temps++}';
    final arguments = names.map((name) {
      final value = written[name];
      return value == null
          ? '$name: $receiver.$name'
          : '$name: ${expression(value)}';
    }).join(', ');
    final value = expression(node.receiver);
    final nullable = node.nullAware && type.endsWith('?');
    if (!nullable) {
      return '(() { final $receiver = $value; return $bare($arguments); })()';
    }
    return '(() { final $receiver = $value; if ($receiver != null) return $bare($arguments); return $receiver; })()';
  }

  String _dot(DotShorthand node) {
    final type = model.types[node]!;
    if (node.name == 'new') {
      final arguments = node.arguments ?? const <Argument>[];
      return '$type(${arguments.map((argument) => '${argument.name}: ${expression(argument.value)}').join(', ')})';
    }
    if (model.enumNames.contains(type)) return '$type.${node.name}';
    return '${node.name}()';
  }

  String _list(ListExpression node) {
    final type = model.types[node]!;
    final element = type.substring(5, type.length - 1);
    final parts = <String>[];
    for (var i = 0; i < node.elements.length; i++) {
      final aware = i < node.nullAware.length && node.nullAware[i];
      parts.add(_piece(node.elements[i], element, aware));
    }
    return '<$element>[${parts.join(', ')}]';
  }

  String _pieces(List<Expression> elements, String type) =>
      elements.map((element) => _piece(element, type, false)).join(', ');

  String _piece(Expression element, String type, bool aware) {
    if (element is SpreadElement) {
      final text = expression(element.operand);
      return element.nullAware ? '...?$text' : '...$text';
    }
    if (element is NullAwareElement) {
      return '?(${expression(element.value)})';
    }
    if (element is CollectionIf) {
      final thenList = _pieces(element.thenElements, type);
      final tail = element.elseElements.isEmpty
          ? ''
          : ' else ...<$type>[${_pieces(element.elseElements, type)}]';
      return 'if (${expression(element.condition, opaqueBool: true)}) ...<$type>[$thenList]$tail';
    }
    if (element is CollectionFor) {
      final symbol = model.declarations[element]!;
      return 'for (final ${_dartType(symbol.type)} ${symbol.dartName} in ${expression(element.iterable)}) ...<$type>[${_pieces(element.body, type)}]';
    }
    final text = expression(element);
    return aware ? '?($text)' : text;
  }

  String _set(SetExpression node) {
    final type = model.types[node]!;
    final element = type.substring(4, type.length - 1);
    final parts = <String>[];
    for (var i = 0; i < node.elements.length; i++) {
      final aware = i < node.nullAware.length && node.nullAware[i];
      parts.add(_piece(node.elements[i], element, aware));
    }
    return '<$element>{${parts.join(', ')}}';
  }

  String _unionClass(String type) =>
      'QudsUnion_${type.split(' | ').map((part) => _alt(part.trim())).join('_or_')}';

  String _alt(String type) => type.replaceAll(RegExp(r'[^A-Za-z0-9]'), '_');

  String _unionPattern(String matched, TypedPattern pattern) {
    _unions.add(matched);
    final cls = '${_unionClass(matched)}_${_alt(pattern.type)}';
    if (pattern.name == null) return '$cls()';
    return '$cls(value: final ${model.declarations[pattern]!.dartName})';
  }
