import 'dart:io';
import 'dart:convert';
import 'package:quds_lang/quds_lang.dart';
import 'package:test/test.dart';

void main() {
  test('suspended calls execute as Quds tests', () async {
    final run = await Process.run(Platform.resolvedExecutable,
        ['run', 'bin/quds.dart', 'test', 'test/call_suspension.quds']);
    expect(run.exitCode, 0, reason: '${run.stdout}${run.stderr}');
    expect('${run.stdout}'.split('\n').where((line) => line.startsWith('ok ')),
        hasLength(10));
  });

  test('current ABI rebuilds valid-checksum v8 suspended-call output',
      () async {
    final root = Directory.systemTemp.createTempSync('quds-call-cache-');
    addTearDown(() => root.deleteSync(recursive: true));
    File('${root.path}/pubspec.yaml').writeAsStringSync(
        "name: call_cache\nenvironment:\n  sdk: '>=3.3.0 <4.0.0'\n");
    final input = File('${root.path}/main.quds')
      ..writeAsStringSync('later(value: int) async -> int = value\n'
          'join(first: int, second: int) -> int = first * 10 + second\n'
          'main() async:\n  print join(second: await later(2), first: await later(1))\n');
    final build = await Process.run(Platform.resolvedExecutable,
        ['run', 'bin/quds.dart', 'build', input.path]);
    expect(build.exitCode, 0, reason: '${build.stdout}${build.stderr}');
    const legacy = "// Generated by Quds MVP-0. Do not edit.\n"
        "void main() { print('legacy-v8'); }\n";
    File('${root.path}/.dart_tool/quds/out/main.dart')
        .writeAsStringSync(legacy);
    final cache = Directory('${root.path}/.dart_tool/quds/cache');
    var updated = false;
    for (final file in cache.listSync().whereType<File>()) {
      final saved = jsonDecode(file.readAsStringSync()) as Map<String, dynamic>;
      saved['abi'] = 'provider-defaults-v8';
      final paths = (saved['paths'] as List).cast<String>();
      if (paths.length == 1 && paths.single == input.path) {
        saved['output'] = sha256Hex(utf8.encode(legacy));
        updated = true;
      }
      file.writeAsStringSync(jsonEncode(saved));
    }
    expect(updated, isTrue);
    final run = await Process.run(Platform.resolvedExecutable,
        ['run', 'bin/quds.dart', 'run', input.path]);
    expect(run.exitCode, 0, reason: '${run.stdout}${run.stderr}');
    expect(run.stdout, '12\n');
    for (final file in cache.listSync().whereType<File>()) {
      expect((jsonDecode(file.readAsStringSync()) as Map)['abi'],
          'provider-defaults-v9');
    }
  });

  test('null-aware method result cannot flow into a nonnullable binding', () {
    const source = '''
class Plain:
  read(value: int) -> int = value
main():
  owner: Plain? = null
  result: int = owner?.read(1)
  print result
''';
    expect(
        () => compile(source, file: 'nullable_result.quds'),
        throwsA(isA<CompilerException>().having(
            (error) => error.span.file, 'source', 'nullable_result.quds')));
  });

  test('suspended operands remain illegal outside async functions', () {
    const source = '''
number() async -> int = 1
pair(first: int, second: int) -> int = first + second
main():
  print pair(second: await number(), first: 1)
''';
    expect(
        () => compile(source, file: 'not_async.quds'),
        throwsA(isA<CompilerException>()
            .having((error) => error.span.file, 'source', 'not_async.quds')));
  });

  test('suspended calls analyze and execute equally on VM and JavaScript',
      () async {
    final input = File('test/call_suspension_web.quds').absolute;
    final result = compile(input.readAsStringSync(), file: input.path);
    expect(
        result.dart, compile(input.readAsStringSync(), file: input.path).dart);
    expect(result.dart,
        File('test/goldens/call_suspension.dart.txt').readAsStringSync());
    final root = Directory.systemTemp.createTempSync('quds-call-suspension-');
    addTearDown(() => root.deleteSync(recursive: true));
    final output = File('${root.path}/main.dart')
      ..writeAsStringSync(result.dart);
    writeSdkBundles(root.path, result);
    final provider =
        File('test/fixtures/constructor_packet_regressions/provider.quds')
            .absolute;
    final compiledProvider =
        compile(provider.readAsStringSync(), file: provider.path);
    final target = File(
        '${root.path}/fixtures/constructor_packet_regressions/provider.dart');
    target.parent.createSync(recursive: true);
    target.writeAsStringSync(
        relocateGeneratedLibraries(compiledProvider, '../../').dart);
    writeSdkBundles(root.path, compiledProvider);
    final analysis = await Process.run(Platform.resolvedExecutable,
        ['analyze', '--no-fatal-warnings', output.path, target.path]);
    expect(analysis.exitCode, 0,
        reason: '${analysis.stdout}${analysis.stderr}');
    final vm = await Process.run(Platform.resolvedExecutable, [output.path]);
    expect(vm.exitCode, 0, reason: '${vm.stdout}${vm.stderr}');
    const expected =
        '12\n7\n3\n2132121b\n8\n8\nnull\n9\nrr2\nnull\n3\nrr21\n1\n2\n21\nnull\n12\n2121d\n12\nnull\n9\nrr2\noperand failed\ntrue\n';
    expect(vm.stdout, expected);
    final js = '${root.path}/main.js';
    final build = await Process.run(
        Platform.resolvedExecutable, ['compile', 'js', output.path, '-o', js]);
    expect(build.exitCode, 0, reason: '${build.stdout}${build.stderr}');
    final node = await Process.run('node',
        ['-e', 'globalThis.self = globalThis; require(process.argv[1]);', js]);
    expect(node.exitCode, 0, reason: '${node.stderr}');
    expect(node.stdout, expected);
  }, timeout: const Timeout(Duration(minutes: 2)));
}
