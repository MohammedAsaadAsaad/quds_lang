import 'dart:io';
import 'package:quds_lang/quds_lang.dart';

void main(List<String> arguments) {
  if (arguments.length != 2 ||
      arguments.first != 'build' ||
      !arguments[1].endsWith('.quds')) {
    stderr.writeln('Usage: quds build <input.quds>');
    exitCode = 64;
    return;
  }
  final input = File(arguments[1]);
  try {
    final result = compile(input.readAsStringSync(), file: input.path);
    final output =
        File('${input.path.substring(0, input.path.length - 5)}.dart');
    if (output.existsSync()) {
      final existing = output.readAsStringSync();
      if (!existing.startsWith('// Generated by Quds MVP-0. Do not edit.\n')) {
        stderr.writeln(
            'Refusing to overwrite non-generated file: ${output.path}');
        exitCode = 73;
        return;
      }
    }
    output.writeAsStringSync(result.dart);
    stdout.writeln('Built ${output.path}');
  } on CompilerException catch (error) {
    stderr.writeln(error);
    exitCode = 65;
  } on FileSystemException catch (error) {
    stderr.writeln(error.message);
    exitCode = 74;
  }
}
