  String _resolveType(String type) =>
      model.resolve(type, boundNames: _openGenerics);

  String _dartType(String type) {
    type = substituteBridgeType(type, _interfaceTypeBindings);
    if (type == 'ConversionError') {
      _requireReadonlyRuntime();
      return '$_readonlyRuntime.ConversionError';
    }
    for (final entry in model.moduleSymbols.entries) {
      if (entry.value.namespace != null &&
          _dartImportPrefix(entry.key) != entry.key) {
        type = type.replaceAll(RegExp('\\b${RegExp.escape(entry.key)}\\.'),
            '${_dartImportPrefix(entry.key)}.');
      }
    }
    final resolved = _resolveType(type);
    if (resolved != type) return _dartType(resolved);
    for (final entry in model.backendTypes.entries) {
      final pattern = RegExp('${RegExp.escape(entry.key)}\\b');
      if (!pattern.hasMatch(type)) continue;
      final prefix = entry.value.split('.').first;
      _imports.add("import '${model.backendTypeImports[prefix]}' as $prefix;");
      type = type.replaceAll(pattern, entry.value);
    }
    if (type.startsWith('readonly ')) return _dartType(type.substring(9));
    if (type.contains(' & ') && functionTypeParts(type) == null) {
      return _dartType(type.split(' & ').first.trim());
    }
    if (type.contains(' | ') && functionTypeParts(type) == null)
      return _unionClass(type);
    if (isNullableType(type)) {
      return '${_dartType(nonNullableType(type))}?';
    }
    if (functionTypeParts(type) != null) {
      final (parameters, returns) = _splitFunctionType(type);
      final shapes = functionParameters(parameters);
      if (packetSignature(shapes)) {
        return '${_dartType(returns)} Function(List<Object?>, List<bool>)';
      }
      final parts = <String>[
        for (final p
            in shapes.where((p) => !p.named && !p.optional && !p.variadic))
          _dartType(p.type),
      ];
      final optional =
          shapes.where((p) => !p.named && p.optional && !p.variadic).toList();
      final named = shapes.where((p) => p.named && !p.variadic).toList();
      final variadic = shapes.where((p) => p.variadic).toList();
      if (optional.isNotEmpty)
        parts.add('[${optional.map((p) => _dartType(p.type)).join(', ')}]');
      if (named.isNotEmpty)
        parts.add(
            '{${named.map((p) => '${p.optional ? '' : 'required '}${_dartType(p.type)} ${p.name}').join(', ')}}');
      for (final parameter in variadic) {
        parts.add('List<${_dartType(parameter.type)}>');
      }
      final args = parts.join(', ');
      return '${_dartType(returns)} Function($args)';
    }
    if (type.startsWith('(') && type.endsWith(')')) {
      final fields = splitTypeList(type.substring(1, type.length - 1));
      final rendered = fields.map(_dartType).join(', ');
      return '($rendered${fields.length == 1 ? ',' : ''})';
    }
    if (type.startsWith('Range<')) return 'Iterable<num>';
    final generic = type.indexOf('<');
    if (generic > 0 && type.endsWith('>')) {
      final args = splitTypeList(type.substring(generic + 1, type.length - 1));
      return '${type.substring(0, generic)}<${args.map(_dartType).join(', ')}>';
    }
    return type;
  }

  bool _containsPropagate(List<Statement> body) {
    for (final statement in body) {
      if (_statementPropagates(statement)) return true;
    }
    return false;
  }

  bool _statementPropagates(Statement node) => switch (node) {
        Binding() => _expressionPropagates(node.value),
        ReturnStatement() =>
          node.value != null && _expressionPropagates(node.value!),
        ExpressionStatement() => _expressionPropagates(node.expression),
        IfStatement() => _containsPropagate(node.thenBody) ||
            _containsPropagate(node.elseBody),
        ForStatement() =>
          _containsPropagate(node.body) || _containsPropagate(node.elseBody),
        WhileStatement() => _containsPropagate(node.body) ||
            _containsPropagate(node.elseBody) ||
            _expressionPropagates(node.condition),
        GuardedStatement() => _statementPropagates(node.statement) ||
            _expressionPropagates(node.condition) ||
            (node.alternate != null && _expressionPropagates(node.alternate!)),
        ParallelAssignment() => node.values.any(_expressionPropagates),
        IfCaseStatement() => _containsPropagate(node.body),
        IfLetStatement() => _containsPropagate(node.thenBody) ||
            _containsPropagate(node.elseBody),
        DeferStatement() => _expressionPropagates(node.expression),
        WhenStatement() => _containsPropagate(node.body),
        UsingStatement() => _containsPropagate(node.body),
        IndexAssignment() => _expressionPropagates(node.target) ||
            _expressionPropagates(node.value),
        MemberAssignment() => _expressionPropagates(node.value),
        LabelStatement() => _statementPropagates(node.statement),
        MatchStatement() =>
          node.arms.any((arm) => _containsPropagate(arm.body)),
        _ => false,
      };

  bool _expressionPropagates(Expression node) => switch (node) {
        PropagateExpression() => true,
        UnaryExpression() => _expressionPropagates(node.operand),
        BinaryExpression() =>
          _expressionPropagates(node.left) || _expressionPropagates(node.right),
        SliceExpression() => _expressionPropagates(node.object) ||
            (node.start != null && _expressionPropagates(node.start!)) ||
            (node.end != null && _expressionPropagates(node.end!)),
        ChainComparison() => node.operands.any(_expressionPropagates),
        CallExpression() =>
          node.arguments.any((a) => _expressionPropagates(a.value)),
        AwaitExpression() => _expressionPropagates(node.operand),
        _ => false,
      };

  String _header(ClassDeclaration node) {
    if (node.kind == 'sealedType') return 'sealed class';
    if (node.kind == 'interface') return 'abstract interface class';
    if (node.modifiers.isEmpty) {
      return switch (node.kind) {
        'mixin' => 'mixin',
        'mixinClass' => 'mixin class',
        'sealed' => 'sealed class',
        _ => 'class',
      };
    }
    final parts = <String>[];
    if (node.modifiers.contains('abstract')) parts.add('abstract');
    for (final word in ['base', 'interface', 'final', 'sealed', 'mixin']) {
      if (node.modifiers.contains(word)) parts.add(word);
    }
    if (node.kind != 'mixin') parts.add('class');
    return parts.join(' ');
  }

  void emitClass(ClassDeclaration node) {
    _span = node.span;
    if (node.kind == 'enum') {
      final values = node.cases.map((item) => item.name).join(', ');
      line('enum ${node.name} { $values }');
      return;
    }
    if (node.kind == 'extensionType') {
      final field = node.fields.single;
      final wrapped = _dartType(field.type);
      if (node.requirements.isEmpty) {
        line('extension type const ${node.name}($wrapped value) {');
      } else {
        line('extension type const ${node.name}._($wrapped value) {');
        final checks = node.requirements
            .map((item) =>
                'if (!(${expression(item)})) throw ArgumentError(\'require failed\');')
            .join(' ');
        line(
            '  factory ${node.name}($wrapped value) { $checks return ${node.name}._(value); }');
      }
      _depth++;
      for (final method in node.methods) {
        emitFunction(method);
      }
      _depth--;
      line('}');
      return;
    }
    if (node.kind == 'interface') {
      if (supportsReadonlyClass(model, node)) _requireReadonlyRuntime();
      line(
          'abstract interface class ${node.name}${_typeParameters(node.typeParameters)}${node.superclass == null ? '' : ' implements ${_dartType(node.superclass!)}'} {');
      _depth++;
      if (supportsReadonlyClass(model, node)) {
        line(
            'Object \$qudsReadonlyView(Map<Type, $_readonlyRuntime.ReadonlyGuard<dynamic>> guards);');
        line('bool \$qudsIsLazySlot(Object slot);');
      }
      for (final field in node.fields) {
        line('${_dartType(field.type)} get ${field.name};');
      }
      for (final property in node.properties) {
        final type = _dartType(property.type);
        if (property.getter != null || property.getterBody != null) {
          line('$type get ${property.name};');
        }
        if (property.setterBody != null)
          line('set ${property.name}($type value);');
      }
      final savedGenerics = _openGenerics;
      _openGenerics = {
        ...savedGenerics,
        ...node.typeParameters.map((p) => p.name)
      };
      for (final method in node.methods) {
        emitFunction(method);
      }
      _openGenerics = savedGenerics;
      _depth--;
      line('}');
      return;
    }
    final header = _header(node);
    final tail = [
      if (node.onType != null) 'on ${node.onType}',
      if (node.superclass != null) 'extends ${_dartType(node.superclass!)}',
      if (node.mixins.isNotEmpty) 'with ${node.mixins.join(', ')}',
      if (node.interfaces.isNotEmpty)
        'implements ${node.interfaces.join(', ')}',
    ].join(' ');
    if (node.kind == 'sealedType') {
      line('$header ${node.name} {');
      line('  const ${node.name}();');
      line('}');
      for (final item in node.cases) {
        final parameters = item.fields
            .map((field) => 'required this.${field.name}')
            .join(', ');
        final constructor = parameters.isEmpty
            ? 'const ${item.name}();'
            : 'const ${item.name}({$parameters});';
        line('class ${item.name} extends ${node.name} {');
        line('  $constructor');
        for (final field in item.fields) {
          line('  final ${field.type} ${field.name};');
        }
        line('}');
      }
      return;
    }
    for (final note in node.annotations) {
      _emitMetadata(note);
    }
    line(
        '$header ${node.name}${_typeParameters(node.typeParameters)}${tail.isEmpty ? '' : ' $tail'} {');
    _depth++;
    final savedClassGenerics = _openGenerics;
    _openGenerics = {
      ...savedClassGenerics,
      for (final parameter in node.typeParameters) parameter.name,
    };
    if (node.kind == 'mixin') {
      for (final field in node.fields) {
        if (field.lazyBody != null) _emitLazy(field);
      }
      for (final property in node.properties) {
        _emitProperty(property);
      }
      for (final method in node.methods) {
        emitFunction(method);
      }
      _depth--;
      line('}');
      _openGenerics = savedClassGenerics;
      return;
    }
    final inherited = _inherited(node);
    final parentConstructor =
        node.constructors.isEmpty ? _synthesizedParentConstructor(node) : null;
    if (node.modifiers.contains('singleton')) {
      line('${node.name}._();');
      line('static ${node.name}? _instance;');
      line(
          'static ${node.name} get instance => _instance ??= ${node.name}._();');
    } else if (parentConstructor != null) {
      _emitSynthesizedParentConstructor(node, parentConstructor);
    } else if (node.constructors.isEmpty) {
      final initializers = <String>[];
      final params = <String>[
        ...inherited
            .where((field) => !field.isStatic && field.lazyBody == null)
            .map((field) {
          final required = field.requiredField && field.initializer == null
              ? 'required '
              : '';
          return '$required super.${field.name}';
        }),
        for (final field in node.fields.where((field) =>
            !field.isStatic && !field.isEvent && field.lazyBody == null))
          _constructorParameter(field, initializers),
      ];
      final tail = initializers.isEmpty ? '' : ' : ${initializers.join(', ')}';
      final list = params.join(', ');
      line(list.isEmpty
          ? '${node.name}()$tail;'
          : '${node.name}({$list})$tail;');
    } else {
      for (final constructor in node.constructors) {
        _emitConstructor(node, constructor);
      }
    }
    for (final field in node.fields) {
      if (field.lazyBody != null) {
        _emitLazy(field);
        continue;
      }
      if (field.isStatic) {
        final declared = model.declarations[field]?.type ?? field.type;
        final initial = field.initializer == null
            ? ''
            : ' = ${expression(field.initializer!)}';
        final kind = field.isConst
            ? 'static const'
            : field.mutable
                ? 'static'
                : 'static final';
        line('$kind ${_dartType(declared)} ${field.name}$initial;');
        continue;
      }
      if (field.isEvent) {
        _requireReadonlyRuntime();
        final payload =
            field.type.startsWith('Event<') && field.type.endsWith('>')
                ? field.type.substring(6, field.type.length - 1)
                : '() -> void';
        final dart = _dartType(payload);
        line(
            'final $_readonlyRuntime.QudsEvent<$dart> ${_fieldDart(field)} = $_readonlyRuntime.QudsEvent<$dart>();');
        continue;
      }
      _markProtected(field.visibility);
      final modifier = field.mutable ? '' : 'final ';
      final initializedByConstructor = node.constructors.isEmpty ||
          node.constructors.any((constructor) => constructor.parameters.any(
              (parameter) =>
                  parameter.initializing == 'this' &&
                  parameter.name == field.name));
      final copied =
          (node.kind == 'value' || node.modifiers.contains('value')) &&
              node.fields.any((item) => !item.isStatic);
      final initial = field.initializer != null &&
              !copied &&
              (node.modifiers.contains('singleton') ||
                  !initializedByConstructor)
          ? ' = ${expression(field.initializer!)}'
          : '';
      line('$modifier${_dartType(field.type)} ${_fieldDart(field)}$initial;');
    }
    final savedInstanceGuards = _guardEnvironment;
    _guardEnvironment =
        '$_readonlyRuntime.guardsOf([...$_knownGuardsName.values, ...$_readonlyRuntime.guardsFor(this).values])';
    for (final property in node.properties) {
      _emitProperty(property);
    }
    for (final method in node.methods) {
      if (hasAnnotation(node.annotations, 'macro') && method.name == 'define') {
        continue;
      }
      emitFunction(method);
    }
    _emitInterfaceForwarders(node);
    _guardEnvironment = savedInstanceGuards;
    final valueFields = node.fields
        .where((field) =>
            !field.isStatic && !field.isEvent && field.lazyBody == null)
        .toList();
    if ((node.kind == 'value' || node.modifiers.contains('value')) &&
        valueFields.isNotEmpty) {
      _emitCopyWith(node, valueFields);
    }
    if (node.kind == 'value' || node.modifiers.contains('value')) {
      _requireReadonlyRuntime();
      final names = valueFields.map(_fieldDart).join(', ');
      if (!node.methods
          .any((method) => method.isOperator && method.name == '==')) {
        line('@override');
        line(
            'bool operator ==(Object other) => other is ${node.name} && $_readonlyRuntime.valueEquals(this, other, <Object?>[$names], <Object?>[${valueFields.map((field) => 'other.${_fieldDart(field)}').join(', ')}]);');
      }
      line('@override');
      line(
          'int get hashCode => $_readonlyRuntime.valueHash(this, <Object?>[$names]);');
    }
    if (supportsReadonlyClass(model, node)) _emitReadonlyDispatch(node);
    _emitConstructorBridges(node);
    _depth--;
    line('}');
    if (supportsReadonlyClass(model, node)) _emitReadonlyProxy(node);
    if (model.reflectable.contains(node)) {
      final fields = node.fields
          .where((field) => field.visibility != 'private')
          .map((field) => "'${field.name}'")
          .join(', ');
      final private = node.fields
          .where((field) => field.visibility == 'private')
          .map((field) => "'${field.name}'")
          .join(', ');
      final parameters = node.typeParameters
          .map((parameter) => "'${parameter.name}'")
          .join(', ');
      line(
          'const qudsReflect${node.name} = <String, Object?>{\'name\': \'${node.name}\', \'fields\': <String>[$fields], \'private\': <String>[$private], \'typeParameters\': <String>[$parameters]};');
    }
    _openGenerics = savedClassGenerics;
  }

  void _emitReflectableRegistry(Program program) {
    final nodes = [
      for (final node in program.statements)
        if (node is ClassDeclaration && model.reflectable.contains(node)) node
    ];
    if (nodes.isEmpty) return;
    final names = nodes.map((node) => 'qudsReflect${node.name}').join(', ');
    line('const qudsReflectable = <Object?>[$names];');
  }

  String _typeParameters(List<TypeParameter> parameters,
      [List<String> extra = const []]) {
    final saved = _openGenerics;
    _openGenerics = {..._openGenerics, for (final p in parameters) p.name};
    try {
      final body = [
        for (final parameter in parameters)
          '${parameter.name}${parameter.bound == null ? '' : ' extends ${_dartType(parameter.bound!)}'}',
        ...extra,
      ];
      if (body.isEmpty) return '';
      return '<${body.join(', ')}>';
    } finally {
      _openGenerics = saved;
    }
  }

  List<String> _intersectionChecks(FunctionDeclaration node) {
    final checks = <String>[];
    for (final parameter in node.parameters) {
      final type = model.declarations[parameter]?.type ?? parameter.type;
      if (!type.contains(' & ')) continue;
      final dart = model.declarations[parameter]!.dartName;
      for (final part in type.split(' & ').skip(1)) {
        checks.add(
            'if ($dart is! ${_dartType(part.trim())}) throw ArgumentError(\'intersection\');');
      }
    }
    return checks;
  }

  String _fieldDart(FieldDeclaration field) =>
      field.visibility == 'private' && !field.name.startsWith('_')
          ? '_${field.name}'
          : field.name;

  ConstructorDeclaration? _synthesizedParentConstructor(ClassDeclaration node) {
    final parentName = node.superclass;
    if (parentName == null) return null;
    final parent = _classes[_genericHead(parentName)];
    if (parent == null || parent.kind == 'interface') return null;
    final unnamed = parent.constructors
        .where(
            (constructor) => constructor.name == null && !constructor.factory)
        .toList();
    if (unnamed.length != 1) return null;
    final constructor = unnamed.single;
    if (constructor.parameters.any((parameter) => parameter.variadic)) {
      return null;
    }
    final names =
        constructor.parameters.map((parameter) => parameter.name).toSet();
    if (node.fields.any((field) =>
        !field.isStatic && !field.isEvent && names.contains(field.name))) {
      return null;
    }
    return constructor;
  }

  void _emitSynthesizedParentConstructor(
      ClassDeclaration node, ConstructorDeclaration parent) {
    final owner = _classes[_genericHead(node.superclass!)];
    final substitution = <String, String>{};
    final spec = node.superclass!;
    final open = spec.indexOf('<');
    if (owner != null &&
        open > 0 &&
        spec.endsWith('>') &&
        owner.typeParameters.isNotEmpty) {
      final args = splitTypeList(spec.substring(open + 1, spec.length - 1));
      if (args.length == owner.typeParameters.length) {
        for (var i = 0; i < args.length; i++) {
          substitution[owner.typeParameters[i].name] = args[i];
        }
      }
    }
    final foreign = _foreignParentDefaults(node, parent);
    final names = <String>[];
    final arguments = <String>[];
    for (final parameter in parent.parameters) {
      final declared = parameter.initializing.isEmpty
          ? model.declarations[parameter]?.type ?? parameter.type
          : (owner?.fields
                  .where((field) => field.name == parameter.name)
                  .firstOrNull
                  ?.type ??
              parameter.type);
      final type = _dartType(substituteBridgeType(declared, substitution));
      final hidden = foreign &&
          parameter.defaultValue != null &&
          parameter.defaultValue is! Literal;
      final required = hidden ||
              parameter.defaultValue == null &&
                  parameter.kind != ParameterKind.optionalPositional
          ? 'required '
          : '';
      final value = parameter.defaultValue == null || hidden
          ? ''
          : ' = ${expression(parameter.defaultValue!)}';
      names.add('$required$type ${parameter.name}$value');
      arguments.add(parameter.name);
    }
    final initializers = <String>[];
    for (final field in node.fields.where((field) =>
        !field.isStatic && !field.isEvent && field.lazyBody == null)) {
      names.add(_constructorParameter(field, initializers));
    }
    if (arguments.isNotEmpty) {
      initializers.insert(0, 'super(${arguments.join(', ')})');
    }
    final tail = initializers.isEmpty ? '' : ' : ${initializers.join(', ')}';
    final list = names.join(', ');
    line(list.isEmpty ? '${node.name}()$tail;' : '${node.name}({$list})$tail;');
    if (foreign)
      _emitSynthesizedParentBridge(node, parent, owner, substitution);
  }

  bool _foreignParentDefaults(
      ClassDeclaration node, ConstructorDeclaration parent) {
    final owner = _classes[_genericHead(node.superclass!)];
    final parentHome = owner == null ? '' : model.libraryOf[owner] ?? '';
    final home = model.libraryOf[node] ?? '';
    if (parentHome.isEmpty || parentHome == home) return false;
    return parent.parameters.any((parameter) =>
        parameter.defaultValue != null && parameter.defaultValue is! Literal);
  }

  void _emitSynthesizedParentBridge(
      ClassDeclaration node,
      ConstructorDeclaration parent,
      ClassDeclaration? owner,
      Map<String, String> substitution) {
    final rendered = _dartType(node.superclass!);
    final open = rendered.indexOf('<');
    final parentOwner = open < 0 ? rendered : rendered.substring(0, open);
    final parentSuffix = open < 0 ? '' : rendered.substring(open);
    final slots =
        owner == null ? '' : providerConstructorSlotsName(owner, parent);
    final bridge = providerSynthesizedConstructorBridgeName(node);
    final generics = _typeParameters(node.typeParameters, const []);
    final saved = _names;
    _names = {..._names};
    final statements = <String>[];
    final arguments = <String>[];
    try {
      statements.add(
          'final \$qParent = $parentOwner.$slots$parentSuffix(\$qInputs, \$qPresent);');
      for (var i = 0; i < parent.parameters.length; i++) {
        final parameter = parent.parameters[i];
        final declared = parameter.initializing.isEmpty
            ? model.declarations[parameter]?.type ?? parameter.type
            : (owner?.fields
                    .where((field) => field.name == parameter.name)
                    .firstOrNull
                    ?.type ??
                parameter.type);
        final type = _dartType(substituteBridgeType(declared, substitution));
        arguments.add('${parameter.name}: \$qParent[$i] as $type');
      }
      final fields = node.fields
          .where((field) =>
              !field.isStatic && !field.isEvent && field.lazyBody == null)
          .toList();
      for (var i = 0; i < fields.length; i++) {
        final field = fields[i];
        final index = parent.parameters.length + i;
        final type = _dartType(field.type);
        final input = '\$qInputs[$index]';
        final fallback = field.initializer == null
            ? "throw StateError('missing')"
            : expression(field.initializer!);
        final slot = '_qchild$i';
        statements.add(
            'final $type $slot = \$qPresent[$index] ? $input as $type : $fallback;');
        arguments.add('${field.name}: $slot');
      }
    } finally {
      _names = saved;
    }
    final returned = node.typeParameters.isEmpty
        ? node.name
        : '${node.name}<${node.typeParameters.map((p) => p.name).join(', ')}>';
    line('static $returned $bridge$generics'
        '(List<Object?> \$qInputs, List<bool> \$qPresent) '
        '{ ${statements.join(' ')} return ${node.name}(${arguments.join(', ')}); }');
  }

  void _emitConstructorBridges(ClassDeclaration node) {
    final savedOpen = _openGenerics;
    _openGenerics = {
      ..._openGenerics,
      for (final parameter in node.typeParameters) parameter.name
    };
    try {
      _emitConstructorBridgeBodies(node);
    } finally {
      _openGenerics = savedOpen;
    }
  }

  void _emitConstructorBridgeBodies(ClassDeclaration node) {
    for (final constructor in node.constructors) {
      if (constructor.factory ||
          constructor.parameters.every((parameter) =>
              parameter.defaultValue == null ||
              parameter.defaultValue is Literal)) {
        continue;
      }
      final symbolType = model.declarations[node]?.type ?? node.name;
      final returned = node.typeParameters.isEmpty
          ? node.name
          : '${node.name}<${node.typeParameters.map((p) => p.name).join(', ')}>';
      final name = providerConstructorBridgeName(node, constructor);
      final generics = _typeParameters(node.typeParameters, const []);
      final saved = _names;
      _names = {..._names};
      final statements = <String>[];
      final arguments = <String>[];
      final casts = <String>[];
      try {
        for (var i = 0; i < constructor.parameters.length; i++) {
          final parameter = constructor.parameters[i];
          final declared =
              model.declarations[parameter]?.type ?? parameter.type;
          final dartType = _dartType(declared == '<field>'
              ? node.fields
                      .where((field) => field.name == parameter.name)
                      .firstOrNull
                      ?.type ??
                  symbolType
              : declared);
          final input = '\$qInputs[$i]';
          final supplied =
              '\$qPresent[$i] ? $input as $dartType : ${parameter.defaultValue == null ? 'null as $dartType' : expression(parameter.defaultValue!)}';
          final slot = '_qctor$i';
          statements.add('final $dartType $slot = $supplied;');
          arguments.add(slot);
          casts.add('\$qSlots[$i] as $dartType');
        }
      } finally {
        _names = saved;
      }
      final ctor = constructor.name == null
          ? node.name
          : '${node.name}.${constructor.name}';
      final applied = node.typeParameters.isEmpty
          ? ''
          : '<${node.typeParameters.map((p) => p.name).join(', ')}>';
      final slots = providerConstructorSlotsName(node, constructor);
      line('static List<Object?> $slots$generics'
          '(List<Object?> \$qInputs, List<bool> \$qPresent) '
          '{ ${statements.join(' ')} return <Object?>[${arguments.join(', ')}]; }');
      line('static $returned $name$generics'
          '(List<Object?> \$qInputs, List<bool> \$qPresent) '
          '{ final \$qSlots = $slots$generics(\$qInputs, \$qPresent); '
          'return $ctor$applied(${casts.join(', ')}); }');
    }
  }

  String _constructorParameter(
      FieldDeclaration field, List<String> initializers) {
    final initializer = field.initializer;
    if (initializer != null && initializer is! Literal) {
      // Collection and call defaults run afresh for every construction. A
      // sentinel also keeps an explicit nullable value distinct from omission.
      _useOptional = true;
      final type = _dartType(field.type);
      initializers.add(
          '${_fieldDart(field)} = identical(${field.name}, missing) ? ${expression(initializer)} : ${field.name} as $type');
      return 'Object? ${field.name} = missing';
    }
    final required =
        field.requiredField && field.initializer == null ? 'required ' : '';
    final value =
        field.initializer == null ? '' : ' = ${expression(field.initializer!)}';
    if (field.visibility == 'private') {
      initializers.add('${_fieldDart(field)} = ${field.name}');
      return '$required${_dartType(field.type)} ${field.name}$value';
    }
    return '${required}this.${field.name}$value';
  }

  void _emitConstructor(
      ClassDeclaration type, ConstructorDeclaration constructor) {
    final parentName = type.superclass;
    final parent =
        parentName == null ? null : _classes[_genericHead(parentName)];
    final namedSuper = parent != null && parent.constructors.isEmpty;
    final params = constructor.parameters.map((parameter) {
      final declared = model.declarations[parameter]!;
      if (parameter.initializing == 'this') {
        final field = type.fields
            .where((item) => item.name == parameter.name)
            .firstOrNull;
        if (field != null && field.visibility == 'private') {
          return '${_dartType(declared.type)} ${parameter.name}';
        }
        return 'this.${parameter.name}';
      }
      if (parameter.initializing == 'super' && !namedSuper)
        return 'super.${parameter.name}';
      return '${_dartType(declared.type)} ${declared.dartName}';
    }).join(', ');
    final private = constructor.parameters.where((parameter) {
      if (parameter.initializing != 'this') return false;
      final field =
          type.fields.where((item) => item.name == parameter.name).firstOrNull;
      return field != null && field.visibility == 'private';
    });
    final lifted = _liftedFields(type, constructor);
    final inits = [
      ...private.map((parameter) => '_${parameter.name} = ${parameter.name}'),
      ..._copyInitializers(type, constructor),
      for (final binding in lifted)
        '${model.references[binding]!.dartName} = ${expression(binding.value)}',
      if (namedSuper)
        'super(${constructor.parameters.where((p) => p.initializing == 'super').map((p) => '${p.name}: ${model.declarations[p]!.dartName}').join(', ')})',
    ];
    final tail = inits.isEmpty ? '' : ' : ${inits.join(', ')}';
    final prefix = '${constructor.constant ? 'const ' : ''}'
        '${constructor.factory ? 'factory ' : ''}';
    final name = constructor.name == null
        ? type.name
        : '${type.name}.${constructor.name}';
    if (constructor.constant &&
        constructor.body == null &&
        constructor.expressionBody == null) {
      line('$prefix$name($params)$tail;');
      return;
    }
    if (constructor.expressionBody case final value?) {
      if (constructor.factory) {
        line('$prefix$name($params) => ${expression(value)};');
      } else if (value is Identifier) {
        line('$prefix$name($params) : this.${value.name};');
      } else {
        line('$prefix$name($params) => ${expression(value)};');
      }
      return;
    }
    line('$prefix$name($params)$tail {');
    _depth++;
    final saved = _skipBindings;
    _skipBindings = {...lifted};
    statements(constructor.body!);
    _skipBindings = saved;
    _depth--;
    line('}');
  }

  List<Binding> _liftedFields(
      ClassDeclaration type, ConstructorDeclaration constructor) {
    final body = constructor.body;
    if (body == null || constructor.factory) return const [];
    final lifted = <Binding>[];
    for (final statement in body) {
      if (statement is! Binding || !model.assignments.contains(statement)) {
        continue;
      }
      final symbol = model.references[statement];
      final field = type.fields
          .where((item) => item.name == statement.name && !item.isStatic)
          .firstOrNull;
      if (symbol == null || !symbol.field || field == null || field.mutable) {
        continue;
      }
      lifted.add(statement);
    }
    return lifted;
  }

  void _hoistOnce(List<Statement>? body) {
    if (body == null) return;
    final found = <OnceStatement>[];
    for (final statement in body) {
      walkAst(statement, (node) {
        if (node is OnceStatement) found.add(node);
      }, skipChildren: (node) => node is FunctionDeclaration || node is Lambda);
    }
    for (final once in found) {
      final flag = '_qo${_temps++}';
      _onceFlags[once] = flag;
      line('var $flag = false;');
    }
  }

  String _lazySlotName(FieldDeclaration field) => r'_$qudsLazy_' + field.name;

  void _emitLazy(FieldDeclaration field) {
    if (field.isStatic) {
      _emitLegacyLazy(field);
      return;
    }
    _requireReadonlyRuntime();
    final declared = model.declarations[field]?.type ?? field.type;
    final slot = _lazySlotName(field);
    line(
        'final $_readonlyRuntime.LazySlot<${_dartType(declared)}> $slot = $_readonlyRuntime.LazySlot<${_dartType(declared)}>();');
    line(
        '${_dartType(declared)} get ${_fieldDart(field)} => $slot.mutableValue(() {');
    _depth++;
    _hoistOnce(field.lazyBody);
    statements(field.lazyBody!);
    _depth--;
    line('});');
  }

  void _emitLegacyLazy(FieldDeclaration field) {
    final declared = model.declarations[field]?.type ?? field.type;
    final dartType = _dartType(declared);
    final store = '_ql${_temps++}';
    final ready = '_qr${_temps++}';
    final prefix = field.isStatic ? 'static ' : '';
    final nullable =
        declared.endsWith('?') || declared == 'dynamic' || declared == 'Null';
    final storeType = nullable ? dartType : '$dartType?';
    _markProtected(field.visibility);
    line('$prefix$storeType $store;');
    line('${prefix}var $ready = false;');
    line('$prefix$dartType get ${_fieldDart(field)} {');
    _depth++;
    line('if (!$ready) {');
    _depth++;
    line('$store = () {');
    _depth++;
    _hoistOnce(field.lazyBody);
    statements(field.lazyBody!);
    _depth--;
    line('}();');
    line('$ready = true;');
    _depth--;
    line('}');
    line('return ${nullable ? store : '$store!'};');
    _depth--;
    line('}');
  }

  void _emitProperty(PropertyDeclaration node) {
    final dart = node.visibility == 'private' && !node.name.startsWith('_')
        ? '_${node.name}'
        : node.name;
    _markProtected(node.visibility);
    if (node.getter != null) {
      line('${_dartType(node.type)} get $dart => ${expression(node.getter!)};');
    } else if (node.getterBody != null) {
      line('${_dartType(node.type)} get $dart {');
      _depth++;
      statements(node.getterBody!);
      _depth--;
      line('}');
    }
    if (node.setterBody != null) {
      final param = node.setter ?? 'value';
      line('set $dart(${_dartType(node.type)} $param) {');
      _depth++;
      statements(node.setterBody!);
      _depth--;
      line('}');
    }
  }

  List<String> _copyInitializers(
      ClassDeclaration type, ConstructorDeclaration constructor) {
    if (constructor.factory || constructor.expressionBody != null) {
      return const [];
    }
    if (type.kind != 'value' && !type.modifiers.contains('value')) {
      return const [];
    }
    final inits = <String>[];
    for (final field in type.fields) {
      if (field.isStatic || field.initializer == null) continue;
      final formal = constructor.parameters.any((parameter) =>
          parameter.initializing == 'this' && parameter.name == field.name);
      if (formal || _bodyAssigns(constructor.body, field.name)) continue;
      inits.add('${_fieldDart(field)} = ${expression(field.initializer!)}');
    }
    return inits;
  }

  bool _bodyAssigns(List<Statement>? body, String name) {
    if (body == null) return false;
    for (final statement in body) {
      if (_statementAssigns(statement, name)) return true;
    }
    return false;
  }

  bool _statementAssigns(Statement node, String name) {
    switch (node) {
      case Binding():
        return node.name == name && model.assignments.contains(node);
      case MemberAssignment():
        return node.name == name && node.object is ThisExpression;
      case IfStatement():
        return _bodyAssigns(node.thenBody, name) ||
            _bodyAssigns(node.elseBody, name);
      case ForStatement():
        return _bodyAssigns(node.body, name) ||
            _bodyAssigns(node.elseBody, name);
      case WhileStatement():
        return _bodyAssigns(node.body, name) ||
            _bodyAssigns(node.elseBody, name);
      case GuardedStatement():
        return _statementAssigns(node.statement, name);
      case UsingStatement():
        return _bodyAssigns(node.body, name);
      case LabelStatement():
        return _statementAssigns(node.statement, name);
      default:
        return false;
    }
  }

  void _emitAnnotation(AnnotationDeclaration node) {
    final params = node.parameters.map((parameter) {
      final required = parameter.defaultValue == null ? 'required ' : '';
      final value = parameter.defaultValue == null
          ? ''
          : ' = ${expression(parameter.defaultValue!)}';
      return '$required this.${parameter.name}$value';
    }).join(', ');
    line('class ${node.name} {');
    _depth++;
    line(params.isEmpty
        ? 'const ${node.name}();'
        : 'const ${node.name}({$params});');
    for (final parameter in node.parameters) {
      line('final ${_dartType(parameter.type)} ${parameter.name};');
    }
    _depth--;
    line('}');
  }

  void _emitMetadata(Metadata note) {
    if (!model.annotations.contains(note.name)) return;
    if (note.arguments.isEmpty) {
      line('@${note.name}()');
      return;
    }
    final args = note.arguments
        .map((argument) => '${argument.name}: ${expression(argument.value)}')
        .join(', ');
    line('@${note.name}($args)');
  }

  void _emitCopyWith(ClassDeclaration node, List<FieldDeclaration> fields,
      {bool readonlyResult = false}) {
    _useOptional = true;
    final params = fields.map((field) {
      if (field.visibility == 'private') {
        return 'required ${_dartType(field.type)} ${field.name}';
      }
      return 'required this.${_fieldDart(field)}';
    }).join(', ');
    final private = fields.where((field) => field.visibility == 'private');
    final tail = private.isEmpty
        ? ''
        : ' : ${private.map((field) => '${_fieldDart(field)} = ${field.name}').join(', ')}';
    if (!readonlyResult) line('${node.name}._qudsCopy({$params})$tail;');
    final copy =
        fields.map((field) => 'Object? ${field.name} = missing').join(', ');
    final type = _readonlyInstanceType(node);
    line('$type copyWith({$copy}) {');
    _depth++;
    String argument(FieldDeclaration field) {
      final cast = _dartType(field.type);
      return 'identical(${field.name}, missing) ? this.${_fieldDart(field)} : ${field.name} as $cast';
    }

    final args =
        fields.map((field) => '${field.name}: ${argument(field)}').join(', ');
    final created = '$type._qudsCopy($args)';
    line(
        'return ${readonlyResult ? '${_guardDescriptor(type)}.protect($created)' : created};');
    _depth--;
    line('}');
  }

  List<FieldDeclaration> _inherited(ClassDeclaration node) =>
      (model.classFields[node] ?? const <FieldDeclaration>[])
          .where((field) =>
              !node.fields.contains(field) &&
              !field.isStatic &&
              !field.isEvent &&
              field.lazyBody == null)
          .toList();

  void emitExtension(ExtensionDeclaration node) {
    _span = node.span;
    final savedGenerics = _openGenerics;
    _openGenerics = {
      ..._openGenerics,
      ...node.typeParameters.map((p) => p.name)
    };
    final generics = _typeParameters(node.typeParameters);
    final title = node.name == null
        ? 'extension$generics'
        : 'extension ${node.name}$generics';
    line('$title on ${_dartType(node.target)} {');
    _depth++;
    for (final property in node.properties) {
      _emitProperty(property);
    }
    for (final method in node.methods) {
      emitFunction(method);
    }
    _depth--;
    line('}');
    _openGenerics = savedGenerics;
  }

  void statement(Statement node) {
    _span = node.span;
    switch (node) {
      case Binding():
        if (model.assignments.contains(node)) {
          if (_skipBindings.contains(node)) break;
          final symbol = model.references[node]!;
          final target =
              symbol.field ? 'this.${symbol.dartName}' : _cell(symbol);
          line('$target ${node.operator} ${expression(node.value)};');
        } else {
          final symbol = model.declarations[node]!;
          if (symbol.reactive == 'state' || symbol.reactive == 'computed') {
            final computed = symbol.reactive == 'computed';
            if (computed) {
              _useComputed = true;
            } else {
              _useState = true;
            }
            final wrapper = computed ? '_QudsComputed' : '_QudsState';
            final type = _dartType(symbol.type);
            if (computed) {
              line('late $wrapper<$type> ${symbol.dartName};');
              line(
                  '${symbol.dartName} = $wrapper<$type>(() => ${expression(node.value)});');
            } else {
              line(
                  'final ${symbol.dartName} = $wrapper<$type>(${expression(node.value)});');
            }
            return;
          }
          final modifier = symbol.late
              ? (symbol.mutable ? 'late ' : 'late final ')
              : symbol.constant
                  ? 'const '
                  : symbol.mutable
                      ? ''
                      : 'final ';
          if (node.open) {
            line('$modifier${_dartType(symbol.type)} ${symbol.dartName};');
            return;
          }
          if (symbol.constant) {
            _constNames.add(symbol.dartName);
            if (_depth == 0) _topLevelConsts.add(symbol.dartName);
          }
          final initializer =
              expression(node.value, constantContext: symbol.constant);
          final declared = symbol.type == 'dynamic'
              ? (_externalConstructor(node.value) ?? _dartType(symbol.type))
              : _dartType(symbol.type);
          line('$modifier$declared ${symbol.dartName} = $initializer;');
        }
      case ReturnStatement():
        if (_inDo) {
          _useReturn = true;
          line(node.value == null
              ? 'throw _QudsReturn(null);'
              : 'throw _QudsReturn(${_wrapReturn(expression(node.value!))});');
        } else {
          line(node.value == null
              ? 'return;'
              : 'return ${_wrapReturn(expression(node.value!))};');
        }
      case ResultStatement():
        line('return ${expression(node.value)};');
      case CForStatement():
        _beginLoop(node.elseBody);
        final init = node.init as Binding;
        final symbol = model.declarations[init]!;
        final step = node.step == null ? '' : _runtimeStep(node.step!);
        final keyword = symbol.mutable ? '' : 'final ';
        line(
            'for ($keyword${_dartType(symbol.type)} ${symbol.dartName} = ${expression(init.value)}; ${expression(node.condition)}; $step) {');
        _depth++;
        statements(node.body);
        _depth--;
        line('}');
        _endLoop(node.elseBody);
      case TryStatement():
        _emitTry(node);
      case ThrowStatement():
        line('throw ${expression(node.value)};');
      case RethrowStatement():
        line('rethrow;');
      case YieldStatement():
        final value = expression(node.value);
        final guarded = node.star && _returnView != null
            ? '($value).map((_qy) => ${_wrapReturn('_qy')})'
            : _wrapReturn(value);
        line('${node.star ? 'yield*' : 'yield'} $guarded;');
      case WatchStatement():
        _useState = true;
        _useWatch = true;
        line('${_watchList}.add(_qWatch(() {');
        _depth++;
        line(
            '(() { final watched = ${expression(node.value)}; return watched; })();');
        statements(node.body);
        _depth--;
        line('}));');
      case OnceStatement():
        final flag = _onceFlags[node]!;
        line('if (!$flag) {');
        _depth++;
        line('$flag = true;');
        statements(node.body);
        _depth--;
        line('}');
      case BatchStatement():
        _useState = true;
        _useBatch = true;
        line('_qBatch(() {');
        _depth++;
        statements(node.body);
        _depth--;
        line('});');
      case RepeatStatement():
        _beginLoop(node.elseBody);
        if (node.count != null) {
          final count = '_qn${_temps++}';
          final index = '_qi${_temps++}';
          line('{');
          _depth++;
          line('final $count = ${expression(node.count!)};');
          line(
              'if ($count < 0) throw RangeError.range($count, 0, null, "count");');
          line('for (var $index = 0; $index < $count; $index = $index + 1) {');
          _depth++;
          statements(node.body);
          _depth--;
          line('}');
          _depth--;
          line('}');
          _endLoop(node.elseBody);
          break;
        }
        line('do {');
        _depth++;
        statements(node.body);
        _depth--;
        line('} while (${expression(node.condition!)});');
        _endLoop(node.elseBody);
      case TestDeclaration():
        _useTests = true;
        final tested = model.declarations[node]!;
        final title = quote(node.title);
        line('Future<void> ${tested.dartName}() async {');
        _depth++;
        line('final _qBefore = _qTestFailed;');
        line('try {');
        _depth++;
        for (final child in node.body) {
          statement(child);
          if (child is TestDeclaration) {
            line('await ${model.declarations[child]!.dartName}();');
          }
        }
        _depth--;
        line('} on StateError catch (error) {');
        _depth++;
        line('_qTestFailed = _qTestFailed + 1;');
        line("print('FAIL ' + $title + ': ' + error.message);");
        _depth--;
        line('} catch (error) {');
        _depth++;
        line('_qTestFailed = _qTestFailed + 1;');
        line("print('FAIL ' + $title + ': ' + error.toString());");
        _depth--;
        line('}');
        line("if (_qTestFailed == _qBefore) print('ok ' + $title);");
        _depth--;
        line('}');
      case ExpressionStatement():
        line('${expression(node.expression)};');
      case IfStatement():
        line('if (${expression(node.condition, opaqueBool: true)}) {');
        _depth++;
        statements(node.thenBody);
        _depth--;
        if (node.elseBody.isNotEmpty) {
          line('} else {');
          _depth++;
          statements(node.elseBody);
          _depth--;
        }
        line('}');
      case ForStatement():
        _beginLoop(node.elseBody);
        final symbol = model.declarations[node]!;
        final indexSymbol = model.loopIndexes[node];
        var iterable = _iterated(node);
        if (_bareType(model.types[node.iterable]) == 'String') {
          iterable = '($iterable).split(\'\')';
        }
        final header =
            '${node.awaiting ? 'await ' : ''}for (final ${_dartType(symbol.type)} ${symbol.dartName} in $iterable) {';
        if (model.loopPairs.contains(node) && indexSymbol != null) {
          final record = '_qp${_temps++}';
          final element = _sequenceElement(model.types[node.iterable] ?? '');
          line('for (final ${_dartType(element)} $record in $iterable) {');
          _depth++;
          line('final ${indexSymbol.dartName} = $record.\$1;');
          line('final ${symbol.dartName} = $record.\$2;');
          statements(node.body);
          _depth--;
          line('}');
          _endLoop(node.elseBody);
          break;
        }
        if (indexSymbol == null) {
          line(header);
          _depth++;
          statements(node.body);
          _depth--;
          line('}');
          _endLoop(node.elseBody);
          break;
        }
        final counter = '_qi${_temps++}';
        line('{ var $counter = 0;');
        _depth++;
        line(header);
        _depth++;
        line('final ${indexSymbol.dartName} = $counter;');
        line('$counter = $counter + 1;');
        statements(node.body);
        _depth--;
        line('}');
        _depth--;
        line('}');
        _endLoop(node.elseBody);
      case WhileStatement():
        _beginLoop(node.elseBody);
        if (node.letName != null) {
          final bound = model.declarations[node]!;
          final temp = '_qn${_temps++}';
          line('while (true) {');
          _depth++;
          _usePresent = true;
          line('final $temp = ${expression(node.condition)};');
          line('if (!_qPresent($temp)) break;');
          line(
              'final ${_dartType(bound.type)} ${bound.dartName} = _qSome<${_dartType(bound.type)}>($temp);');
          statements(node.body);
          _depth--;
          line('}');
          _endLoop(node.elseBody);
          break;
        }
        if (node.pattern != null) {
          line('while (true) {');
          _depth++;
          _openPattern('if', node.condition, node.pattern!);
          _depth++;
          statements(node.body);
          _depth--;
          line('} else {');
          line('  break;');
          line('}');
          _depth--;
          line('}');
          _endLoop(node.elseBody);
          break;
        }
        line('while (${expression(node.condition, opaqueBool: true)}) {');
        _depth++;
        statements(node.body);
        _depth--;
        line('}');
        _endLoop(node.elseBody);
      case GuardedStatement():
        _emitGuarded(node);
      case ParallelAssignment():
        if (node.values.length == 1) {
          final temp = '_qt${_temps++}';
          final value = expression(node.values.single);
          final type = model.types[node.values.single] ?? '';
          final record = type.startsWith('(') &&
              type.endsWith(')') &&
              functionTypeParts(type) == null;
          final read = record ? value : '$value.${_deconstructName(type)}()';
          line('final $temp = $read;');
          for (var i = 0; i < node.targets.length; i++) {
            _writeTarget(node.targets[i], '$temp.\$${i + 1}');
          }
          break;
        }
        final temps = <String>[];
        for (final value in node.values) {
          final temp = '_qt${_temps++}';
          temps.add(temp);
          line('final $temp = ${expression(value)};');
        }
        for (var i = 0; i < node.targets.length; i++) {
          _writeTarget(node.targets[i], temps[i]);
        }
      case BreakStatement():
        if (node.value != null) {
          line('return ${expression(node.value!)};');
          break;
        }
        _markBreak(node.label);
        line(node.label == null ? 'break;' : 'break ${node.label};');
      case ContinueStatement():
        line(node.label == null ? 'continue;' : 'continue ${node.label};');
      case LabelStatement():
        if (node.statement is ForStatement ||
            node.statement is WhileStatement ||
            node.statement is RepeatStatement ||
            node.statement is CForStatement) {
          _pendingLabel = node.name;
          statement(node.statement);
        } else {
          line('${node.name}:');
          statement(node.statement);
        }
      case MatchStatement():
        _matched = model.types[node.value];
        if (_matched != null && _matched!.contains(' | '))
          _unions.add(_matched!);
        line('switch (${expression(node.value)}) {');
        _depth++;
        for (final arm in node.arms) {
          final guard =
              arm.guard == null ? '' : ' when ${expression(arm.guard!)}';
          line('case ${_pattern(arm.pattern)}$guard:');
          _depth++;
          statements(arm.body);
          _depth--;
        }
        if (model.warnings.any((warning) =>
            warning.code == 'W001' && identical(warning.span, node.span))) {
          line('default:');
          line('  break;');
        }
        _depth--;
        line('}');
      case DestructureStatement():
        final temp = '_qt${_temps++}';
        line('final $temp = ${expression(node.value)};');
        _destructure(node.pattern, temp, 1);
      case IfLetStatement():
        final bound = model.declarations[node]!;
        final temp = '_qn${_temps++}';
        line('final $temp = ${expression(node.value)};');
        line('if ($temp != null) {');
        _depth++;
        line('final ${_dartType(bound.type)} ${bound.dartName} = $temp;');
        statements(node.thenBody);
        _depth--;
        if (node.elseBody.isNotEmpty) {
          line('} else {');
          _depth++;
          statements(node.elseBody);
          _depth--;
        }
        line('}');
      case DeferStatement():
        break;
      case IfCaseStatement():
        final scrutinee = expression(node.scrutinee);
        final matched = model.types[node.scrutinee];
        final savedMatched = _matched;
        if (matched != null && matched.contains(' | ')) _matched = matched;
        final typed =
            node.pattern is TypedPattern ? node.pattern as TypedPattern : null;
        if (typed != null &&
            typed.name == null &&
            (_matched == null || !_matched!.contains(' | '))) {
          line('if ($scrutinee is ${typed.type}) {');
        } else {
          line('if ($scrutinee case ${_pattern(node.pattern)}) {');
        }
        _matched = savedMatched;
        _depth++;
        statements(node.body);
        _depth--;
        line('}');
      case WhenStatement():
        if (model.skipped.contains(node)) break;
        statements(node.body);
      case UsingStatement():
        final resource = model.declarations[node]!;
        line('{');
        _depth++;
        line('final ${resource.dartName} = ${expression(node.value)};');
        line('try {');
        _depth++;
        statements(node.body);
        _depth--;
        line(node.async
            ? '} finally { await ${resource.dartName}.dispose(); }'
            : '} finally { ${resource.dartName}.dispose(); }');
        _depth--;
        line('}');
      case IndexAssignment():
        _emitIndexAssignment(node);
      case MemberAssignment():
        final dart = model.references[node]?.dartName ?? node.name;
        line(
            '${expression(node.object)}.$dart ${node.operator} ${expression(node.value)};');
      case PartDirective():
      case SectionDeclaration():
        break;
      case FunctionDeclaration():
        emitFunction(node);
      case RequireStatement():
        final failure = switch (node.kind) {
          'assert' => null,
          'check' => 'StateError',
          _ => 'ArgumentError',
        };
        final message = node.message == null
            ? "'${_quote(node.source ?? '${node.kind} failed')}'"
            : expression(node.message!);
        if (node.kind == 'assert') {
          line(node.message == null
              ? 'assert(${expression(node.condition)});'
              : 'assert(${expression(node.condition)}, $message);');
        } else {
          line(
              'if (!(${expression(node.condition)})) throw $failure($message);');
        }
      case RaiseStatement():
        final symbol = model.references[node];
        final payload = symbol?.type ?? '() -> void';
        final dartType = _dartType(payload);
        final field = symbol?.dartName ?? node.name;
        final args = node.arguments
            .map((argument) => expression(argument.value))
            .join(', ');
        line('for (final _qHandler in List<$dartType>.of($field.handlers)) {');
        line('  _qHandler($args);');
        line('}');
      case TaskGroupStatement():
        _useTask = true;
        final arms = node.children.map(_taskStep).toList();
        line(
            'await _qTaskGroup(<Future<Object?> Function(_QudsCancel)>[${arms.join(', ')}]);');
      case AnnotationDeclaration():
      case ConfigDeclaration():
        break;
      case AliasDeclaration():
      case ClassDeclaration():
      case ExtensionDeclaration():
      case ImportDeclaration():
        break;
    }
  }

  String _constructed(CallExpression node, String ctor) {
    final type = model.types[node];
    if (type != null && type.startsWith('$ctor<') && type.endsWith('>')) {
      return _dartType(type);
    }
    return ctor;
  }

  String _awaitedType(String type) =>
      type.startsWith('Future<') && type.endsWith('>')
          ? type.substring(7, type.length - 1)
          : type;

  String _awaitAll(AwaitAllExpression node) {
    _useAwaitAll = true;
    final calls = node.arms.map(_cancelThunk).join(', ');
    final fields = [
      for (var i = 0; i < node.arms.length; i++)
        '_values[$i] as ${_dartType(_awaitedType(model.types[node.arms[i]] ?? 'Object'))}'
    ].join(', ');
    final record = node.arms.length == 1 ? '($fields,)' : '($fields)';
    return '(await (() async { final _values = await _qAwaitAll(<Future<Object?> Function(_QudsCancel)>[$calls]); return $record; })())';
  }

  /// A child that throws before returning is cancelled, and later children are
  /// not entered. An async child still starts immediately.
  String _taskStep(Node node) {
    if (node is! TaskGroupStatement) return _cancelThunk(node as Expression);
    final inner = node.children.map(_taskStep).join(', ');
    return '(_QudsCancel token) { if (token.cancelled) return Future<Object?>.value(null); return _qTaskGroup(<Future<Object?> Function(_QudsCancel)>[$inner], token); }';
  }

  String _cancelThunk(Expression spawn) {
    final value = expression(spawn);
    final type = model.types[spawn];
    final call = type == 'void' || type == 'Future<void>'
        ? '(() { $value; return null; })()'
        : value;
    return '(_QudsCancel token) { try { return Future<Object?>.value($call); } catch (error) { token.cancelled = true; return Future<Object?>.error(error); } }';
  }

  String _awaitIsolate(AwaitIsolateExpression node) {
    _useIsolate = true;
    return '(await Isolate.run(() => ${expression(node.call)}))';
  }

  String _symbol(String text) {
    if (RegExp(r'^[A-Za-z_][A-Za-z0-9_]*$').hasMatch(text)) return '#$text';
    return 'Symbol(${quote(text)})';
  }

  String _iterated(ForStatement node) {
    if (node.iterable is RangeExpression) {
      return _range(node.iterable as RangeExpression, step: node.step);
    }
    if (node.step != null && node.iterable is CallExpression) {
      final call = node.iterable as CallExpression;
      final symbol = model.references[call.callee];
      if (symbol != null &&
          symbol.name == 'range' &&
          symbol.function == null &&
          !symbol.external) {
        return _rangeCall(call, node.step!);
      }
    }
    return expression(node.iterable);
  }

  String _range(RangeExpression node, {Expression? step}) {
    final integer = model.types[node] == 'Range<int>';
    if (integer) {
      _useRange = true;
    } else {
      _useNumRange = true;
    }
    final name = integer ? '_qRange' : '_qNumRange';
    final start = expression(node.start);
    final end = expression(node.end);
    if (step == null) return '$name($start, $end, ${node.inclusive})';
    return '$name($start, $end, ${node.inclusive}, ${expression(step)})';
  }

  String _rangeCall(CallExpression node, Expression step) {
    final integer = model.types[node] == 'Range<int>';
    if (integer) {
      _useRange = true;
    } else {
      _useNumRange = true;
    }
    final helper = integer ? '_qRange' : '_qNumRange';
    if (node.arguments.length == 1) {
      return '$helper(0, ${expression(node.arguments.single.value)}, true, ${expression(step)})';
    }
    final start = expression(node.arguments[0].value);
    final end = expression(node.arguments[1].value);
    return '$helper($start, $end, true, ${expression(step)})';
  }

  String _pattern(Pattern pattern) {
    final matched = _matched;
    return switch (pattern) {
      WildcardPattern() => '_',
      TypedPattern() => matched != null && matched.contains(' | ')
          ? _unionPattern(matched, pattern)
          : pattern.name == null
              ? pattern.type
              : '${pattern.type} ${model.declarations[pattern]!.dartName}',
      BindingPattern() => _bindingPattern(pattern),
      LiteralPattern() => expression(pattern.literal),
      ListPattern() => '[${pattern.elements.map(_pattern).join(', ')}]',
      MapPattern() => '{${[
          for (var i = 0; i < pattern.keys.length; i++)
            '${expression(pattern.keys[i])}: ${_pattern(pattern.values[i])}'
        ].join(', ')}}',
      RestPattern() => pattern.name == null
          ? '...'
          : '...final ${model.declarations[pattern]!.dartName}',
      OrPattern() =>
        '(${_pattern(pattern.left)} || ${_pattern(pattern.right)})',
      AndPattern() =>
        '(${_pattern(pattern.left)} && ${_pattern(pattern.right)})',
      RelationalPattern() => '${pattern.operator} ${expression(pattern.value)}',
      CastPattern() =>
        '${_pattern(pattern.inner)} as ${_dartType(pattern.type)}',
      NullCheckPattern() => '${_pattern(pattern.inner)}?',
      NullAssertPattern() => '${_pattern(pattern.inner)}!',
      ConstructorPattern() => pattern.typeName.isEmpty
          ? '(${pattern.fields.map(_pattern).join(', ')})'
          : '${pattern.typeName}(${[
              for (var i = 0; i < pattern.fields.length; i++)
                pattern.names[i] == null
                    ? _resultField(pattern, i)
                    : '${pattern.names[i]}: ${_pattern(pattern.fields[i])}'
            ].join(', ')})',
    };
  }

  String _resultField(ConstructorPattern pattern, int index) {
    final inner = _pattern(pattern.fields[index]);
    final field = pattern.typeName == 'Ok'
        ? 'value'
        : pattern.typeName == 'Error'
            ? 'error'
            : null;
    if (field == null) return inner;
    return '$field: $inner';
  }

  void _openPattern(String keyword, Expression scrutinee, Pattern pattern) {
    final text = expression(scrutinee);
    final matched = model.types[scrutinee];
    final saved = _matched;
    if (matched != null && matched.contains(' | ')) _matched = matched;
    final typed = pattern is TypedPattern ? pattern : null;
    if (typed != null &&
        typed.name == null &&
        (_matched == null || !_matched!.contains(' | '))) {
      line('$keyword ($text is ${typed.type}) {');
    } else {
      line('$keyword ($text case ${_pattern(pattern)}) {');
    }
    _matched = saved;
  }

  String _bindingPattern(BindingPattern pattern) {
    final symbol = model.references[pattern];
    if (symbol != null &&
        (symbol.name == 'Ok' || symbol.name == 'Error') &&
        symbol.classCase == null) {
      _useResult = true;
      final field = symbol.name == 'Ok' ? 'value' : 'error';
      return '${symbol.name}($field: _)';
    }
    if (symbol?.classCase != null) {
      final owner = symbol!.classDeclaration!.name;
      if (model.enumNames.contains(owner)) return symbol.dartName;
      final fields = symbol.classCase!.fields;
      if (fields.isEmpty) return '${symbol.dartName}()';
      return '${symbol.dartName}(${fields.map((field) => '${field.name}: _').join(', ')})';
    }
    return 'final ${model.declarations[pattern]!.dartName}';
  }

  void _writeTarget(Pattern pattern, String source) {
    final String? name = switch (pattern) {
      BindingPattern(:final name) => name,
      RestPattern(:final name) => name,
      _ => null,
    };
    if (name == null) return;
    final declared = model.declarations[pattern];
    if (declared == null) return;
    if (model.rebinding.contains(pattern)) {
      line('${declared.dartName} = $source;');
      return;
    }
    line('final ${_dartType(declared.type)} ${declared.dartName} = $source;');
  }

  void _assignList(ListPattern pattern, String source) {
    final elements = pattern.elements;
    var restAt = -1;
    for (var i = 0; i < elements.length; i++) {
      if (elements[i] is RestPattern) restAt = i;
    }
    final prefix = restAt < 0 ? elements.length : restAt;
    final suffix = restAt < 0 ? 0 : elements.length - restAt - 1;
    if (restAt < 0) {
      line(
          'if ($source.length != ${elements.length}) throw StateError(\'Pattern did not match\');');
    } else {
      line(
          'if ($source.length < ${prefix + suffix}) throw StateError(\'Pattern did not match\');');
    }
    for (var i = 0; i < prefix; i++) {
      _destructure(elements[i], '$source[$i]', 1);
    }
    if (restAt < 0) return;
    final end = suffix == 0 ? '$source.length' : '$source.length - $suffix';
    _destructure(elements[restAt], '$source.sublist($prefix, $end)', 1);
    for (var j = 0; j < suffix; j++) {
      _destructure(elements[restAt + 1 + j],
          '$source[($source.length - $suffix) + $j]', 1);
    }
  }

  void _destructure(Pattern pattern, String source, int position) {
    switch (pattern) {
      case WildcardPattern():
      case TypedPattern():
        if (pattern is TypedPattern &&
            pattern.name != null &&
            model.declarations[pattern] != null) {
          final declared = model.declarations[pattern]!;
          line('final ${declared.type} ${declared.dartName} = $source;');
        }
        return;
      case BindingPattern():
        final declared = model.declarations[pattern];
        if (declared != null) {
          if (model.rebinding.contains(pattern)) {
            line('${declared.dartName} = $source;');
          } else {
            line(
                'final ${_dartType(declared.type)} ${declared.dartName} = $source;');
          }
        }
      case ListPattern():
        _assignList(pattern, source);
      case MapPattern():
        for (var i = 0; i < pattern.values.length; i++) {
          _destructure(pattern.values[i],
              '$source[${expression(pattern.keys[i])}]', position);
        }
      case RestPattern():
        _writeTarget(pattern, source);
      case OrPattern():
      case AndPattern():
        _destructure(
            pattern is OrPattern ? pattern.left : (pattern as AndPattern).left,
            source,
            position);
      case RelationalPattern():
      case CastPattern():
        if (pattern is CastPattern) {
          _destructure(pattern.inner, source, position);
        }
      case NullCheckPattern():
        _destructure(pattern.inner, source, position);
      case NullAssertPattern():
        _destructure(pattern.inner, source, position);
      case ConstructorPattern():
        for (var i = 0; i < pattern.fields.length; i++) {
          final field = pattern.names[i];
          final child = field == null ? '$source.\$${i + 1}' : '$source.$field';
          _destructure(pattern.fields[i], child, position);
        }
      case LiteralPattern():
        return;
    }
  }

  String quote(String value) => quoteDartString(value);
  final _emittingContextualFunction = <Expression>{};
  final _emittingValueLowering = <Expression>{};
  final _emittingValueGuard = <Expression>{};
  String expression(Expression node,
      {bool constantContext = false, bool opaqueBool = false}) {
    if (identical(node, _replace) && _replaceWith != null) {
      final replacement = _replaceWith!;
      _replace = null;
      _replaceWith = null;
      return expression(replacement,
          constantContext: constantContext, opaqueBool: opaqueBool);
    }
    final conversion = model.implicitConversions[node];
    if (conversion != null && _emittingConversions.add(node)) {
      if (constantContext)
        throw CompilerException(
            'E401', 'Custom conversion in const context', node.span);
      try {
        return '${_conversionTarget(conversion)}(${expression(node, opaqueBool: opaqueBool)})';
      } finally {
        _emittingConversions.remove(node);
      }
    }
    if (model.qudsValueLowerings.containsKey(node) &&
        _emittingValueLowering.add(node)) {
      try {
        return _finishValue(node, _emitQudsValueLowering(node));
      } finally {
        _emittingValueLowering.remove(node);
      }
    }
    final functionArguments = model.contextualFunctionArguments[node];
    if (functionArguments != null && _emittingContextualFunction.add(node)) {
      try {
        return _instantiateNativeValue(node, functionArguments);
      } finally {
        _emittingContextualFunction.remove(node);
      }
    }
    // Folding only logical const operators avoids Dart's dead_code warning
    // while leaving other const operations for Dart to evaluate again.
    if (constantContext &&
        node is BinaryExpression &&
        (node.operator == 'and' || node.operator == 'or')) {
      final value = model.constants[node];
      if (value is! ConstBool) {
        throw StateError('Logical const was not evaluated');
      }
      return value.dartSource;
    }
    // A const or literal bool is reachable to Dart's analyzer when it is
    // hidden behind an identity call. The operand is still read once.
    if (model.wrapAs[node] case final union?) {
      model.wrapAs.remove(node);
      final innerType = model.types[node]!;
      final inner = expression(node,
          constantContext: constantContext, opaqueBool: opaqueBool);
      _unions.add(union);
      return '${_unionClass(union)}_${_alt(innerType)}($inner)';
    }
    if (opaqueBool && !constantContext && _opaqueBoolLeaf(node)) {
      _useBoolHelper = true;
      return '_qBool(${expression(node, constantContext: constantContext)})';
    }
    if (!constantContext && node is CallExpression) {
      final declaration = model.references[node.callee]?.classDeclaration;
      if (declaration != null &&
          declaration.typeParameters.isNotEmpty &&
          supportsReadonlyClass(model, declaration) &&
          _registeringReadonly.add(node)) {
        try {
          final value = expression(node,
              constantContext: constantContext, opaqueBool: opaqueBool);
          final type = model.types[node]!;
          return '$_readonlyRuntime.registerGuards<${_dartType(type)}>($value, [${_guardDescriptor(type, includeKnown: false)}])';
        } finally {
          _registeringReadonly.remove(node);
        }
      }
    }
    final typedReadonly = model.types[node];
    if (!constantContext &&
        typedReadonly != null &&
        _readonlyBoundary(typedReadonly) != null &&
        _typedReadonlyEmitting.add(node)) {
      try {
        final value = expression(node,
            constantContext: constantContext, opaqueBool: opaqueBool);
        return _readonlyGuard(typedReadonly, value);
      } finally {
        _typedReadonlyEmitting.remove(node);
      }
    }
    final logic = node is BinaryExpression &&
        (node.operator == 'and' || node.operator == 'or');
    final childOpaque = !constantContext && (opaqueBool || logic);
    return _finishValue(
        node,
        switch (node) {
          Literal() => node.value is String
              ? quote(node.value as String)
              : '${node.value}',
          Identifier() => _identifier(node),
          // Dart has no prefix +. Quds unary + is numeric identity.
          UnaryExpression() => switch (node.operator) {
              'not' =>
                '(!${expression(node.operand, constantContext: constantContext, opaqueBool: childOpaque)})',
              '+' => expression(node.operand, constantContext: constantContext),
              '!' =>
                '(${expression(node.operand, constantContext: constantContext)}!)',
              _ =>
                '(${node.operator}${expression(node.operand, constantContext: constantContext)})',
            },
          BinaryExpression() => _binary(node,
              constantContext: constantContext, childOpaque: childOpaque),
          ChainComparison() => _chain(node),
          SliceExpression() => _slice(node),
          TypeTestExpression() =>
            '(${expression(node.operand, constantContext: constantContext)} ${node.operator} ${_dartType(node.type)})',
          ListExpression() => _list(node),
          CallExpression() => call(node, constantContext: constantContext),
          InterpolatedString() =>
            '[${node.parts.map((part) => expression(part, constantContext: constantContext)).join(', ')}].join()',
          ShownExpression() =>
            "('${_quote(node.text)}=' + (${expression(node.value, constantContext: constantContext)}).toString())",
          Lambda() => _lambda(node),
          MemberAccess() => _member(node, constantContext: constantContext),
          IndexExpression() => _index(node, constantContext: constantContext),
          MapExpression() => _map(node),
          SetExpression() => _set(node),
          RecordExpression() =>
            '(${node.fields.map((field) => expression(field)).join(', ')})',
          RangeExpression() => _range(node),
          AwaitExpression() =>
            '(await ${expression(node.operand, constantContext: constantContext)})',
          PropagateExpression() => _propagate(node),
          DoExpression() => _do(node),
          CaptureExpression() => _capture(node),
          ConversionExpression() => _convert(node),
          WithExpression() => _with(node),
          DotShorthand() => _dot(node),
          AssignExpression() =>
            '${_cell(model.references[node]!)} ${node.operator} ${expression(node.value, constantContext: constantContext)}',
          ThisExpression() => _defaultReceiver ?? 'this',
          SpreadElement() =>
            '${node.nullAware ? '...?' : '...'}${expression(node.operand, constantContext: constantContext)}',
          IfExpression() => _if(node),
          MatchExpression() => _match(node),
          TryExpression() =>
            '(() { try { return ${expression(node.operand)}; } catch (error) { return ${expression(node.fallback)}; } })()',
          LoopExpression() => _loopValue(node),
          WhereExpression() => _where(node),
          MapComprehension() => _mapEntry(node, node, 'Object', 'Object'),
          NullAwareElement() => '?(${expression(node.value)})',
          CollectionIf() => _piece(node, 'Object', false),
          CollectionFor() => _piece(node, 'Object', false),
          TypeApplication() => _functionInstantiation(node),
          AwaitAllExpression() => _awaitAll(node),
          AwaitIsolateExpression() => _awaitIsolate(node),
          SymbolExpression() => _symbol(node.text),
          NameofExpression() => "'${_quote(node.text)}'",
        });
  }

  bool _opaqueBoolLeaf(Expression node) {
    if (node is Literal) return node.value is bool;
    if (node is Identifier) {
      final symbol = model.references[node];
      return symbol != null && symbol.type == 'bool' && symbol.function == null;
    }
    return false;
  }

  String _bareType(String? type) {
    if (type == null) return '';
    var value = type.startsWith('readonly ') ? type.substring(9) : type;
    if (value.endsWith('?')) value = value.substring(0, value.length - 1);
    return value;
  }

  String _sequenceElement(String type) {
    final bare = _bareType(type);
    final typed = model.dartShapes[bare]?.listElement;
    if (typed != null) return typed;
    for (final head in ['List<', 'Iterable<', 'Set<']) {
      if (bare.startsWith(head) && bare.endsWith('>')) {
        return bare.substring(head.length, bare.length - 1);
      }
    }
    return 'Object';
  }

  String _binary(BinaryExpression node,
      {required bool constantContext, required bool childOpaque}) {
    final leftType = model.types[node.left];
    final rightType = model.types[node.right];
    if (!constantContext &&
        (node.operator == '==' || node.operator == '!=') &&
        ((leftType?.startsWith('readonly ') ?? false) ||
            (rightType?.startsWith('readonly ') ?? false))) {
      _requireReadonlyRuntime();
      final code =
          '$_readonlyRuntime.readonlyEquals(${expression(node.left)}, ${expression(node.right)})';
      return node.operator == '!=' ? '(!$code)' : code;
    }
    if (node.operator == '+') {
      final result = model.types[node];
      if (result != null &&
          (result.startsWith('List<') || result.startsWith('Map<'))) {
        final left = '_ql${_temps++}';
        final right = '_qr${_temps++}';
        final leftCode =
            expression(node.left, constantContext: constantContext);
        final rightCode =
            expression(node.right, constantContext: constantContext);
        final built = result.startsWith('List<')
            ? '<${_dartType(result.substring(5, result.length - 1))}>[...$left, ...$right]'
            : '<${result.substring(4, result.length - 1)}>{...$left, ...$right}';
        return '(() { final $left = $leftCode; final $right = $rightCode; return $built; })()';
      }
    }
    if (node.operator == 'in' || node.operator == 'not in') {
      final left = '_ql${_temps++}';
      final right = '_qr${_temps++}';
      final collection = _bareType(rightType);
      final test = collection.startsWith('Map<')
          ? '$right.containsKey($left)'
          : '$right.contains($left)';
      final result = node.operator == 'not in' ? '!$test' : test;
      return '(() { final $left = ${expression(node.left, constantContext: constantContext)}; final $right = ${expression(node.right, constantContext: constantContext)}; return $result; })()';
    }
    if (node.operator == '*' && leftType == 'int' && rightType == 'String') {
      final count = '_qn${_temps++}';
      final text = '_qn${_temps++}';
      return '(() { final $count = ${expression(node.left, constantContext: constantContext)}; final $text = ${expression(node.right, constantContext: constantContext)}; return $text * $count; })()';
    }
    final op = switch (node.operator) {
      'and' => '&&',
      'or' => '||',
      _ => node.operator,
    };
    final code =
        '(${expression(node.left, constantContext: constantContext, opaqueBool: childOpaque)} $op ${expression(node.right, constantContext: constantContext, opaqueBool: childOpaque)})';
    final result = model.types[node];
    if (result != null &&
        result == leftType &&
        result == rightType &&
        const {'+', '-', '*', '~/', '%'}.contains(node.operator) &&
        _openGenerics.contains(result)) {
      return '($code as $result)';
    }
    return code;
  }

  String _quote(String text) =>
      text.replaceAll(r'\', r'\\').replaceAll("'", r"\'");

  String _deconstructName(String type) {
    var bare = type.startsWith('readonly ') ? type.substring(9) : type;
    if (bare.endsWith('?')) bare = bare.substring(0, bare.length - 1);
    final declaration = model.classes[bare];
    final method = declaration?.methods
        .where((item) => item.name == 'deconstruct' && item.parameters.isEmpty)
        .firstOrNull;
    return model.declarations[method]?.dartName ?? 'deconstruct';
  }

  /// Every operand runs, left to right, before any comparison is combined.
  String _chain(ChainComparison node) {
    final names = <String>[];
    final bindings = <String>[];
    for (final operand in node.operands) {
      final name = '_qc${_temps++}';
      names.add(name);
      bindings.add('final $name = ${expression(operand)};');
    }
    final text = model.types[node.operands.first] == 'String';
    final checks = <String>[
      for (var i = 0; i < node.operators.length; i++)
        text
            ? '${names[i]}.compareTo(${names[i + 1]}) ${node.operators[i]} 0'
            : '${names[i]} ${node.operators[i]} ${names[i + 1]}'
    ];
    return '(() { ${bindings.join(' ')} return ${checks.join(' && ')}; })()';
  }

  String _slice(SliceExpression node) {
    final object = '_qo${_temps++}';
    final start = '_qa${_temps++}';
    final end = '_qb${_temps++}';
    final text = _bareType(model.types[node.object]) == 'String';
    final method = text ? 'substring' : 'sublist';
    final lines = <String>['final $object = ${expression(node.object)}'];
    if (node.start == null) {
      lines.add('final $start = 0');
    } else {
      final raw = '_qs${_temps++}';
      lines.add('final $raw = ${expression(node.start!)}');
      lines.add('final $start = $raw < 0 ? $object.length + $raw : $raw');
    }
    if (node.end == null) {
      lines.add('final $end = $object.length');
    } else {
      final raw = '_qe${_temps++}';
      final norm = '$raw < 0 ? $object.length + $raw : $raw';
      final value = node.inclusive ? '($norm) + 1' : norm;
      lines.add('final $raw = ${expression(node.end!)}');
      lines.add('final $end = $value');
    }
    return '(() { ${lines.join('; ')}; return $object.$method($start, $end); })()';
  }

  String _functionInstantiation(TypeApplication node) {
    if (!model.instantiatedFunctionValues.contains(node))
      return expression(node.callee);
    if (model.qudsValueLowerings.containsKey(node.callee))
      return expression(node.callee);
    return _instantiateNativeValue(node.callee, node.arguments);
  }

  String _finishValue(Expression node, String value) {
    final guard = model.qudsValueResultGuards[node];
    final parameters = model.qudsValueLowerings[node]?.function.parameters;
    if (parameters != null && parameters.isNotEmpty) return value;
    if (guard == null || !_emittingValueGuard.add(node)) return value;
    try {
      final call = '($value)()';
      return '(() => ${_readonlyGuard(guard, call)})';
    } finally {
      _emittingValueGuard.remove(node);
    }
  }

  String _emitQudsValueLowering(Expression node) {
    final lowering = model.qudsValueLowerings[node]!;
    final function = lowering.function;
    if (packetValueLayout(function.parameters)) {
      return _emitPacketTearoff(node, lowering);
    }
    final declared = model.declarations[function]!;
    final implementation = _defaultBridges.contains(function)
        ? _defaultBridgeName(function)
        : declared.dartName;
    String target;
    if (model.providerDefaultFunctions.contains(function)) {
      if (node is MemberAccess) {
        target = '${expression(node.object)}.$implementation';
      } else {
        final original = model.references[node]?.dartName ?? declared.dartName;
        final dot = original.lastIndexOf('.');
        target =
            '${dot < 0 ? '' : original.substring(0, dot + 1)}$implementation';
      }
    } else if (node is MemberAccess) {
      final method = implementation;
      if (function.isStatic) {
        final owner = lowering.staticOwner == null
            ? expression(node.object)
            : _dartType(lowering.staticOwner!);
        target = '$owner.$method';
      } else if (node.nullAware) {
        final receiver = '_qrecv${_temps++}';
        final type = _dartType(nullableType(model.types[node.object]!));
        final body = _attachGap(
            _valueAdapter('$receiver.$method', lowering,
                resultGuard: function.parameters.isEmpty
                    ? null
                    : model.qudsValueResultGuards[node]),
            function,
            '$receiver.$method');
        return '(($type $receiver) => $receiver == null ? null : $body)(${expression(node.object)})';
      } else {
        final receiver = '_qrecv${_temps++}';
        final body = _attachGap(
            _valueAdapter('$receiver.$method', lowering,
                resultGuard: function.parameters.isEmpty
                    ? null
                    : model.qudsValueResultGuards[node]),
            function,
            '$receiver.$method');
        return '((${_dartType(model.types[node.object]!)} $receiver) => $body)(${expression(node.object)})';
      }
    } else {
      target = _defaultBridges.contains(function)
          ? implementation
          : node is Identifier
              ? _identifier(node)
              : expression(node is TypeApplication ? node.callee : node);
    }
    return _attachGap(
        _valueAdapter(target, lowering,
            resultGuard: function.parameters.isEmpty
                ? null
                : model.qudsValueResultGuards[node]),
        function,
        target);
  }

  String _attachGap(
      String value, FunctionDeclaration function, String implementation) {
    if (!positionalGapPossible(function.parameters)) return value;
    _useGap = true;
    final held = '_qgapv${_temps++}';
    final gap = _defaultBridges.contains(function)
        ? value
            .replaceFirst(r'$QudsMethodDefault', r'$QudsMethodGap')
            .replaceFirst(r'$QudsDefault', r'$QudsGap')
        : _localGapClosure(function, implementation);
    return '(() { final $held = $value; _\$qudsBindGap($held, $gap); return $held; })()';
  }

  String _localGapClosure(FunctionDeclaration function, String target) {
    final saved = _names;
    _names = {..._names};
    final statements = <String>[];
    final arguments = <String>[];
    try {
      for (var i = 0; i < function.parameters.length; i++) {
        final parameter = function.parameters[i];
        final declared = model.declarations[parameter]!;
        final dartType = _dartType(declared.type);
        final slot = '_qlocal$i${_temps++}';
        final input = '\$qInputs[$i]';
        final supplied =
            declared.type == 'Object?' || declared.type == 'dynamic'
                ? input
                : '$input as $dartType';
        final resolved = parameter.defaultValue == null
            ? supplied
            : '\$qPresent[$i] ? $supplied : ${expression(parameter.defaultValue!)}';
        statements.add('final $dartType $slot = $resolved;');
        _names[declared.dartName] = slot;
        arguments.add(parameter.isNamed ? '${parameter.name}: $slot' : slot);
      }
    } finally {
      _names = saved;
    }
    final returned = _dartType(model.declarations[function]!.type);
    final invocation = '$target(${arguments.join(', ')})';
    final tail = returned == 'void'
        ? '$invocation; return null;'
        : 'return $invocation;';
    return '((List<Object?> \$qInputs, List<bool> \$qPresent) { ${statements.join(' ')} $tail })';
  }

  String _valueAdapter(String target, QudsValueLowering lowering,
      {bool declaration = false, String? resultGuard}) {
    final function = lowering.function;
    final hidden = <String>[];
    for (var i = 0; i < function.parameters.length; i++) {
      if (!function.parameters[i].type.contains(' & ')) continue;
      hidden.add(lowering.parameterTypes[i].split(' & ').first.trim());
    }
    final arguments = [...lowering.typeArguments, ...hidden];
    if (arguments.isNotEmpty)
      target = '$target<${arguments.map(_dartType).join(', ')}>';
    if (!declaration &&
        _defaultBridges.contains(function) &&
        resultGuard == null) return target;
    if (resultGuard == null &&
        function.parameters.every((parameter) => !parameter.needsAdapter)) {
      return target;
    }
    final required = <String>[];
    final optional = <String>[];
    final optionalPositional = <String>[];
    final passed = <String>[];
    final statements = <String>[];
    final savedNames = _names;
    _names = {..._names};
    try {
      for (var i = 0; i < function.parameters.length; i++) {
        final parameter = function.parameters[i];
        final dartName = model.declarations[parameter]!.dartName;
        final raw = lowering.parameterTypes[i];
        final type = raw.contains(' & ') ? raw.split(' & ').first.trim() : raw;
        final dartType = _dartType(type);
        if (parameter.variadic) {
          required.add('List<$dartType> $dartName');
          passed.add(dartName);
        } else if (parameter.kind == ParameterKind.requiredNamed) {
          optional.add('required $dartType ${parameter.name}');
          passed.add(parameter.name);
          _names[dartName] = parameter.name;
        } else if (parameter.defaultValue != null) {
          _useDefaultOmitted = true;
          final suppliedName = parameter.name;
          (parameter.kind == ParameterKind.optionalPositional
                  ? optionalPositional
                  : optional)
              .add('Object? $suppliedName = $_defaultOmitted');
          final fallback = expression(parameter.defaultValue!);
          final resolved = '_qdefault${_temps++}';
          final supplied = type == 'Object?' || type == 'dynamic'
              ? suppliedName
              : '$suppliedName as $dartType';
          statements.add('final $dartType $resolved = '
              'identical($suppliedName, $_defaultOmitted) ? $fallback : $supplied;');
          _names[dartName] = resolved;
          passed.add(resolved);
        } else {
          required.add('$dartType $dartName');
          passed.add(dartName);
        }
      }
      final signature = [
        ...required,
        if (optional.isNotEmpty) '{${optional.join(', ')}}',
        if (optionalPositional.isNotEmpty) '[${optionalPositional.join(', ')}]',
      ].join(', ');
      final invocation = '$target(${passed.join(', ')})';
      final guarded = resultGuard == null
          ? invocation
          : _readonlyGuard(resultGuard, invocation);
      return '($signature) { ${statements.join(' ')} return $guarded; }';
    } finally {
      _names = savedNames;
    }
  }

  String _instantiateNativeValue(Expression callee, List<String> arguments) {
    final types = arguments.map(_dartType).join(', ');
    if (callee case MemberAccess member when member.nullAware) {
      // Dart cannot instantiate a nullable generic function value. Capture the
      // receiver once, then instantiate the non-null bound method in its arm.
      final receiver = '_qgi${_temps++}';
      final type = _dartType(nullableType(model.types[member.object]!));
      final name = model.references[member]?.dartName ?? member.name;
      return '(($type $receiver) => $receiver == null ? null : $receiver.$name<$types>)(${expression(member.object)})';
    }
    return '${expression(callee)}<$types>';
  }

  String _member(MemberAccess node, {bool constantContext = false}) {
    final dart = model.references[node]?.dartName ?? node.name;
    if (model.staticValueOwners[node] case final owner?) {
      return '${_dartType(owner)}.$dart';
    }
    final access = node.nullAware ? '?.' : '.';
    var object = expression(node.object, constantContext: constantContext);
    final referenced = model.references[node];
    if (model.types[node.object] == 'prefix' &&
        referenced?.classDeclaration != null &&
        referenced?.classCase == null) {
      // Imported Quds type symbols may already carry their namespace. The
      // expression's receiver supplies that prefix, including escaped aliases.
      return '$object.${dart.split('.').last}';
    }
    final type = model.types[node.object];
    final bare = _bareType(type);
    final builtin = model.references[node]?.dartName == node.name;
    final nullAware = node.nullAware || (type != null && isNullableType(type));
    if (builtin && node.name == 'chars' && bare == 'String') {
      return nullAware ? "$object?.split('')" : "$object.split('')";
    }
    if (builtin && node.name == 'lines' && bare == 'String') {
      final text = '_qt${_temps++}';
      final split =
          "$text.replaceAll('\\r\\n', '\\n').replaceAll('\\r', '\\n').split('\\n')";
      if (nullAware) {
        return '(() { final $text = $object; return $text == null ? null : $split; })()';
      }
      return '(() { final $text = $object; return $split; })()';
    }
    if (builtin &&
        node.name == 'abs' &&
        (bare == 'int' || bare == 'double' || bare == 'num')) {
      return nullAware ? '$object?.abs()' : '$object.abs()';
    }
    if (builtin &&
        (node.name == 'round' || node.name == 'floor' || node.name == 'ceil') &&
        (bare == 'int' || bare == 'double' || bare == 'num')) {
      if (bare == 'int') return object;
      final call = '${node.name}()';
      return nullAware ? '$object?.$call' : '$object.$call';
    }
    if (builtin &&
        node.name == 'plain' &&
        (bare == 'int' || bare == 'double' || bare == 'num')) {
      _usePlain = true;
      if (!nullAware) return '_qPlain($object)';
      final value = '_qn${_temps++}';
      return '(() { final $value = $object; return $value == null ? null : _qPlain($value); })()';
    }
    if (type != null && type.contains(' & ')) {
      final parts = type.split(' & ').map((part) => part.trim()).toList();
      final owner = parts.cast<String?>().firstWhere(
          (part) => _declaresMember(part!, node.name),
          orElse: () => null);
      if (owner != null && owner != parts.first) {
        object = '($object as ${_dartType(owner)})';
      }
    }
    return '$object$access$dart';
  }

  bool _declaresMember(String type, String name) {
    final declaration = _classes[_genericHead(type)];
    if (declaration == null) return false;
    return declaration.fields.any((field) => field.name == name) ||
        declaration.methods.any((method) => method.name == name) ||
        declaration.properties.any((property) => property.name == name);
  }

  String _genericHead(String type) {
    final open = type.indexOf('<');
    return open < 0 ? type : type.substring(0, open);
  }

  String _identifier(Identifier node) {
    if (_defaultReceiver != null &&
        (model.implicitThis.contains(node) ||
            model.references[node]?.field == true)) {
      return '$_defaultReceiver.${model.references[node]?.dartName ?? node.name}';
    }
    if (model.implicitThis.contains(node)) {
      final dart = model.references[node]?.dartName ?? node.name;
      return 'this.$dart';
    }
    final symbol = model.references[node];
    if (symbol?.library == 'check') _useChecks = true;
    if (symbol?.name == 'log' && symbol?.dartName == 'log') _useLog = true;
    if (symbol?.name == 'missing') _useOptional = true;
    if (symbol != null &&
        (symbol.reactive == 'state' || symbol.reactive == 'computed')) {
      return _cell(symbol);
    }
    final dart = _use(node);
    if (symbol?.namespace != null) return _dartImportPrefix(dart);
    return _names[dart] ?? dart;
  }

  String _cell(Symbol symbol) {
    if (symbol.reactive == 'state' || symbol.reactive == 'computed') {
      if (symbol.reactive == 'state') {
        _useState = true;
      } else {
        _useComputed = true;
      }
      return '${symbol.dartName}.value';
    }
    return symbol.dartName;
  }

  String _use(Identifier node) {
    final name = model.references[node]!.dartName;
    _usedNames.add(name);
    return name;
  }

  String _emitPacketTearoff(Expression node, QudsValueLowering lowering) {
    final function = lowering.function;
    final owner = model.providerDefaultMethods[function] ??
        model.classes.values
            .where((item) => item.methods.contains(function))
            .firstOrNull;
    final bridge = owner == null
        ? providerPacketBridgeName(function)
        : providerMethodPacketBridgeName(owner, function);
    final arguments = [...lowering.typeArguments];
    final suffix =
        arguments.isEmpty ? '' : '<${arguments.map(_dartType).join(', ')}>';
    if (node is MemberAccess) {
      if (function.isStatic) {
        final ownerType = lowering.staticOwner == null
            ? expression(node.object)
            : _dartType(lowering.staticOwner!);
        return '$ownerType.$bridge$suffix';
      }
      final receiver = '_qrecv${_temps++}';
      final body = '$receiver.$bridge$suffix';
      if (node.nullAware) {
        final type = _dartType(nullableType(model.types[node.object]!));
        return '(($type $receiver) => $receiver == null ? null : $body)(${expression(node.object)})';
      }
      final type = _dartType(model.types[node.object]!);
      return '(($type $receiver) => $body)(${expression(node.object)})';
    }
    final declared = model.declarations[function]!;
    final original = model.references[node]?.dartName ?? declared.dartName;
    final dot = original.lastIndexOf('.');
    final prefix = dot < 0 ? '' : original.substring(0, dot + 1);
    return '$prefix$bridge$suffix';
  }

  String _lambda(Lambda node) {
    final savedReturn = _returnView;
    _returnView = null;
    if (packetValueLayout(node.parameters)) {
      final text = _packetLambda(node);
      _returnView = savedReturn;
      return text;
    }
    if (node.parameters.any((parameter) => parameter.needsAdapter)) {
      return _shapedLambda(node, savedReturn);
    }
    final parameters = node.parameters
        .map((p) =>
            '${_dartType(model.declarations[p]!.type)} ${model.declarations[p]!.dartName}')
        .join(', ');
    final async = model.asyncLambdas.contains(node) ? 'async ' : '';
    if (node.expressionBody case final value?) {
      final text = '(($parameters) $async=> ${expression(value)})';
      _returnView = savedReturn;
      return text;
    }
    final savedDepth = _depth;
    _depth = 0;
    final body = _captureBlock(() {
      _hoistOnce(node.body);
      statements(node.body!);
    });
    _depth = savedDepth;
    _returnView = savedReturn;
    return '(($parameters) $async{\n$body})';
  }

  String _packetLambda(Lambda node) {
    final saved = _names;
    _names = {..._names};
    final bindings = <String>[];
    try {
      final slots = packetSlots(node.parameters);
      for (var i = 0; i < slots.length; i++) {
        final parameter = slots[i];
        final declared = model.declarations[parameter]!;
        final element = _dartType(declared.type);
        final slot = '_qslot$i';
        final input = '\$qInputs[$i]';
        if (parameter.variadic) {
          final listType = _variadicListType(declared.type);
          final elementType = listType.substring(5, listType.length - 1);
          bindings.add(
              'final $listType $slot = \$qPresent[$i] ? $input as $listType : <$elementType>[]');
        } else {
          final supplied =
              declared.type == 'Object?' || declared.type == 'dynamic'
                  ? input
                  : '$input as $element';
          final resolved = parameter.defaultValue == null
              ? supplied
              : '\$qPresent[$i] ? $supplied : ${expression(parameter.defaultValue!)}';
          bindings.add('final $element $slot = $resolved');
        }
        _names[declared.dartName] = slot;
      }
      final async = model.asyncLambdas.contains(node) ? 'async ' : '';
      final setup = bindings.join('; ');
      if (node.expressionBody case final value?) {
        return '((List<Object?> \$qInputs, List<bool> \$qPresent) $async{ $setup; return ${expression(value)}; })';
      }
      final savedDepth = _depth;
      _depth = 0;
      final body = _captureBlock(() {
        _hoistOnce(node.body);
        statements(node.body!);
      });
      _depth = savedDepth;
      return '((List<Object?> \$qInputs, List<bool> \$qPresent) $async{ $setup;\n$body})';
    } finally {
      _names = saved;
    }
  }

  String _shapedLambda(Lambda node, String? savedReturn) {
    try {
      final required = <String>[];
      final optional = <String>[];
      final optionalPositional = <String>[];
      final setup = <String>[];
      final savedNames = _names;
      _names = {..._names};
      try {
        for (final parameter in node.parameters) {
          final symbol = model.declarations[parameter]!;
          final dartType = _dartType(symbol.type);
          final dartName = symbol.dartName;
          if (parameter.kind == ParameterKind.requiredNamed) {
            optional.add('required $dartType ${parameter.name}');
            _names[dartName] = parameter.name;
          } else if (parameter.kind == ParameterKind.optionalNamed ||
              parameter.kind == ParameterKind.optionalPositional) {
            _useDefaultOmitted = true;
            final slot = parameter.name;
            (parameter.kind == ParameterKind.optionalPositional
                    ? optionalPositional
                    : optional)
                .add('Object? $slot = $_defaultOmitted');
            final resolved = '_qdefault${_temps++}';
            final fallback = parameter.defaultValue == null
                ? 'null'
                : expression(parameter.defaultValue!);
            final supplied =
                symbol.type == 'Object?' || symbol.type == 'dynamic'
                    ? slot
                    : '$slot as $dartType';
            setup.add(
                'final $dartType $resolved = identical($slot, $_defaultOmitted) ? $fallback : $supplied');
            _names[dartName] = resolved;
          } else {
            required.add('$dartType $dartName');
            _names[dartName] = dartName;
          }
        }
        final signature = [
          ...required,
          if (optional.isNotEmpty) '{${optional.join(', ')}}',
          if (optionalPositional.isNotEmpty)
            '[${optionalPositional.join(', ')}]',
        ].join(', ');
        final async = model.asyncLambdas.contains(node) ? 'async ' : '';
        if (node.expressionBody case final value?) {
          final text = expression(value);
          final prelude = setup.isEmpty ? '' : '${setup.join('; ')}; ';
          return '(($signature) $async{ $prelude return $text; })';
        }
        final savedDepth = _depth;
        _depth = 0;
        final body = _captureBlock(() {
          for (final statement in setup) {
            line('$statement;');
          }
          _hoistOnce(node.body);
          statements(node.body!);
        });
        _depth = savedDepth;
        return '(($signature) $async{\n$body})';
      } finally {
        _names = savedNames;
      }
    } finally {
      _returnView = savedReturn;
    }
  }

  String _map(MapExpression node) {
    final type = model.types[node]!;
    final inner = type.substring(4, type.length - 1);
    final splitAt = inner.indexOf(',');
    final keyType = _dartType(inner.substring(0, splitAt).trim());
    final valueType = _dartType(inner.substring(splitAt + 1).trim());
    return '<$keyType, $valueType>{${_mapEntries(node, keyType, valueType)}}';
  }

  String _mapEntries(MapExpression node, String keyType, String valueType) => [
        for (var i = 0; i < node.keys.length; i++)
          _mapEntry(node.keys[i], node.values[i], keyType, valueType)
      ].join(', ');

  String _mapEntry(
      Expression key, Expression value, String keyType, String valueType) {
    if (key is SpreadElement) {
      final text = expression(key.operand);
      return key.nullAware ? '...?$text' : '...$text';
    }
    if (key is MapComprehension) {
      if (key.name != null) {
        final symbol = model.declarations[key]!;
        return 'for (final ${_dartType(symbol.type)} ${symbol.dartName} in ${expression(key.iterable!)}) ...<$keyType, $valueType>{${_mapEntries(key.thenMap, keyType, valueType)}}';
      }
      final tail = key.elseMap == null
          ? ''
          : ' else ...<$keyType, $valueType>{${_mapEntries(key.elseMap!, keyType, valueType)}}';
      return 'if (${expression(key.condition!, opaqueBool: true)}) ...<$keyType, $valueType>{${_mapEntries(key.thenMap, keyType, valueType)}}$tail';
    }
    return '${expression(key)}: ${expression(value)}';
  }

  String _if(IfExpression node) {
    String chain(Expression branch) {
      if (branch is IfExpression) {
        return ' else if (${expression(branch.condition, opaqueBool: true)}) { return ${expression(branch.thenValue)}; }${chain(branch.elseValue)}';
      }
      return ' else { return ${expression(branch)}; }';
    }

    return '(() { if (${expression(node.condition, opaqueBool: true)}) { return ${expression(node.thenValue)}; }${chain(node.elseValue)} })()';
  }

  String _match(MatchExpression node) {
    final saved = _matched;
    _matched = model.types[node.value];
    if (_matched != null && _matched!.contains(' | ')) _unions.add(_matched!);
    final arms = node.arms.map((arm) {
      final guard = arm.guard == null ? '' : ' when ${expression(arm.guard!)}';
      return 'case ${_pattern(arm.pattern)}$guard: return ${expression(arm.result)};';
    }).join(' ');
    _matched = saved;
    return '(() { switch (${expression(node.value)}) { $arms } })()';
  }

  String _runtimeStep(Expression step) {
    if (step is AssignExpression &&
        (step.operator == '+=' || step.operator == '-=') &&
        step.value is! Literal) {
      final target = model.references[step]!.dartName;
      final temp = '_qs${_temps++}';
      final op = step.operator == '+=' ? '+=' : '-=';
      return '(() { final $temp = ${expression(step.value)}; if ($temp == 0) throw StateError(\'A loop step cannot be zero\'); $target $op $temp; })()';
    }
    return expression(step);
  }

  String _propagate(PropagateExpression node) {
    _useResult = true;
    _usePropagate = true;
    final temp = '_qr${_temps++}';
    final value = expression(node.operand);
    return '(() { final $temp = $value; if ($temp is Error) throw _QudsPropagate($temp); return ($temp as Ok).value; })()';
  }

  void _emitIndexAssignment(IndexAssignment node) {
    final receiver = '_qo${_temps++}';
    final key = '_qi${_temps++}';
    final at = '_qi${_temps++}';
    final base = _bareType(model.types[node.target.object]);
    final list =
        base.startsWith('List<') || model.dartShapes[base]?.listElement != null;
    line('{');
    _depth++;
    line('final $receiver = ${expression(node.target.object)};');
    line('final $key = ${expression(node.target.index)};');
    if (list) line('final $at = $key < 0 ? $receiver.length + $key : $key;');
    final slot = '$receiver[${list ? at : key}]';
    final targetType = model.types[node.target]!;
    if (node.operator == '+=' && targetType.startsWith('Map<')) {
      final old = '_qv${_temps++}';
      final added = '_qv${_temps++}';
      line('final $old = $slot;');
      line('final $added = ${expression(node.value)};');
      line(
          '$slot = <${_dartType(targetType.substring(4, targetType.length - 1))}>{...$old, ...$added};');
    } else {
      line('$slot ${node.operator} ${expression(node.value)};');
    }
    _depth--;
    line('}');
  }

  String _index(IndexExpression node, {bool constantContext = false}) {
    final object = expression(node.object, constantContext: constantContext);
    final index = expression(node.index, constantContext: constantContext);
    final bare = _bareType(model.types[node.object]);
    if (bare == 'String') {
      _useAt = true;
      return '_qAt($object, $index)';
    }
    if (bare.startsWith('List<') ||
        model.dartShapes[bare]?.listElement != null) {
      final items = '_qo${_temps++}';
      final at = '_qi${_temps++}';
      return '(() { final $items = $object; final $at = $index; return $items[$at < 0 ? $items.length + $at : $at]; })()';
    }
    return '$object[$index]';
  }

  String? _lowerCollection(
      CallExpression node, MemberAccess member, String dartName,
      {bool constantContext = false}) {
    final recv =
        '(${expression(member.object, constantContext: constantContext)})';
    String arg(int parameter) {
      final order = model.argumentOrder[node];
      final index = order != null && parameter < order.length
          ? order[parameter]
          : parameter;
      return expression(node.arguments[index].value,
          constantContext: constantContext);
    }

    switch (dartName) {
      case '_qmap':
        return '$recv.map(${arg(0)}).toList()';
      case '_qfold':
        final seed = model.types[node] ?? 'Object';
        return '$recv.fold<${_dartType(seed)}>(${arg(0)}, ${arg(1)})';
      case '_qreduce':
        return '$recv.reduce(${arg(0)})';
      case '_qsum':
        final type = model.types[node] ?? 'num';
        final zero = type == 'double' ? '0.0' : '0';
        return '$recv.fold<${_dartType(type)}>($zero, (a, b) => a + b)';
      case '_qmin' || '_qmax':
        _useLeast = true;
        return '_qLeast($recv, ${dartName == '_qmax'})';
      case '_qcount':
        return '$recv.length';
      case '_qcountWhere':
        return '$recv.where(${arg(0)}).length';
      case '_qfind':
        return '$recv.where(${arg(0)}).firstOrNull';
      case '_qfindLast':
        return '$recv.where(${arg(0)}).lastOrNull';
      case '_qtake':
        return '$recv.take(${arg(0)}).toList()';
      case '_qskip' || '_qdrop':
        return '$recv.skip(${arg(0)}).toList()';
      case '_qtakeLast' || '_qdropLast':
        final items = '_qi${_temps++}';
        final count = '_qn${_temps++}';
        final kept = dartName == '_qtakeLast'
            ? 'if ($count >= $items.length) return $items; return $items.sublist($items.length - $count);'
            : 'if ($count >= $items.length) return $items.sublist(0, 0); return $items.sublist(0, $items.length - $count);';
        return '(() { final $items = $recv.toList(); final $count = ${arg(0)}; if ($count < 0) throw RangeError.range($count, 0, null, "count"); $kept })()';
      case '_qtakeText' || '_qdropText' || '_qtakeLastText' || '_qdropLastText':
        final text = '_qt${_temps++}';
        final count = '_qn${_temps++}';
        final kept = switch (dartName) {
          '_qtakeText' =>
            'return $count >= $text.length ? $text : $text.substring(0, $count);',
          '_qdropText' =>
            'return $count >= $text.length ? "" : $text.substring($count);',
          '_qtakeLastText' =>
            'return $count >= $text.length ? $text : $text.substring($text.length - $count);',
          _ =>
            'return $count >= $text.length ? "" : $text.substring(0, $text.length - $count);',
        };
        return '(() { final $text = $recv; final $count = ${arg(0)}; if ($count < 0) throw RangeError.range($count, 0, null, "count"); $kept })()';
      case '_qclamp':
        final bare = _bareType(model.types[member.object]);
        final call = '$recv.clamp(${arg(0)}, ${arg(1)})';
        if (bare == 'int') return call;
        return '($call as ${_dartType(bare.isEmpty ? 'num' : bare)})';
      case '_qzip':
        final left = '_qa${_temps++}';
        final right = '_qb${_temps++}';
        final count = '_qn${_temps++}';
        final index = '_qi${_temps++}';
        final returned = model.types[node] ?? 'List<(Object, Object)>';
        final pair = returned.startsWith('List<') && returned.endsWith('>')
            ? returned.substring(5, returned.length - 1)
            : '(Object, Object)';
        return '(() { final $left = $recv.toList(); final $right = (${arg(0)}).toList(); final $count = $left.length < $right.length ? $left.length : $right.length; return <${_dartType(pair)}>[for (var $index = 0; $index < $count; $index = $index + 1) ($left[$index], $right[$index])]; })()';
      case '_qpadStart' || '_qpadEnd':
        final method = dartName == '_qpadStart' ? 'padLeft' : 'padRight';
        final text = '_qt${_temps++}';
        final width = '_qw${_temps++}';
        final fill = '_qf${_temps++}';
        final order = model.argumentOrder[node];
        final fillAt = order != null && order.length > 1 ? order[1] : -1;
        final fillCode = fillAt >= 0
            ? expression(node.arguments[fillAt].value,
                constantContext: constantContext)
            : '" "';
        return '(() { final $text = $recv; final $width = ${arg(0)}; final $fill = $fillCode; if ($width < 0) throw RangeError.range($width, 0, null, "width"); return $text.$method($width, $fill); })()';
      case '_qfixed':
        final value = '_qv${_temps++}';
        final digits = '_qd${_temps++}';
        return '(() { final $value = $recv; final $digits = ${arg(0)}; if ($digits < 0) throw RangeError.range($digits, 0, 20, "digits"); return $value.toDouble().toStringAsFixed($digits); })()';
      case '_qpad':
        final value = '_qv${_temps++}';
        final width = '_qw${_temps++}';
        final negative = '_ng${_temps++}';
        final digits = '_qd${_temps++}';
        final room = '_kr${_temps++}';
        final body = '_kb${_temps++}';
        return '(() { final $value = $recv; final $width = ${arg(0)}; if ($width < 0) throw RangeError.range($width, 0, null, "width"); final $negative = $value < 0; final $digits = ($negative ? -$value : $value).toString(); final $room = $negative ? $width - 1 : $width; final $body = $digits.padLeft($room < 0 ? 0 : $room, "0"); return $negative ? "-" + $body : $body; })()';
      case '_qsorted' || '_qsortedBy':
        final returned = model.types[node] ?? 'List<Object>';
        final inner = returned.startsWith('List<') && returned.endsWith('>')
            ? returned.substring(5, returned.length - 1)
            : 'Object';
        final list = 'List<${_dartType(inner)}>.of($recv)';
        final compare = dartName == '_qsortedBy' ? arg(0) : '';
        return '($list..sort($compare))';
      case '_qunique':
        return '$recv.toSet().toList()';
      case '_qflat':
        return '$recv.expand((item) => item).toList()';
      case '_qgroup':
        _useGroup = true;
        return '_qGroup($recv, ${arg(0)})';
      case '_qjoin':
        return '$recv.join()';
      case '_qjoinSep':
        return '$recv.join(${arg(0)})';
      case '_qsubstring':
        final end = node.arguments.length == 2 ? ', ${arg(1)}' : '';
        return '$recv.substring(${arg(0)}$end)';
      default:
        return null;
    }
  }

  /// `expect(actual, matcher)` uses Dart's matchers. Named `reason` and `skip`
  /// stay named. Both sides are read once, in source order.
  String _expect(CallExpression node) {
    _useChecks = true;
    final positional = <String>[];
    final named = <String>[];
    for (final argument in node.arguments) {
      final value = expression(argument.value);
      if (argument.name == null) {
        positional.add(value);
      } else {
        named.add('${argument.name}: $value');
      }
    }
    final helper = model.references[node.callee]?.dartName ?? '_qrun.qExpect';
    return '$helper(${[...positional, ...named].join(', ')})';
  }

  String? _functionValueVariadicList(
      CallExpression node, String Function(int) value) {
    final element = model.functionValueVariadicElements[node];
    if (element == null) return null;
    final pieces = [
      for (final index in model.variadicArguments[node] ?? const <int>[])
        value(index)
    ];
    return '<${_dartType(element)}>[${pieces.join(', ')}]';
  }

  String _nativeInvocation(CallExpression node, String target,
      MemberAccess? member, bool constantContext) {
    final layout = model.nativeArguments[node]!;
    final reordered =
        List.generate(layout.length, (i) => layout[i].$2 != i).any((v) => v);
    String arguments(String Function(int) value) {
      final head = layout
          .map((slot) =>
              '${slot.$1 == null ? '' : '${slot.$1}: '}${value(slot.$2)}')
          .join(', ');
      final tail = _functionValueVariadicList(node, value);
      if (tail == null) return head;
      return [if (head.isNotEmpty) head, tail].join(', ');
    }

    if (!reordered || constantContext) {
      return '$target(${arguments((i) => expression(node.arguments[i].value, constantContext: constantContext))})';
    }
    // Invocation operands remain outside the closure: await stays in its
    // original async scope and a Future result is not accidentally flattened.
    final parameters = <String>[];
    final inputs = <String>[];
    if (model.functionValueCalls.contains(node)) {
      final callable = '_qnf${_temps++}';
      parameters.add('${_dartType(model.types[node.callee]!)} $callable');
      inputs.add(target);
      target = callable;
      member = null;
    }
    if (member != null &&
        model.types[member.object] != 'prefix' &&
        model.references[member.object]?.namespace == null) {
      final receiver = '_qnr${_temps++}';
      parameters.add('${_dartType(model.types[member.object]!)} $receiver');
      inputs.add(expression(member.object));
      final generic = model.inferredTypeArguments[node];
      final suffix =
          generic == null ? '' : '<${generic.map(_dartType).join(', ')}>';
      target = '$receiver.${member.name}$suffix';
    }
    final values = <String>[];
    for (var i = 0; i < node.arguments.length; i++) {
      final value = '_qna${_temps++}';
      values.add(value);
      parameters.add(
          '${_dartType(model.implicitConversions[node.arguments[i].value]?.resultType ?? model.types[node.arguments[i].value]!)} $value');
      inputs.add(expression(node.arguments[i].value));
    }
    return '((${parameters.join(', ')}) => $target(${arguments((i) => values[i])}))(${inputs.join(', ')})';
  }

  String _packetCall(
      CallExpression node, String target, List<int> order, String returned,
      {required bool gap, int? variadicIndex}) {
    final lines = <String>[];
    final temps = <String>[];
    for (var i = 0; i < node.arguments.length; i++) {
      final temp = '_qpk${_temps++}';
      temps.add(temp);
      final value = node.arguments[i].value;
      final text = value is SpreadElement
          ? expression(value.operand)
          : expression(value);
      lines.add('final $temp = $text;');
    }
    final inputs = <String>[];
    final present = <String>[];
    for (var i = 0; i < order.length; i++) {
      final index = order[i];
      if (i == variadicIndex) {
        inputs.add(_packetVariadicList(node, temps));
        present.add('true');
      } else if (index < 0) {
        inputs.add('null');
        present.add('false');
      } else {
        inputs.add(temps[index]);
        present.add('true');
      }
    }
    final call = gap
        ? '_\$qudsCallGap<$returned>($target, <Object?>[${inputs.join(', ')}], <bool>[${present.join(', ')}])'
        : '$target(<Object?>[${inputs.join(', ')}], <bool>[${present.join(', ')}])';
    if (gap) _useGap = true;
    final result = returned == 'void' ? call : 'return $call';
    return '(() { ${lines.join(' ')} $result; })()';
  }

  String _variadicListType(String declared) {
    final rendered = _dartType(declared);
    if (rendered.startsWith('List<') && rendered.endsWith('>')) return rendered;
    return 'List<$rendered>';
  }

  String _packetVariadicList(CallExpression node, List<String> temps) {
    final element =
        _dartType(model.functionValueVariadicElements[node] ?? 'Object?');
    final pieces = <String>[];
    for (final index in model.variadicArguments[node] ?? const <int>[]) {
      final value = node.arguments[index].value;
      pieces.add(value is SpreadElement
          ? (value.nullAware ? '...?${temps[index]}' : '...${temps[index]}')
          : temps[index]);
    }
    return '<$element>[${pieces.join(', ')}]';
  }

  String _providerGapCall(
      CallExpression node,
      String target,
      MemberAccess? member,
      FunctionDeclaration function,
      List<Parameter> parameters,
      List<int> order) {
    final owner = model.providerDefaultMethods[function];
    final gapName = owner == null
        ? providerGapBridgeName(function)
        : providerMethodGapBridgeName(owner, function);
    final typeStart = target.indexOf('<');
    final plain = typeStart < 0 ? target : target.substring(0, typeStart);
    final suffix = typeStart < 0 ? '' : target.substring(typeStart);
    final dot = plain.lastIndexOf('.');
    final prefix = dot < 0 ? '' : plain.substring(0, dot + 1);
    final bridge = '$prefix$gapName$suffix';
    return _packetCall(
        node, bridge, order, _dartType(model.types[node] ?? 'Object?'),
        gap: false);
  }

  String _constructorGapCall(
      CallExpression node, ClassDeclaration type, bool constantContext) {
    final constructor = type.constructors
        .where((item) => item.name == null && !item.factory)
        .firstOrNull;
    final parent =
        constructor == null ? _synthesizedParentConstructor(type) : null;
    final name = constructor == null
        ? providerSynthesizedConstructorBridgeName(type)
        : providerConstructorBridgeName(type, constructor);
    String owner;
    var suffix = '';
    if (node.callee is TypeApplication) {
      final applied = node.callee as TypeApplication;
      owner = expression(applied.callee, constantContext: constantContext);
      suffix = '<${applied.arguments.map(_dartType).join(', ')}>';
    } else {
      owner = expression(node.callee, constantContext: constantContext);
      if (model.inferredTypeArguments[node] case final arguments?) {
        suffix = '<${arguments.map(_dartType).join(', ')}>';
      }
    }
    final count = constructor?.parameters.length ??
        (parent?.parameters.length ?? 0) +
            type.fields
                .where((field) =>
                    !field.isStatic && !field.isEvent && field.lazyBody == null)
                .length;
    final order = model.argumentOrder[node] ?? List<int>.filled(count, -1);
    return _packetCall(node, '$owner.$name$suffix', order,
        _dartType(model.types[node] ?? type.name),
        gap: false);
  }

  String call(CallExpression node, {bool constantContext = false}) {
    if (model.packetValueCalls.contains(node)) {
      return _packetCall(
          node,
          expression(node.callee),
          model.argumentOrder[node] ?? const <int>[],
          _dartType(model.types[node] ?? 'Object?'),
          gap: false,
          variadicIndex: model.functionValueVariadicIndex[node]);
    }
    if (model.functionValueGapCalls.contains(node)) {
      return _packetCall(
          node,
          expression(node.callee),
          model.argumentOrder[node] ?? const <int>[],
          _dartType(model.types[node] ?? 'Object?'),
          gap: true);
    }
    if (model.constructorGapTargets[node] case final type?) {
      return _constructorGapCall(node, type, constantContext);
    }
    if (model.functionValueCalls.contains(node)) {
      final target = expression(node.callee);
      return _nativeInvocation(
          node,
          node.callee is Identifier ? target : '($target)',
          null,
          constantContext);
    }
    if (model.references[node.callee] == null) {
      final callee = expression(node.callee, constantContext: constantContext);
      final arguments = node.arguments.map((argument) {
        final value =
            expression(argument.value, constantContext: constantContext);
        return argument.name == null ? value : '${argument.name}: $value';
      }).join(', ');
      return '($callee)($arguments)';
    }
    final targetSymbol = model.references[node.callee]!;
    if (targetSymbol.name == 'ConversionError' &&
        targetSymbol.function == null) {
      _requireReadonlyRuntime();
      return '$_readonlyRuntime.ConversionError(${expression(node.arguments.single.value)})';
    }
    if (targetSymbol.library == 'check') _useChecks = true;
    if (targetSymbol.name == 'missing') _useOptional = true;
    if (targetSymbol.library == 'check' &&
        (targetSymbol.name == 'expect' || targetSymbol.name == 'expectLater')) {
      return _expect(node);
    }
    if (targetSymbol.library == 'check' &&
        (targetSymbol.name == 'isA' || targetSymbol.name == 'isSorted') &&
        node.callee is TypeApplication) {
      final types =
          (node.callee as TypeApplication).arguments.map(_dartType).join(', ');
      return '${targetSymbol.dartName}<$types>()';
    }
    if (targetSymbol.name == 'present') {
      _useOptional = true;
      return 'Optional.present(${expression(node.arguments.single.value, constantContext: constantContext)})';
    }
    if (targetSymbol.name == 'Ok' || targetSymbol.name == 'Error') {
      _useResult = true;
      final value = expression(node.arguments.single.value,
          constantContext: constantContext);
      final type = model.types[node] ?? 'Result<Object, Object>';
      final inner = type.startsWith('Result<')
          ? type.substring(7, type.length - 1)
          : 'Object, Object';
      final splitAt = inner.indexOf(',');
      final success = inner.substring(0, splitAt).trim();
      final error = inner.substring(splitAt + 1).trim();
      return '${targetSymbol.name}<$success, $error>($value)';
    }
    if (targetSymbol.classDeclaration != null) {
      if (targetSymbol.classDeclaration!.kind == 'extensionType') {
        final value = node.arguments.isEmpty
            ? ''
            : expression(node.arguments.first.value,
                constantContext: constantContext);
        final checked = targetSymbol.classDeclaration!.requirements.isNotEmpty;
        final ctor = model.constants.containsKey(node) && checked
            ? '${targetSymbol.name}._'
            : targetSymbol.name;
        return '$ctor($value)';
      }
      final fields = targetSymbol.classCase?.fields ??
          [
            ..._inherited(targetSymbol.classDeclaration!),
            ...targetSymbol.classDeclaration!.fields.where((field) =>
                !field.isStatic && !field.isEvent && field.lazyBody == null)
          ];
      final declared = targetSymbol.classDeclaration!.name;
      final ctor = targetSymbol.classCase?.name ??
          (targetSymbol.dartName.contains('.')
              ? targetSymbol.dartName
              : declared);
      final order = model.argumentOrder[node] ?? const <int>[];
      final parts = <String>[];
      for (var i = 0; i < fields.length && i < order.length; i++) {
        final index = order[i];
        if (index < 0) continue;
        parts.add(
            '${fields[i].name}: ${expression(node.arguments[index].value, constantContext: constantContext)}');
      }
      final rendered = _constructed(node, ctor);
      if (node.arguments.length <= 1) {
        return '$rendered(${parts.join(', ')})';
      }
      final declarations = <String>[];
      final named = <String>[];
      for (var i = 0; i < node.arguments.length; i++) {
        declarations.add(
            'final _qa$i = ${expression(node.arguments[i].value, constantContext: constantContext)};');
      }
      for (var i = 0; i < fields.length && i < order.length; i++) {
        final index = order[i];
        if (index < 0) continue;
        named.add('${fields[i].name}: _qa$index');
      }
      return '(() { ${declarations.join(' ')} return $rendered(${named.join(', ')}); })()';
    }
    final sourceCallee = node.callee is TypeApplication
        ? (node.callee as TypeApplication).callee
        : node.callee;
    final member = sourceCallee is MemberAccess ? sourceCallee : null;
    if (member != null && targetSymbol.dartName.startsWith('_q')) {
      final lowered = _lowerCollection(node, member, targetSymbol.dartName,
          constantContext: constantContext);
      if (lowered != null) return lowered;
    }
    if (member != null &&
        member.name == 'copyWith' &&
        !targetSymbol.external &&
        targetSymbol.function == null &&
        targetSymbol.classDeclaration == null) {
      _useOptional = true;
      final args = node.arguments
          .map((argument) =>
              '${argument.name}: ${expression(argument.value, constantContext: constantContext)}')
          .join(', ');
      return '${expression(member.object, constantContext: constantContext)}.copyWith($args)';
    }
    final constructed = targetSymbol.nativeConstructor &&
            (node.callee is Identifier ||
                node.callee is TypeApplication &&
                    (node.callee as TypeApplication).callee is Identifier)
        ? _dartType(model.types[node]!)
        : _constructed(node, targetSymbol.name);
    final inheritedStatic =
        member == null ? null : model.staticValueOwners[member];
    var target = member != null
        ? '${inheritedStatic == null ? expression(member.object, constantContext: constantContext) : _dartType(inheritedStatic)}.${model.references[member]?.dartName ?? member.name}'
        : node.callee is Identifier &&
                model.implicitThis.contains(node.callee as Identifier)
            ? 'this.${targetSymbol.dartName}'
            : constructed != targetSymbol.name &&
                    (node.callee is Identifier ||
                        node.callee is TypeApplication)
                ? constructed
                : targetSymbol.dartName;
    if (node.callee case TypeApplication applied) {
      final original = model.references[applied.callee];
      final explicitQudsConstructor =
          original?.classDeclaration != null && targetSymbol.function != null;
      if (explicitQudsConstructor) {
        target = member == null
            ? original!.dartName
            : '${expression(member.object, constantContext: constantContext)}.${original!.classDeclaration!.name}';
      }
      if (explicitQudsConstructor ||
          original?.function != null && original?.classDeclaration == null ||
          targetSymbol.external &&
              model.nativeArguments.containsKey(node) &&
              (!targetSymbol.nativeConstructor || member != null)) {
        target += '<${applied.arguments.map(_dartType).join(', ')}>';
      }
    } else if (model.inferredTypeArguments[node] case final arguments?) {
      if (!targetSymbol.nativeConstructor || member != null)
        target += '<${arguments.map(_dartType).join(', ')}>';
    }
    if ((targetSymbol.dartName == 'min' || targetSymbol.dartName == 'max') &&
        !targetSymbol.external &&
        targetSymbol.function == null) {
      final left = '_qa${_temps++}';
      final right = '_qb${_temps++}';
      final op = targetSymbol.dartName == 'min' ? '<=' : '>=';
      return '(() { final $left = ${expression(node.arguments[0].value, constantContext: constantContext)}; final $right = ${expression(node.arguments[1].value, constantContext: constantContext)}; return $left $op $right ? $left : $right; })()';
    }
    if (targetSymbol.dartName == 'range' && !targetSymbol.external) {
      final integer = model.types[node] == 'Range<int>';
      if (integer) {
        _useRange = true;
      } else {
        _useNumRange = true;
      }
      final helper = integer ? '_qRange' : '_qNumRange';
      if (node.arguments.length == 1) {
        return '$helper(0, ${expression(node.arguments.single.value, constantContext: constantContext)}, true)';
      }
      return '$helper(${expression(node.arguments[0].value, constantContext: constantContext)}, ${expression(node.arguments[1].value, constantContext: constantContext)}, true)';
    }
    if (targetSymbol.external) {
      if (model.nativeArguments.containsKey(node))
        return _nativeInvocation(node, target, member, constantContext);
      final parts = [
        for (final argument in node.arguments)
          argument.name == null
              ? expression(argument.value, constantContext: constantContext)
              : '${argument.name}: ${expression(argument.value, constantContext: constantContext)}'
      ];
      return '$target(${parts.join(', ')})';
    }
    final parameters = targetSymbol.function?.parameters ?? const <Parameter>[];
    final providerFunction = targetSymbol.function;
    final providerOrder = model.argumentOrder[node];
    if (!constantContext &&
        model.providerGapCalls.contains(node) &&
        providerFunction != null &&
        providerOrder != null) {
      return _providerGapCall(
          node, target, member, providerFunction, parameters, providerOrder);
    }
    if (!constantContext &&
        providerFunction != null &&
        (model.providerDefaultFunctions.contains(providerFunction) ||
            model.providerDefaultMethods.containsKey(providerFunction)) &&
        providerOrder != null &&
        !parameters.asMap().entries.any((entry) =>
            entry.value.kind == ParameterKind.optionalPositional &&
            providerOrder[entry.key] == -1 &&
            providerOrder.skip(entry.key + 1).any((index) => index >= 0)) &&
        (providerOrder.contains(-1) ||
            (model.providerDefaultMethods.containsKey(providerFunction) &&
                member?.nullAware == true)) &&
        !node.arguments.any((argument) => _isHole(argument.value))) {
      // Capture all written arguments in source order before the provider
      // resolves omitted defaults. Its private symbols never enter this scope.
      final supplied = <String>[];
      final resolved = <String>[];
      final methodOwner = model.providerDefaultMethods[providerFunction];
      String? methodReceiver;
      if (methodOwner != null && !providerFunction.isStatic && member != null) {
        methodReceiver = '_qreceiver${_temps++}';
        resolved.add('final $methodReceiver = ${expression(member.object)};');
        if (member.nullAware)
          resolved.add('if ($methodReceiver == null) return null;');
      }
      for (var i = 0; i < node.arguments.length; i++) {
        final temporary = '_qprovided${_temps++}';
        supplied.add(temporary);
        resolved
            .add('final $temporary = ${expression(node.arguments[i].value)};');
      }
      final passed = <String>[];
      for (var i = 0; i < parameters.length; i++) {
        final index = providerOrder[i];
        if (index < 0) continue;
        passed.add(
            '${parameters[i].isNamed ? '${parameters[i].name}: ' : ''}${supplied[index]}');
      }
      final typeStart = target.indexOf('<');
      final plain = typeStart < 0 ? target : target.substring(0, typeStart);
      final typeArguments = node.callee is TypeApplication
          ? (node.callee as TypeApplication).arguments
          : model.inferredTypeArguments[node];
      final suffix = typeArguments == null
          ? ''
          : '<${typeArguments.map(_dartType).join(', ')}>';
      final dot = plain.lastIndexOf('.');
      final receiverPrefix = methodReceiver == null
          ? (dot < 0 ? '' : plain.substring(0, dot + 1))
          : '$methodReceiver.';
      final bridgeName = methodOwner == null
          ? providerDefaultBridgeName(providerFunction)
          : providerMethodDefaultBridgeName(methodOwner, providerFunction);
      final bridge = '$receiverPrefix$bridgeName$suffix';
      final invoke = '$bridge(${passed.join(', ')})';
      return '(() { ${resolved.join(' ')} ${targetSymbol.type == 'void' ? '' : 'return '}$invoke; })()';
    }
    final variadic = parameters.indexWhere((parameter) => parameter.variadic);
    if (variadic >= 0) {
      final order = model.argumentOrder[node] ?? const <int>[];
      final fixed = <String>[];
      for (var i = 0; i < variadic; i++) {
        final index = i < order.length ? order[i] : -1;
        if (index >= 0) {
          fixed.add(expression(node.arguments[index].value,
              constantContext: constantContext));
        }
      }
      final pieces = <String>[];
      for (final index in model.variadicArguments[node] ?? const <int>[]) {
        final value = node.arguments[index].value;
        if (value is SpreadElement) {
          final text =
              expression(value.operand, constantContext: constantContext);
          pieces.add(value.nullAware ? '...?$text' : '...$text');
        } else {
          pieces.add(expression(value, constantContext: constantContext));
        }
      }
      final list =
          '<${_dartType(model.instantiatedParameterTypes[node]?[variadic] ?? parameters[variadic].type)}>[${pieces.join(', ')}]';
      return '$target(${[...fixed, list].join(', ')})';
    }
    final order = model.argumentOrder[node];
    final holes = node.arguments.where((a) => _isHole(a.value)).length;
    final simple = holes == 0 &&
        (order == null || !order.contains(-1)) &&
        node.arguments.every((a) => a.name == null);
    if (simple) {
      return '$target(${node.arguments.map((a) => expression(a.value, constantContext: constantContext)).join(', ')})';
    }
    if (constantContext && holes == 0) {
      final values = <String>[];
      final arranged = order ?? List.generate(parameters.length, (i) => i);
      for (var i = 0; i < arranged.length; i++) {
        final index = arranged[i];
        if (index >= 0) {
          values.add(
              expression(node.arguments[index].value, constantContext: true));
        } else if (i < parameters.length &&
            parameters[i].defaultValue != null) {
          values.add(
              expression(parameters[i].defaultValue!, constantContext: true));
        }
      }
      return '$target(${values.join(', ')})';
    }
    // Evaluate written arguments exactly once, left to right, before arranging
    // them in declaration order for Dart's positional ABI.
    final declarations = <String>[];
    String? defaultReceiver;
    if (member != null &&
        targetSymbol.function?.isStatic == false &&
        model.types[member.object] != 'prefix' &&
        model.references[member.object]?.namespace == null) {
      final receiver = '_qr${_temps++}';
      declarations.add(
          'final $receiver = ${expression(member.object, constantContext: constantContext)};');
      final method = model.references[member]?.dartName ?? member.name;
      final typeArguments = node.callee is TypeApplication
          ? (node.callee as TypeApplication).arguments
          : model.inferredTypeArguments[node];
      final suffix = typeArguments == null
          ? ''
          : '<${typeArguments.map(_dartType).join(', ')}>';
      target = '$receiver.$method$suffix';
      defaultReceiver = receiver;
    }
    final values = <String>[];
    final holeNames = <String>[];
    final holeTypes = <String>[];
    final subst = <String, String>{};
    for (var i = 0; i < node.arguments.length; i++) {
      if (_isHole(node.arguments[i].value)) continue;
      declarations.add(
          'final _qa$i = ${expression(node.arguments[i].value, constantContext: constantContext)};');
    }
    final arranged = order ?? List.generate(node.arguments.length, (i) => i);
    for (var i = 0; i < arranged.length; i++) {
      final index = arranged[i];
      if (index >= 0 && !_isHole(node.arguments[index].value)) {
        values.add('_qa$index');
        if (i < parameters.length) {
          subst[model.declarations[parameters[i]]!.dartName] = '_qa$index';
        }
      } else if (index >= 0 && _isHole(node.arguments[index].value)) {
        final hole = '_qh${holeNames.length}';
        holeNames.add(hole);
        holeTypes.add(i < parameters.length
            ? (model.instantiatedParameterTypes[node]?[i] ?? parameters[i].type)
            : 'Object');
        values.add(hole);
      } else if (i < parameters.length && parameters[i].defaultValue != null) {
        final saved = _names;
        _names = subst;
        final savedReceiver = _defaultReceiver;
        _defaultReceiver = defaultReceiver ?? savedReceiver;
        final savedBindings = _interfaceTypeBindings;
        final substitution = model.constructorSubstitutions[node];
        if (substitution != null) {
          _interfaceTypeBindings = {..._interfaceTypeBindings, ...substitution};
        }
        late String value;
        try {
          value = expression(parameters[i].defaultValue!);
        } finally {
          _names = saved;
          _defaultReceiver = savedReceiver;
          _interfaceTypeBindings = savedBindings;
        }
        declarations.add('final _qd$i = $value;');
        values.add('_qd$i');
        subst[model.declarations[parameters[i]]!.dartName] = '_qd$i';
      }
    }
    final invocation = '$target(${values.join(', ')})';
    final returnsVoid =
        targetSymbol.type == 'void' || targetSymbol.type == 'Future<void>';
    final body = returnsVoid ? '$invocation;' : 'return $invocation;';
    if (holeNames.isNotEmpty) {
      final signature = [
        for (var i = 0; i < holeNames.length; i++)
          '${holeTypes[i]} ${holeNames[i]}'
      ].join(', ');
      return '(($signature) { ${declarations.join(' ')} $body })';
    }
    return '(() { ${declarations.join(' ')} $body })()';
  }

  bool _isHole(Expression node) => node is Identifier && node.name == '_';

  bool _containsDoReturn(List<Statement> body) {
    for (final statement in body) {
      if (_doReturns(statement)) return true;
    }
    return false;
  }

  bool _doReturns(Statement node) => switch (node) {
        IfStatement() =>
          node.thenBody.any(_doReturns) || node.elseBody.any(_doReturns),
        ForStatement() =>
          node.body.any(_doReturns) || node.elseBody.any(_doReturns),
        WhileStatement() =>
          node.body.any(_doReturns) || node.elseBody.any(_doReturns),
        GuardedStatement() => _doReturns(node.statement),
        IfCaseStatement() => node.body.any(_doReturns),
        IfLetStatement() =>
          node.thenBody.any(_doReturns) || node.elseBody.any(_doReturns),
        WhenStatement() => node.body.any(_doReturns),
        UsingStatement() => node.body.any(_doReturns),
        RepeatStatement() =>
          node.body.any(_doReturns) || node.elseBody.any(_doReturns),
        CForStatement() =>
          node.body.any(_doReturns) || node.elseBody.any(_doReturns),
        LabelStatement() => _doReturns(node.statement),
        MatchStatement() => node.arms.any((arm) => arm.body.any(_doReturns)),
        ExpressionStatement() => _exprReturns(node.expression),
        Binding() => _exprReturns(node.value),
        ReturnStatement() => node.value != null && _exprReturns(node.value!),
        _ => false,
      };

  bool _exprReturns(Expression node) {
    if (node is DoExpression) return _containsFunctionReturn(node.body);
    if (node is LoopExpression) return _loopReturns(node.loop);
    if (node is WhereExpression) return _exprReturns(node.value);
    return false;
  }

  bool _loopReturns(Statement node) {
    final body = switch (node) {
      ForStatement() => node.body,
      WhileStatement() => node.body,
      RepeatStatement() => node.body,
      CForStatement() => node.body,
      _ => const <Statement>[],
    };
    return _containsFunctionReturn(body);
  }

  bool _containsFunctionReturn(List<Statement> body) =>
      body.any(_functionReturns);

  bool _functionReturns(Statement node) => switch (node) {
        ReturnStatement() => true,
        IfStatement() => node.thenBody.any(_functionReturns) ||
            node.elseBody.any(_functionReturns),
        ForStatement() => node.body.any(_functionReturns) ||
            node.elseBody.any(_functionReturns),
        WhileStatement() => node.body.any(_functionReturns) ||
            node.elseBody.any(_functionReturns),
        RepeatStatement() => node.body.any(_functionReturns),
        CForStatement() => node.body.any(_functionReturns),
        GuardedStatement() => _functionReturns(node.statement),
        LabelStatement() => _functionReturns(node.statement),
        MatchStatement() =>
          node.arms.any((arm) => arm.body.any(_functionReturns)),
        _ => false,
      };

  void _beginLoop(List<Statement> elseBody) {
    final label = _pendingLabel;
    _pendingLabel = null;
    final braced = label != null && elseBody.isNotEmpty;
    if (braced) {
      line('$label: {');
      _depth++;
    } else if (label != null) {
      line('$label:');
    }
    String? hit;
    if (elseBody.isNotEmpty) {
      hit = '_qHit${_temps++}';
      line('var $hit = false;');
    }
    _emitLoops.add(_LoopEmit(hit, label, braced));
  }

  void _emitTry(TryStatement node) {
    final flag = node.elseBody.isEmpty ? null : '_qe${_temps++}';
    if (flag != null) line('var $flag = true;');
    final wrap = flag != null && node.finallyBody.isNotEmpty;
    if (wrap) {
      line('try {');
      _depth++;
    }
    line('try {');
    _depth++;
    statements(node.body);
    _depth--;
    for (final clause in node.catches) {
      final caught = model.declarations[clause]!;
      final trace = model.traces[clause];
      final names = trace == null
          ? caught.dartName
          : '${caught.dartName}, ${trace.dartName}';
      line(clause.type == null
          ? '} catch ($names) {'
          : '} on ${_dartType(clause.type!)} catch ($names) {');
      _depth++;
      if (flag != null) line('$flag = false;');
      statements(clause.body);
      _depth--;
    }
    if (flag == null && node.finallyBody.isNotEmpty) {
      line('} finally {');
      _depth++;
      statements(node.finallyBody);
      _depth--;
      line('}');
      return;
    }
    line('}');
    if (flag != null) {
      line('if ($flag) {');
      _depth++;
      statements(node.elseBody);
      _depth--;
      line('}');
    }
    if (wrap) {
      _depth--;
      line('} finally {');
      _depth++;
      statements(node.finallyBody);
      _depth--;
      line('}');
    }
  }

  void _endLoop(List<Statement> elseBody) {
    final frame = _emitLoops.removeLast();
    if (elseBody.isNotEmpty) {
      line('if (!${frame.hit}) {');
      _depth++;
      statements(elseBody);
      _depth--;
      line('}');
    }
    if (frame.braced) {
      _depth--;
      line('}');
    }
  }

  void _markBreak(String? label) {
    if (label == null) {
      if (_emitLoops.isNotEmpty && _emitLoops.last.hit != null) {
        line('${_emitLoops.last.hit} = true;');
      }
      return;
    }
    for (var i = _emitLoops.length - 1; i >= 0; i--) {
      final frame = _emitLoops[i];
      if (frame.label != label) continue;
      if (frame.hit != null) line('${frame.hit} = true;');
      return;
    }
  }

  void _emitGuarded(GuardedStatement node) {
    final binding =
        node.statement is Binding ? node.statement as Binding : null;
    final hoisted = binding != null &&
        node.alternate != null &&
        !model.assignments.contains(binding);
    if (hoisted) {
      final symbol = model.declarations[binding]!;
      final modifier = symbol.mutable ? '' : 'final ';
      line('$modifier${_dartType(symbol.type)} ${symbol.dartName};');
    }
    void emitChosen(Expression? replacement) {
      if (hoisted) {
        final symbol = model.declarations[binding]!;
        final target = symbol.field ? 'this.${symbol.dartName}' : _cell(symbol);
        final value = replacement ?? binding.value;
        line('$target ${binding.operator} ${expression(value)};');
        return;
      }
      if (replacement != null) {
        _replace = _slot(node.statement);
        _replaceWith = replacement;
      }
      statement(node.statement);
      _replace = null;
      _replaceWith = null;
    }

    void emitBody() {
      emitChosen(null);
      if (node.alternate == null) return;
      _depth--;
      line('} else {');
      _depth++;
      emitChosen(node.alternate);
    }

    if (node.letName != null) {
      final bound = model.declarations[node]!;
      final temp = '_qn${_temps++}';
      _usePresent = true;
      line('final $temp = ${expression(node.condition)};');
      line('if (_qPresent($temp)) {');
      _depth++;
      line(
          'final ${_dartType(bound.type)} ${bound.dartName} = _qSome<${_dartType(bound.type)}>($temp);');
      emitBody();
      _depth--;
      line('}');
      return;
    }
    if (node.pattern != null) {
      _openPattern('if', node.condition, node.pattern!);
      _depth++;
      emitBody();
      _depth--;
      line('}');
      return;
    }
    line('if (${expression(node.condition, opaqueBool: true)}) {');
    _depth++;
    emitBody();
    _depth--;
    line('}');
  }

  Expression? _slot(Statement statement) => switch (statement) {
        ReturnStatement(:final value) => value,
        Binding(:final value) => value,
        IndexAssignment(:final value) => value,
        MemberAssignment(:final value) => value,
        ThrowStatement(:final value) => value,
        YieldStatement(:final value) => value,
        ResultStatement(:final value) => value,
        ExpressionStatement(:final expression) => _callSlot(expression),
        _ => null,
      };

  Expression? _callSlot(Expression expression) {
    if (expression is! CallExpression || expression.arguments.length != 1) {
      return null;
    }
    final argument = expression.arguments.single;
    if (argument.name != null || argument.value is SpreadElement) return null;
    return argument.value;
  }

  String _loopValue(LoopExpression node) {
    final saved = _inDo;
    _inDo = true;
    final body = _captureBlock(() {
      statement(node.loop);
      if (node.fallback != null) {
        line('return ${expression(node.fallback!)};');
      } else {
        line('return null;');
      }
    });
    _inDo = saved;
    return '(() {\n$body})()';
  }

  String _where(WhereExpression node) {
    final body = _captureBlock(() {
      for (final binding in node.bindings) {
        statement(binding);
      }
      line('return ${expression(node.value)};');
    });
    return '(() {\n$body})()';
  }

  String _captureBlock(void Function() emit) {
    final saved = _redirect;
    final buffer = StringBuffer();
    _redirect = buffer;
    emit();
    _redirect = saved;
    return buffer.toString();
  }

  String _do(DoExpression node) {
    final saved = _inDo;
    _inDo = true;
    final body = _captureBlock(() {
      for (final statement in node.body) {
        this.statement(statement);
      }
    });
    _inDo = saved;
    return '(() {\n$body})()';
  }

  String _capture(CaptureExpression node) {
    final copies = model.captures[node] ?? const [];
    final saved = copies
        .map((copy) =>
            'final ${_dartType(copy.$2.type)} ${copy.$2.dartName} = ${copy.$1.dartName};')
        .join(' ');
    return '(() { $saved return () => (${expression(node.body)}); })()';
  }

  String _conversionTarget(ConversionPlan plan) {
    var target = model.declarations[plan.function]!.dartName;
    // Root converters have generated private implementation names. Imported
    // providers expose stable public tear-offs from their original library.
    if (plan.library.isNotEmpty && plan.library != model.library) {
      final prefix =
          '_qCast${sha256Hex(utf8.encode(plan.library)).substring(0, 10)}';
      final sdk = sdkLibraryName(plan.library);
      final uri = model.backendTypeImports[prefix] ??
          (sdk == null
              ? Uri.file(plan.library.replaceFirst(RegExp(r'\.quds$'), '.dart'))
                  .toString()
              : sdkDartFileName(sdk));
      _imports.add("import '$uri' as $prefix;");
      target = '$prefix.${plan.function.name}';
      for (final directive in model.imports) {
        if (directive.export ||
            directive.uri.startsWith('quds:') ||
            directive.show.isNotEmpty ||
            librarySection(directive.uri) != null) continue;
        final home = resolveLibraryPath(directive.span.file, directive.uri);
        if (home != plan.library) continue;
        _imports.remove("import '$uri' as $prefix;");
        target = directive.prefix == null
            ? plan.function.name
            : '${_dartImportPrefix(directive.prefix!)}.${plan.function.name}';
        break;
      }
    }
    final types = plan.typeArguments.isEmpty
        ? ''
        : '<${plan.typeArguments.map(_dartType).join(', ')}>';
    return '$target$types';
  }

  String _convert(ConversionExpression node) {
    final custom = model.explicitConversions[node];
    if (custom != null) {
      final target = _conversionTarget(custom);
      final operand = expression(node.operand);
      if (!node.safe) return '$target($operand)';
      _requireReadonlyRuntime();
      return '$_readonlyRuntime.safeConvert($operand, $target)';
    }
    final sourceType = model.types[node.operand]!;
    final bareSource = nonNullableType(stripReadonlyType(sourceType));
    final bareTarget = nonNullableType(stripReadonlyType(node.type));
    if (bareSource == bareTarget &&
        !const {'int', 'double', 'num', 'String', 'bool'}
            .contains(bareSource)) {
      final cast = node.safe ? nullableType(node.type) : node.type;
      return '(${expression(node.operand)} as ${_dartType(cast)})';
    }
    _useConversion = true;
    final target = node.type.endsWith('?')
        ? node.type.substring(0, node.type.length - 1)
        : node.type;
    final cast = node.safe
        ? (node.type.endsWith('?') ? node.type : '${node.type}?')
        : node.type;
    return '(_qConvert(${expression(node.operand)}, ${quote(target)}, ${node.safe}) as ${_dartType(cast)})';
  }

  String _with(WithExpression node) {
    final type = model.types[node.receiver]!;
    final bare = type.endsWith('?') ? type.substring(0, type.length - 1) : type;
    final names = model.shapes[node] ?? node.fields;
    final written = {
      for (var i = 0; i < node.fields.length; i++)
        node.fields[i]: node.values[i]
    };
    final receiver = '_qw${_temps++}';
    final arguments = names.map((name) {
      final value = written[name];
      return value == null
          ? '$name: $receiver.$name'
          : '$name: ${expression(value)}';
    }).join(', ');
    final value = expression(node.receiver);
    final nullable = node.nullAware && type.endsWith('?');
    if (!nullable) {
      return '(() { final $receiver = $value; return $bare($arguments); })()';
    }
    return '(() { final $receiver = $value; if ($receiver != null) return $bare($arguments); return $receiver; })()';
  }

  String _dot(DotShorthand node) {
    final type = model.types[node]!;
    if (node.name == 'new') {
      final arguments = node.arguments ?? const <Argument>[];
      return '$type(${arguments.map((argument) => '${argument.name}: ${expression(argument.value)}').join(', ')})';
    }
    if (model.enumNames.contains(type)) return '$type.${node.name}';
    return '${node.name}()';
  }

  String _list(ListExpression node) {
    final type = model.types[node]!;
    final element = _dartType(type.substring(5, type.length - 1));
    final parts = <String>[];
    for (var i = 0; i < node.elements.length; i++) {
      final aware = i < node.nullAware.length && node.nullAware[i];
      parts.add(_piece(node.elements[i], element, aware));
    }
    final body = parts.join(', ');
    if (element == 'dynamic') return '[$body]';
    return '<$element>[$body]';
  }

  /// `Column(...)` is a Dart constructor. The binding keeps that type so a
  /// later list can use Dart's inference instead of `List<dynamic>`.
  String? _externalConstructor(Expression value) {
    if (value is! CallExpression || value.callee is! Identifier) return null;
    final name = (value.callee as Identifier).name;
    final symbol = model.references[value.callee];
    if (symbol == null || !symbol.external || name.isEmpty) return null;
    final unit = name.codeUnitAt(0);
    if (unit < 65 || unit > 90) return null;
    return name;
  }

  String _pieces(List<Expression> elements, String type) =>
      elements.map((element) => _piece(element, type, false)).join(', ');

  String _piece(Expression element, String type, bool aware) {
    if (element is SpreadElement) {
      final text = expression(element.operand);
      return element.nullAware ? '...?$text' : '...$text';
    }
    if (element is NullAwareElement) {
      return '?(${expression(element.value)})';
    }
    if (element is CollectionIf) {
      final thenList = _pieces(element.thenElements, type);
      final tail = element.elseElements.isEmpty
          ? ''
          : ' else ...<$type>[${_pieces(element.elseElements, type)}]';
      return 'if (${expression(element.condition, opaqueBool: true)}) ...<$type>[$thenList]$tail';
    }
    if (element is CollectionFor) {
      final symbol = model.declarations[element]!;
      final indexSymbol = model.loopIndexes[element];
      var iterable = expression(element.iterable);
      if (_bareType(model.types[element.iterable]) == 'String') {
        iterable = '($iterable).split(\'\')';
      }
      if (indexSymbol == null) {
        final guard = element.filter == null
            ? ''
            : ' if (${expression(element.filter!, opaqueBool: true)})';
        return 'for (final ${_dartType(symbol.type)} ${symbol.dartName} in $iterable)$guard ...<$type>[${_pieces(element.body, type)}]';
      }
      final record = '_qp${_temps++}';
      final body = _pieces(element.body, type);
      final filter = element.filter == null
          ? ''
          : 'if (!(${expression(element.filter!, opaqueBool: true)})) return <$type>[]; ';
      final bindings =
          'final ${indexSymbol.dartName} = $record.\$1; final ${symbol.dartName} = $record.\$2;';
      final source = model.loopPairs.contains(element)
          ? 'for (final ${_dartType('(${indexSymbol.type}, ${symbol.type})')} $record in $iterable)'
          : 'for (final $record in ($iterable).indexed)';
      return '$source ...(() { $bindings $filter return <$type>[$body]; })()';
    }
    final text = expression(element);
    return aware ? '?($text)' : text;
  }

  String _set(SetExpression node) {
    final type = model.types[node]!;
    final element = _dartType(type.substring(4, type.length - 1));
    final parts = <String>[];
    for (var i = 0; i < node.elements.length; i++) {
      final aware = i < node.nullAware.length && node.nullAware[i];
      parts.add(_piece(node.elements[i], element, aware));
    }
    return '<$element>{${parts.join(', ')}}';
  }

  String _unionClass(String type) =>
      'QudsUnion_${type.split(' | ').map((part) => _alt(part.trim())).join('_or_')}';

  String _alt(String type) => type.replaceAll(RegExp(r'[^A-Za-z0-9]'), '_');

  String _unionPattern(String matched, TypedPattern pattern) {
    _unions.add(matched);
    final cls = '${_unionClass(matched)}_${_alt(pattern.type)}';
    if (pattern.name == null) return '$cls()';
    return '$cls(value: final ${model.declarations[pattern]!.dartName})';
  }
