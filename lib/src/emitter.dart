  String _defaultBridgeName(FunctionDeclaration node) {
    final methodOwner = model.providerDefaultMethods[node];
    if (methodOwner != null)
      return providerMethodDefaultBridgeName(methodOwner, node);
    if (model.providerDefaultFunctions.contains(node))
      return providerDefaultBridgeName(node);
    final owners =
        model.classes.values.where((owner) => owner.methods.contains(node));
    final owner = owners.isEmpty ? '' : '${owners.first.name}_';
    return r'_$qudsDefault_' + owner + model.declarations[node]!.dartName;
  }

  void emitFunction(FunctionDeclaration node) {
    _emitFunctionBody(node);
    if (packetValueLayout(node.parameters)) _emitPacketBridge(node);
    _emitDefaultBridge(node);
  }

  void _emitDefaultBridge(FunctionDeclaration node) {
    if (!_defaultBridges.contains(node) || packetValueLayout(node.parameters)) {
      return;
    }
    final owner = model.providerDefaultMethods[node];
    if (owner?.kind == 'interface') {
      _emitInterfaceMember(node);
      return;
    }
    final savedGenerics = _openGenerics;
    _openGenerics = {
      ..._openGenerics,
      for (final p in node.typeParameters) p.name
    };
    try {
      final symbol = model.declarations[node]!;
      final lowering = QudsValueLowering(
          node,
          node.typeParameters.map((p) => p.name).toList(),
          node.parameters.map((p) => model.declarations[p]!.type).toList());
      final body = _valueAdapter(symbol.dartName, lowering, declaration: true);
      final returned = _dartType(symbol.type);
      final generics = _typeParameters(node.typeParameters, const []);
      line('${node.isStatic ? 'static ' : ''}$returned '
          '${_defaultBridgeName(node)}$generics$body');
      _emitConcreteGap(node);
    } finally {
      _openGenerics = savedGenerics;
    }
  }

  void _emitPacketBridge(FunctionDeclaration node) {
    final savedGenerics = _openGenerics;
    _openGenerics = {
      ..._openGenerics,
      for (final parameter in node.typeParameters) parameter.name
    };
    try {
      final symbol = model.declarations[node]!;
      final owner = model.classes.values
          .where((item) => item.methods.contains(node))
          .firstOrNull;
      final name = owner == null
          ? providerPacketBridgeName(node)
          : providerMethodPacketBridgeName(owner, node);
      final returned = _dartType(symbol.type);
      final generics = _typeParameters(node.typeParameters, const []);
      final prefix = owner != null && node.isStatic ? 'static ' : '';
      final target = node.isStatic || owner == null
          ? symbol.dartName
          : 'this.${symbol.dartName}';
      final body = _packetInvocation(node.parameters, target, returned);
      line('$prefix$returned $name$generics'
          '(List<Object?> \$qInputs, List<bool> \$qPresent) { $body }');
    } finally {
      _openGenerics = savedGenerics;
    }
  }

  /// Binds signature-order packet slots, then calls [target] in source order.
  String _packetInvocation(
      List<Parameter> parameters, String target, String returned) {
    final saved = _names;
    _names = {..._names};
    final statements = <String>[];
    try {
      final slots = packetSlots(parameters);
      for (var i = 0; i < slots.length; i++) {
        final parameter = slots[i];
        final declared = model.declarations[parameter]!;
        final element = _dartType(declared.type);
        final slot = '_qslot$i';
        final input = '\$qInputs[$i]';
        if (parameter.variadic) {
          final listType = _variadicListType(declared.type);
          final elementType = listType.substring(5, listType.length - 1);
          statements.add(
              'final $listType $slot = \$qPresent[$i] ? $input as $listType : <$elementType>[];');
        } else {
          final supplied =
              declared.type == 'Object?' || declared.type == 'dynamic'
                  ? input
                  : '$input as $element';
          final resolved = parameter.defaultValue == null
              ? supplied
              : '\$qPresent[$i] ? $supplied : ${expression(parameter.defaultValue!)}';
          statements.add('final $element $slot = $resolved;');
        }
        _names[declared.dartName] = slot;
      }
      final arguments = [
        for (final parameter in parameters)
          _names[model.declarations[parameter]!.dartName]!
      ];
      final invocation = '$target(${arguments.join(', ')})';
      final tail = returned == 'void' ? '$invocation;' : 'return $invocation;';
      return '${statements.join(' ')} $tail';
    } finally {
      _names = saved;
    }
  }

  void _emitConcreteGap(FunctionDeclaration node) {
    if (!positionalGapPossible(node.parameters)) return;
    final owner = model.providerDefaultMethods[node];
    final name = owner == null
        ? providerGapBridgeName(node)
        : providerMethodGapBridgeName(owner, node);
    final symbol = model.declarations[node]!;
    final returned = _dartType(symbol.type);
    final generics = _typeParameters(node.typeParameters, const []);
    final saved = _names;
    _names = {..._names};
    final statements = <String>[];
    final arguments = <String>[];
    try {
      for (var i = 0; i < node.parameters.length; i++) {
        final parameter = node.parameters[i];
        final declared = model.declarations[parameter]!;
        final dartType = _dartType(declared.type);
        final slot = '_qslot$i';
        final input = '\$qInputs[$i]';
        final supplied =
            declared.type == 'Object?' || declared.type == 'dynamic'
                ? input
                : '$input as $dartType';
        final resolved = parameter.defaultValue == null
            ? supplied
            : '\$qPresent[$i] ? $supplied : ${expression(parameter.defaultValue!)}';
        statements.add('final $dartType $slot = $resolved;');
        _names[declared.dartName] = slot;
        arguments.add(parameter.isNamed ? '${parameter.name}: $slot' : slot);
      }
    } finally {
      _names = saved;
    }
    final invoke = node.isStatic || owner == null
        ? symbol.dartName
        : 'this.${symbol.dartName}';
    line('${node.isStatic ? 'static ' : ''}$returned $name$generics'
        '(List<Object?> \$qInputs, List<bool> \$qPresent) '
        '{ ${statements.join(' ')} return $invoke(${arguments.join(', ')}); }');
  }

  String _interfaceSignature(FunctionDeclaration method,
      {bool declaration = false, List<String>? parameterTypes}) {
    final positional = <String>[];
    final named = <String>[];
    final optionalPositional = <String>[];
    for (var i = 0; i < method.parameters.length; i++) {
      final p = method.parameters[i];
      if (p.kind == ParameterKind.requiredNamed) {
        named.add(
            'required ${_dartType(parameterTypes?[i] ?? p.type)} ${p.name}');
      } else if (p.defaultValue == null) {
        positional.add(
            '${_dartType(parameterTypes?[i] ?? p.type)} \$qInterfaceArg$i');
      } else {
        if (!declaration) _useDefaultOmitted = true;
        (p.kind == ParameterKind.optionalPositional
                ? optionalPositional
                : named)
            .add(
                'Object? ${p.name}${declaration ? '' : ' = $_defaultOmitted'}');
      }
    }
    return [
      ...positional,
      if (optionalPositional.isNotEmpty) '[${optionalPositional.join(', ')}]',
      if (named.isNotEmpty) '{${named.join(', ')}}'
    ].join(', ');
  }

  void _emitInterfaceMember(FunctionDeclaration method) {
    final saved = _openGenerics;
    _openGenerics = {...saved, for (final p in method.typeParameters) p.name};
    try {
      line(
          '${_dartType(model.declarations[method]!.type)} ${_defaultBridgeName(method)}'
          '${_typeParameters(method.typeParameters)}(${_interfaceSignature(method, declaration: true)});');
      if (positionalGapPossible(method.parameters)) {
        line(
            '${_dartType(model.declarations[method]!.type)} ${providerMethodGapBridgeName(model.providerDefaultMethods[method]!, method)}'
            '${_typeParameters(method.typeParameters)}(List<Object?> \$qInputs, List<bool> \$qPresent);');
      }
    } finally {
      _openGenerics = saved;
    }
  }

  void _emitInterfaceDefaults(
