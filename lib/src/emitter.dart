import 'ast.dart';
import 'constants.dart';
import 'semantics.dart';

class DartEmitter {
  DartEmitter(this.model);
  final SemanticModel model;
  final _out = StringBuffer('// Generated by Quds MVP-0. Do not edit.\n');
  final _constNames = <String>{};
  final _topLevelConsts = <String>{};
  final _usedNames = <String>{};
  var _useBoolHelper = false;
  int _depth = 0;
  void line(String text) => _out.writeln('${'  ' * _depth}$text');
  String emit(Program program) {
    for (final node in program.statements) {
      _out.writeln();
      if (node is FunctionDeclaration) {
        final symbol = model.declarations[node]!;
        final parameters = node.parameters
            .map((p) => '${p.type} ${model.declarations[p]!.dartName}')
            .join(', ');
        if (node.expressionBody case final value?) {
          line(
              '${symbol.type} ${symbol.dartName}($parameters) => ${expression(value)};');
        } else {
          line('${symbol.type} ${symbol.dartName}($parameters) {');
          _depth++;
          statements(node.body!);
          _depth--;
          line('}');
        }
      } else {
        statement(node);
      }
    }
    final source = _suppressUnreadConsts(_out.toString());
    if (!_useBoolHelper) return source;
    // Dart treats a const bool as unreachable in `if` and `&&`/`||`. The
    // identity call keeps Quds's read-once short-circuit behavior while
    // leaving the generated condition a runtime value.
    return source.replaceFirst(
      '// Generated by Quds MVP-0. Do not edit.\n',
      '// Generated by Quds MVP-0. Do not edit.\n\n'
          'bool _qBool(bool value) => value;\n',
    );
  }

  /// Logical const folding can remove the only read of a const. Keep the
  /// binding and silence Dart's unused warning for that declaration.
  String _suppressUnreadConsts(String source) {
    final unread = _constNames.difference(_usedNames);
    if (unread.isEmpty) return source;
    final lines = source.split('\n');
    final rewritten = <String>[];
    for (final line in lines) {
      final trimmed = line.trimLeft();
      String? lint;
      for (final name in unread) {
        if (trimmed.startsWith('const ') && trimmed.contains(' $name =')) {
          lint = _topLevelConsts.contains(name)
              ? 'unused_element'
              : 'unused_local_variable';
          break;
        }
      }
      if (lint != null) {
        final indent = line.substring(0, line.length - trimmed.length);
        rewritten.add('$indent// ignore: $lint');
      }
      rewritten.add(line);
    }
    return rewritten.join('\n');
  }

  void statements(List<Statement> body) {
    for (final node in body) {
      statement(node);
    }
  }

  void statement(Statement node) {
    switch (node) {
      case Binding():
        if (model.assignments.contains(node)) {
          line(
              '${model.references[node]!.dartName} ${node.operator} ${expression(node.value)};');
        } else {
          final symbol = model.declarations[node]!;
          final modifier = symbol.constant
              ? 'const '
              : symbol.mutable
                  ? ''
                  : 'final ';
          if (symbol.constant) {
            _constNames.add(symbol.dartName);
            if (_depth == 0) _topLevelConsts.add(symbol.dartName);
          }
          final initializer =
              expression(node.value, constantContext: symbol.constant);
          line('$modifier${symbol.type} ${symbol.dartName} = $initializer;');
        }
      case ReturnStatement():
        line(node.value == null
            ? 'return;'
            : 'return ${expression(node.value!)};');
      case ExpressionStatement():
        line('${expression(node.expression)};');
      case IfStatement():
        line('if (${expression(node.condition, opaqueBool: true)}) {');
        _depth++;
        statements(node.thenBody);
        _depth--;
        if (node.elseBody.isNotEmpty) {
          line('} else {');
          _depth++;
          statements(node.elseBody);
          _depth--;
        }
        line('}');
      case ForStatement():
        final symbol = model.declarations[node]!;
        line(
            'for (final ${symbol.type} ${symbol.dartName} in ${expression(node.iterable)}) {');
        _depth++;
        statements(node.body);
        _depth--;
        line('}');
      case FunctionDeclaration():
        throw StateError('Nested function reached emitter');
    }
  }

  String quote(String value) => quoteDartString(value);
  String expression(Expression node,
      {bool constantContext = false, bool opaqueBool = false}) {
    // Folding only logical const operators avoids Dart's dead_code warning
    // while leaving other const operations for Dart to evaluate again.
    if (constantContext &&
        node is BinaryExpression &&
        (node.operator == 'and' || node.operator == 'or')) {
      final value = model.constants[node];
      if (value is! ConstBool) {
        throw StateError('Logical const was not evaluated');
      }
      return value.dartSource;
    }
    // A const or literal bool is reachable to Dart's analyzer when it is
    // hidden behind an identity call. The operand is still read once.
    if (opaqueBool && !constantContext && _opaqueBoolLeaf(node)) {
      _useBoolHelper = true;
      return '_qBool(${expression(node, constantContext: constantContext)})';
    }
    final logic = node is BinaryExpression &&
        (node.operator == 'and' || node.operator == 'or');
    final childOpaque = !constantContext && (opaqueBool || logic);
    return switch (node) {
      Literal() =>
        node.value is String ? quote(node.value as String) : '${node.value}',
      Identifier() => _use(node),
      // Dart has no prefix +. Quds unary + is numeric identity.
      UnaryExpression() => switch (node.operator) {
          'not' =>
            '(!${expression(node.operand, constantContext: constantContext, opaqueBool: childOpaque)})',
          '+' => expression(node.operand, constantContext: constantContext),
          _ =>
            '(${node.operator}${expression(node.operand, constantContext: constantContext)})',
        },
      BinaryExpression() =>
        '(${expression(node.left, constantContext: constantContext, opaqueBool: childOpaque)} ${switch (node.operator) {
          'and' => '&&',
          'or' => '||',
          _ => node.operator
        }} ${expression(node.right, constantContext: constantContext, opaqueBool: childOpaque)})',
      ListExpression() =>
        '<${model.types[node]!.substring(5, model.types[node]!.length - 1)}>[${node.elements.map((element) => expression(element, constantContext: constantContext)).join(', ')}]',
      CallExpression() => call(node, constantContext: constantContext),
      InterpolatedString() =>
        '[${node.parts.map((part) => expression(part, constantContext: constantContext)).join(', ')}].join()',
    };
  }

  bool _opaqueBoolLeaf(Expression node) {
    if (node is Literal) return node.value is bool;
    if (node is Identifier) {
      final symbol = model.references[node];
      return symbol != null && symbol.type == 'bool' && symbol.function == null;
    }
    return false;
  }

  String _use(Identifier node) {
    final name = model.references[node]!.dartName;
    _usedNames.add(name);
    return name;
  }

  String call(CallExpression node, {bool constantContext = false}) {
    final target = model.references[node.callee]!.dartName;
    if (node.arguments.every((a) => a.name == null)) {
      return '$target(${node.arguments.map((a) => expression(a.value, constantContext: constantContext)).join(', ')})';
    }
    // Evaluate written arguments exactly once, left to right, before arranging
    // them in declaration order for Dart's positional ABI.
    final declarations = <String>[];
    for (var i = 0; i < node.arguments.length; i++) {
      declarations.add(
          'final _qa$i = ${expression(node.arguments[i].value, constantContext: constantContext)};');
    }
    final ordered = model.argumentOrder[node]!.map((i) => '_qa$i').join(', ');
    return '(() { ${declarations.join(' ')} return $target($ordered); })()';
  }
}
