#!/usr/bin/env python3
"""Validate the 115-rule inventory and render its current evidence/rejections."""
import argparse
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
manifest = json.loads((root / 'docs/readiness/language.json').read_text(encoding='utf-8'))
decisions = dict(re.findall(r'^- \*\*(QUDS-\d{3})\*\* (.+)$', (root / 'docs/LANGUAGE_DECISIONS.md').read_text(encoding='utf-8'), re.M))
rows = manifest['rules']
expected = {f'QUDS-{i:03}' for i in range(1, 116)}
assert len(rows) == 115 and {r['id'] for r in rows} == expected, 'Missing/duplicate approved decision'
for row in rows:
    assert row['decision_summary'] == decisions[row['id']], f"Stale decision: {row['id']}"
    assert row['status'] in {'needs_certification', 'partial', 'complete'}
    for path in row['candidate_test_files'] + row['verified_slice_files']:
        assert (root / path).is_file(), f'Missing evidence file: {path}'
    if row['status'] == 'complete':
        assert not row['known_limits'], 'A complete rule cannot have known gaps'
        for kind in ('positive', 'negative', 'interop'):
            assert row['completion_evidence'][kind], f'Missing {kind} certification'
            for path in row['completion_evidence'][kind]:
                assert (root / path).is_file(), f'Missing certificate evidence: {path}'

def link(path):
    return f'[{path}](../{path})'

lines = ['# Language readiness inventory', '',
    'Generated by `python3 tool/audit_language.py`; edit `docs/readiness/language.json`.', '',
    'The formal specification is authoritative. Handoff summaries below are navigation labels,',
    'not new grammar. `needs_certification` means rule-specific positive/negative/interop proof',
    'has not been assembled. `partial` identifies a known limit. Candidate files are leads,',
    'not proof of complete support. Verified slices are deliberately narrower than whole rules.',
    'No row is declared complete merely because a sample or the full test suite passes.', '',
    '| Rule | Decision | Status | Evidence / next review |', '| --- | --- | --- | --- |']
for row in rows:
    evidence = row['verified_slice_files'] or row['candidate_test_files']
    description = row['decision_summary'].replace('|', '\\|')
    note = '; '.join(row['known_limits'])
    lines.append(f"| {row['id']} | {description} | {row['status']} | {', '.join(link(p) for p in evidence)}{' — ' + note if note else ''} |")
lines += ['', '## Current explicit E910 boundaries', '',
    'This is a source inventory, not a claim that every deliberate rejection is a missing feature.',
    'Readonly erasure constraints and unsupported signatures must remain rejected until proved safe.', '']
for path in ('lib/src/semantics.dart', 'lib/src/emitter.dart'):
    source = (root / path).read_text(encoding='utf-8').splitlines()
    for index, line in enumerate(source):
        if "'E910'" in line:
            context = ' '.join(s.strip() for s in source[index:index+4])[:260]
            lines.append(f'- [{path}:{index+1}](../{path}#L{index+1}): `{context}`')
lines += ['', '## Exit gate', '',
    'A stable release requires verified rule slices expanded into full conformance, reviewed',
    'remaining rejections, actual cross-host CI and Flutter engine evidence. Configuration of',
    'a CI job is not a passed run. See [the working plan](LANGUAGE_READINESS_AR.md).', '']
text = '\n'.join(lines)
target = root / 'docs/LANGUAGE_READINESS.md'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
if parser.parse_args().check:
    assert target.is_file() and target.read_text(encoding='utf-8') == text, 'Stale readiness inventory; run tool/audit_language.py'
else:
    target.write_text(text, encoding='utf-8')
print('READINESS: 115 decisions indexed; no unearned completeness claims')
