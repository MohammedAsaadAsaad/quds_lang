  StringBuffer? _redirect;
  final _unions = <String>{};
  int _depth = 0;
  int _temps = 0;
  SourceSpan? _span;
  final mappings = <(int, SourceSpan)>[];
  final _imports = <String>[];
  var _classes = <String, ClassDeclaration>{};
