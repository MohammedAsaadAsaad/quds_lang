#!/usr/bin/env python3
"""Generates pinned Unicode 15.0.0 lookup tables for lib/sdk/text.quds and
independent Unicode reference tests in test/text_unicode_reference.quds.
"""
from pathlib import Path
import unicodedata

VERSION = unicodedata.unidata_version
BEGIN_MARKER = "# BEGIN GENERATED UNICODE DATA"
END_MARKER = "# END GENERATED UNICODE DATA"


def to36(n: int) -> str:
    chars = "0123456789abcdefghijklmnopqrstuvwxyz"
    if n == 0:
        return "0"
    out = []
    while n:
        out.append(chars[n % 36])
        n //= 36
    return "".join(reversed(out))


def encode_ranges(cps: list[int]) -> str:
    cps = sorted(set(cps))
    runs = []
    for cp in cps:
        if runs and runs[-1][1] + 1 == cp:
            runs[-1][1] = cp
        else:
            runs.append([cp, cp])
    return ";".join(f"{to36(s)},{to36(e - s)}" for s, e in runs)


def chunk_quds_string(name: str, data: str, width: int = 120) -> str:
    parts = [data[i : i + width] for i in range(0, len(data), width)]
    if not parts:
        return f'{name}() -> String = ""\n'
    lines = [f"{name}() -> String:", "  b = StringBuffer()"]
    for part in parts:
        lines.append(f'  b.write("{part}")')
    lines.append("  return b.toString()")
    return "\n".join(lines) + "\n"


def build_tables() -> str:
    ccc_runs = []
    canon = []
    compat = []
    comp_pairs = []
    cf = []
    extend_cps = [
        0x200C,
        0xFF9E,
        0xFF9F,
        *range(0x1F3FB, 0x1F400),
        *range(0xE0020, 0xE0080),
    ]
    mc_cps = []

    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        cat = unicodedata.category(ch)
        if cat in ("Mn", "Me"):
            extend_cps.append(cp)
        elif cat == "Mc":
            mc_cps.append(cp)

        c = unicodedata.combining(ch)
        if c:
            if ccc_runs and ccc_runs[-1][1] + 1 == cp and ccc_runs[-1][2] == c:
                ccc_runs[-1][1] = cp
            else:
                ccc_runs.append([cp, cp, c])

        d = unicodedata.decomposition(ch)
        if d:
            if d.startswith("<"):
                seq = [int(x, 16) for x in d.split()[1:]]
                compat.append((cp, seq))
            else:
                seq = [int(x, 16) for x in d.split()]
                canon.append((cp, seq))
                if (
                    len(seq) == 2
                    and unicodedata.normalize("NFC", chr(seq[0]) + chr(seq[1])) == ch
                ):
                    comp_pairs.append((seq[0], seq[1], cp))

        if not (65 <= cp <= 90):
            folded = ch.casefold()
            if folded != ch:
                cf.append((cp, [ord(x) for x in folded]))

    ccc_str = ";".join(f"{to36(s)},{to36(e - s)},{to36(c)}" for s, e, c in ccc_runs)
    canon_str = ";".join(
        to36(cp) + ":" + ",".join(to36(x) for x in seq) for cp, seq in canon
    )
    compat_str = ";".join(
        to36(cp) + ":" + ",".join(to36(x) for x in seq) for cp, seq in compat
    )
    comp_str = ";".join(f"{to36(a)},{to36(b)},{to36(c)}" for a, b, c in comp_pairs)
    cf_str = ";".join(
        to36(cp) + ":" + ",".join(to36(x) for x in seq) for cp, seq in cf
    )
    extend_str = encode_ranges(extend_cps)
    spacing_str = encode_ranges(mc_cps)

    out = [
        BEGIN_MARKER,
        f"# Pinned Unicode data version: {VERSION} (generated by tool/generate_text_unicode.py).",
        f'_uDataVersion() -> String = "{VERSION}"',
        "",
        chunk_quds_string("_uCccRaw", ccc_str),
        chunk_quds_string("_uCanonRaw", canon_str),
        chunk_quds_string("_uCompatRaw", compat_str),
        chunk_quds_string("_uCompRaw", comp_str),
        chunk_quds_string("_uCaseFoldRaw", cf_str),
        chunk_quds_string("_uExtendRaw", extend_str),
        chunk_quds_string("_uSpacingRaw", spacing_str),
        END_MARKER,
    ]
    return "\n".join(out) + "\n"


def quds_codepoints_expr(s: str) -> str:
    if not s:
        return '""'
    cps = [ord(ch) for ch in s]
    return "String.fromCharCodes([" + ", ".join(str(c) for c in cps) + "])"


def generate_reference_suite() -> str:
    samples = [
        "",
        "ASCII plain 123",
        "Café",
        "Cafe\u0301",
        "e\u0301\u0327",
        "e\u0327\u0301",
        "a\u0308\u0323",
        "a\u0323\u0308",
        "\u00C5",
        "\u212B",
        "A\u030A",
        "\u1E9B\u0323",
        "\u017F\u0323\u0307",
        "\uFB01\uFB02\uFB03",
        "\u2460\u00B2\u00BD\uFF21\uFF22\uFF11",
        "قُدْسٌ",
        "\u0642\u0651\u064E",
        "\u0642\u064E\u0651",
        "\uFEFB",
        "\uFDF2",
        "한글",
        "\u1112\u1161\u11AB\u1100\u1173\u11AF",
        "\uAC00",
        "\u1100\u1161",
        "\uAC01",
        "\u1100\u1161\u11A8",
        "Ω",
        "\u2126",
        "ΐ",
        "\u03B9\u0308\u0301",
        "\u0399\u0308\u0301",
        "Straße",
        "İSTANBUL",
        "ΌΣΟΣ",
        "ﬁle",
        "ǅ",
        "ᾨ",
        "가나다라마바사",
        "😀",
        "👨‍👩‍👧‍👦",
        "🇵🇸🇺🇸",
        "👋🏽",
    ]
    # Add diverse single code points across Unicode blocks with decompositions / casefold
    extra_cps = [
        0x00C0, 0x00E9, 0x00DF, 0x0130, 0x0131, 0x0149, 0x0178, 0x01F0,
        0x0390, 0x03B0, 0x03C2, 0x03D2, 0x03D3, 0x03D4, 0x0401, 0x0451,
        0x0587, 0x0622, 0x0623, 0x0624, 0x0625, 0x0626, 0x06C0, 0x06C2,
        0x0929, 0x0958, 0x09DC, 0x0F43, 0x1E00, 0x1E9E, 0x1F80, 0x1FB2,
        0x1FC2, 0x1FF2, 0x2000, 0x2126, 0x212A, 0x212B, 0x2160, 0x24B6,
        0x304C, 0x30AC, 0x3099, 0x3200, 0x3300, 0xF900, 0xFB00, 0xFB04,
        0xFB05, 0xFB06, 0xFE70, 0xFF01, 0xFF66, 0x1D15E, 0x1D400, 0x2F800,
    ]
    for cp in extra_cps:
        samples.append(chr(cp))

    out = [
        f"# Independent Unicode {VERSION} reference suite generated from Python unicodedata.",
        "use quds:text::unicode",
        "",
        "_check(s: String, nfc: String, nfd: String, nfkc: String, nfkd: String, cf: String) -> int:",
        "  rNfc = normalizeUnicode(s, form: TextNormalizationForm.nfc)",
        "  rNfd = normalizeUnicode(s, form: TextNormalizationForm.nfd)",
        "  rNfkc = normalizeUnicode(s, form: TextNormalizationForm.nfkc)",
        "  rNfkd = normalizeUnicode(s, form: TextNormalizationForm.nfkd)",
        "  expect(rNfc, nfc)",
        "  expect(rNfd, nfd)",
        "  expect(rNfkc, nfkc)",
        "  expect(rNfkd, nfkd)",
        "  expect(isNormalizedUnicode(rNfc, form: TextNormalizationForm.nfc), true)",
        "  expect(isNormalizedUnicode(rNfd, form: TextNormalizationForm.nfd), true)",
        "  expect(isNormalizedUnicode(rNfkc, form: TextNormalizationForm.nfkc), true)",
        "  expect(isNormalizedUnicode(rNfkd, form: TextNormalizationForm.nfkd), true)",
        "  expect(caseFoldText(s), cf)",
        "  expect(caseFoldText(cf), cf)",
        "  return 10",
        "",
        f'test "unicode reference ({VERSION}): NFC, NFD, NFKC, NFKD, idempotence, and caseFoldText":',
        f'  expect(unicodeVersion(), "{VERSION}")',
        "  var checks = 0",
    ]
    for s in samples:
        expr = quds_codepoints_expr(s)
        nfc = quds_codepoints_expr(unicodedata.normalize("NFC", s))
        nfd = quds_codepoints_expr(unicodedata.normalize("NFD", s))
        nfkc = quds_codepoints_expr(unicodedata.normalize("NFKC", s))
        nfkd = quds_codepoints_expr(unicodedata.normalize("NFKD", s))
        cf = quds_codepoints_expr(s.casefold())
        out.append(f"  checks = checks + _check({expr}, {nfc}, {nfd}, {nfkc}, {nfkd}, {cf})")
    out.append(f'  print "QUDS TEXT UNICODE CHECKS=" + checks.toString() + " FAILURES=0"')
    return "\n".join(out) + "\n"


def main() -> None:
    text_path = Path("lib/sdk/text.quds")
    text = text_path.read_text()
    block = build_tables()
    if BEGIN_MARKER in text and END_MARKER in text:
        before = text.split(BEGIN_MARKER)[0]
        after = text.split(END_MARKER)[1]
        if after.startswith("\n"):
            after = after[1:]
        text_path.write_text(before + block + after)
    else:
        text_path.write_text(text.rstrip() + "\n\n" + block)
    ref_path = Path("test/text_unicode_reference.quds")
    ref_path.write_text(generate_reference_suite())
    print(f"Updated {text_path} ({len(block)} bytes Unicode {VERSION} data) and {ref_path}")


if __name__ == "__main__":
    main()
