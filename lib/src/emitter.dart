      helpers.writeln('String _qAt(String text, int index) {\n'
          '  final i = index < 0 ? text.length + index : index;\n'
          '  return text.substring(i, i + 1);\n'
          '}');
    }
    if (_useLeast) {
      helpers.writeln(
          'T? _qLeast<T extends num>(Iterable<T> items, bool greatest) {\n'
          '  T? best;\n'
          '  for (final item in items) {\n'
          '    if (best == null || (greatest ? item > best : item < best)) best = item;\n'
          '  }\n'
          '  return best;\n'
          '}');
    }
    if (_useGroup) {
      helpers.writeln(
          'Map<K, List<T>> _qGroup<T, K>(Iterable<T> items, K Function(T) key) {\n'
          '  final grouped = <K, List<T>>{};\n'
          '  for (final item in items) {\n'
          '    grouped.putIfAbsent(key(item), () => <T>[]).add(item);\n'
          '  }\n'
          '  return grouped;\n'
          '}');
    }
    if (_useTests) {
      helpers.writeln('var _qTestFailed = 0;');
    }
    if (_useDefaultOmitted) {
      helpers.writeln(
          'class $_defaultOmittedClass { const $_defaultOmittedClass(); }\n'
          'const $_defaultOmitted = $_defaultOmittedClass();');
    }
    if (_useGap) {
      helpers.writeln(
          'final _\$qudsGaps = Expando<Object? Function(List<Object?>, List<bool>)>();\n'
          'void _\$qudsBindGap(Object value, Object? Function(List<Object?>, List<bool>) gap) {\n'
          '  _\$qudsGaps[value] = gap;\n'
          '}\n'
          'T _\$qudsCallGap<T>(Object value, List<Object?> inputs, List<bool> present) =>\n'
          '    _\$qudsGaps[value]!(inputs, present) as T;');
    }
    if (_useOptional) {
      helpers.writeln('class Optional<T> {\n'
          '  final bool isPresent;\n'
          '  final T? value;\n'
          '  const Optional.missing() : isPresent = false, value = null;\n'
          '  const Optional.present(this.value) : isPresent = true;\n'
          '}\n'
          'const missing = Optional<Never>.missing();');
    }
    if (_useResult) {
      helpers.writeln('sealed class Result<T, E> { const Result(); }\n'
          'class Ok<T, E> extends Result<T, E> {\n'
          '  final T value;\n'
          '  const Ok(this.value);\n'
          '}\n'
          'class Error<T, E> extends Result<T, E> {\n'
          '  final E error;\n'
          '  const Error(this.error);\n'
          '}');
      if (_usePropagate) {
        helpers.writeln('class _QudsPropagate implements Exception {\n'
            '  final Result<Object?, Object?> result;\n'
            '  _QudsPropagate(this.result);\n'
            '}');
      }
    }
    if (_useConversion) {
      _requireReadonlyRuntime();
      helpers.writeln(
          'Object? _qConvert(Object? value, String target, bool safe) {\n'
          '  try {\n'
          '    switch (target) {\n'
          "      case 'String': return value.toString();\n"
          "      case 'bool':\n"
          '        if (value is bool) return value;\n'
          "        if (value == 'true') return true;\n"
          "        if (value == 'false') return false;\n"
          '        break;\n'
          "      case 'int':\n"
          '        if (value is int) return value;\n'
          '        if (value is double && value.isFinite && value == value.truncateToDouble()) return value.toInt();\n'
          '        if (value is String) return int.parse(value);\n'
          '        break;\n'
          "      case 'double':\n"
          '        if (value is double) return value;\n'
          '        if (value is int) return value.toDouble();\n'
          '        if (value is String) return double.parse(value);\n'
          '        break;\n'
          "      case 'num':\n"
          '        if (value is num) return value;\n'
          '        if (value is String) return num.parse(value);\n'
          '        break;\n'
          '    }\n'
          '    throw $_readonlyRuntime.ConversionError(\'\$value to \$target\');\n'
          '  } catch (error) {\n'
          '    if (safe) return null;\n'
          '    if (error is $_readonlyRuntime.ConversionError) throw error;\n'
          '    throw $_readonlyRuntime.ConversionError(\'\$value to \$target\');\n'
          '  }\n'
          '}');
    }
    if (_useReturn) {
      helpers.writeln('class _QudsReturn {\n'
          '  _QudsReturn(this.value);\n'
          '  final Object? value;\n'
          '}');
    }
    for (final union in _unions) {
      final name = _unionClass(union);
      final parts = union.split(' | ').map((part) => part.trim());
      helpers.writeln('sealed class $name { const $name(); }');
      for (final part in parts) {
        final alt = _alt(part);
        helpers.writeln('class ${name}_$alt extends $name {\n'
            '  final ${_dartType(part)} value;\n'
            '  const ${name}_$alt(this.value);\n'
            '}');
      }
    }
    final prelude = StringBuffer();
    for (final item in _imports.toSet()) {
      prelude.writeln(item);
    }
    if (_useChecks) {
      prelude
        ..writeln("import 'package:matcher/expect.dart' as _qmatch;")
        ..writeln(
            "import 'package:quds_lang/src/check_runtime.dart' as _qrun;");
    }
    if (_useState || _useWatch || _useBatch) {
      final batchFields = _useBatch
          ? '  static var batchDepth = 0;\n'
              '  static final List<_QudsState<Object?>> _pending = [];\n'
          : '';
      final batchSet = _useBatch
          ? '    if (batchDepth > 0) {\n'
              '      final cell = this as _QudsState<Object?>;\n'
              '      if (!_pending.contains(cell)) _pending.add(cell);\n'
              '      return;\n'
              '    }\n'
          : '';
      final listeners = _useWatch
          ? '  void _listen(void Function() listener) {\n'
              '    _listeners.remove(listener);\n'
