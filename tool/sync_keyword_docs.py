#!/usr/bin/env python3
"""Embed the English Markdown reference in the language server; no runtime I/O."""
import argparse
import json
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
source = root / 'docs/KEYWORD_REFERENCE.md'
target = root / 'lib/src/keyword_docs_data.dart'
sections = re.findall(r'^## `([^`]+)`\n\n(.*?)(?=^## |\Z)', source.read_text(), re.M | re.S)
if not sections or len(dict(sections)) != len(sections):
    raise SystemExit('Missing or duplicate keyword sections')
lines = ['// Generated by tool/sync_keyword_docs.py. Edit docs/KEYWORD_REFERENCE.md.',
         'const keywordDocumentation = <String, String>{']
for key, body in sections:
    if '```quds\n' not in body:
        raise SystemExit(f'Missing example: {key}')
    encode = lambda s: json.dumps(s, ensure_ascii=False).replace('$', r'\$')
    lines.append(f'  {encode(key)}: {encode("### " + key + chr(10) * 2 + body.strip())},')
lines.append('};\n')
# dart format is applied separately; ignore formatting-only whitespace by comparing
# generated string tokens, rather than maintaining a second Markdown copy.
output = '\n'.join(lines)
args = argparse.ArgumentParser()
args.add_argument('--check', action='store_true')
if args.parse_args().check:
    tokens = lambda s: re.findall(r'"(?:\\.|[^"\\])*"', s)
    if not target.exists() or tokens(target.read_text()) != tokens(output):
        raise SystemExit('Keyword documentation is stale; run tool/sync_keyword_docs.py')
else:
    target.write_text(output)
