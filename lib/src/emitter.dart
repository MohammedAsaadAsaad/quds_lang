          '    yield value;\n'
          '  }\n'
          '}');
    }
    if (_useNumRange) {
      helpers.writeln(
          'Iterable<num> _qNumRange(num start, num end, bool inclusive, [num? step]) sync* {\n'
          '  final stride = step ?? (start > end ? -1 : 1);\n'
          '  if (stride == 0) throw RangeError.range(0, 1, null, "step");\n'
          '  final forward = stride > 0;\n'
          '  if (forward ? start > end : start < end) return;\n'
          '  for (var value = start; forward ? (inclusive ? value <= end : value < end) : (inclusive ? value >= end : value > end); value += stride) {\n'
          '    yield value;\n'
          '  }\n'
          '}');
    }
    if (_usePlain) {
      helpers.writeln('String _qPlain(num value) {\n'
          '  final text = value.toString();\n'
          '  if (text.contains(\'e\') || text.contains(\'E\') || !text.contains(\'.\')) return text;\n'
          '  var body = text;\n'
          '  while (body.endsWith(\'0\')) {\n'
          '    body = body.substring(0, body.length - 1);\n'
          '  }\n'
          '  if (body.endsWith(\'.\')) body = body.substring(0, body.length - 1);\n'
          '  if (body == \'\' || body == \'-\') return \'0\';\n'
          '  return body;\n'
          '}');
