"""Frozen exact polynomial calculus references, using only Python Fraction."""
from fractions import Fraction as F
from pathlib import Path
import random
rng=random.Random(59207)
def q(value): return f'bigFraction(bigInt("{value.numerator}"), bigInt("{value.denominator}"))'
def number(value): return f'exprNumber({q(value)})'
def polynomial(coefficients):
    terms=[f'exprMultiply({number(c)}, exprPower(exprSymbol("x"), {number(F(i))}))' for i,c in enumerate(coefficients)]
    expression=number(F(0))
    for term in terms: expression=f'exprAdd({expression}, {term})'
    return expression
polys=[[],[F(0)],[F(1)],[F(-2,3)],[F(0),F(1)],[F(1),F(-2),F(1)]]
for degree in [9,12,16]:
    polys.append([F((-1)**i*(i+1),i+2) for i in range(degree+1)])
for _ in range(50):
    polys.append([F(rng.randrange(-9,10),rng.randrange(1,8)) for _ in range(rng.randrange(1,8))])
header='''# Generated by Python Fraction polynomial formulas, no symbolic dependency.
use quds:math

class _SymbolicCount:
  var value: int = 0

# Evaluation only; this oracle never differentiates or integrates an AST.
_symbolicEval(node: Expr, point: BigFraction) -> BigFraction:
  if node.kind == "number": return node.number
  if node.kind == "symbol":
    expect(node.name, "x")
    return point
  left = _symbolicEval(node.arguments[0], point)
  if node.kind == "power":
    exponent = node.arguments[1].number
    expect(exponent.denominator, BigInt.one)
    var remaining = exponent.numerator.toInt()
    var factor = left
    if remaining < 0:
      factor = left.reciprocal()
      remaining = -remaining
    var accumulator = bigFraction(BigInt.one, BigInt.one)
    while remaining > 0:
      accumulator = accumulator * factor
      remaining -= 1
    return accumulator
  right = _symbolicEval(node.arguments[1], point)
  if node.kind == "add": return left + right
  if node.kind == "subtract": return left - right
  if node.kind == "multiply": return left * right
  if node.kind == "divide": return left / right
  throw "unsupported reference expression"

_symbolicReference(counter: _SymbolicCount, tree: Expr, point: BigFraction, expected: BigFraction):
  counter.value += 1
  expect(_symbolicEval(tree, point).compareTo(expected), 0)

test "exact symbolic polynomial calculus against independent references":
  counter = _SymbolicCount()
'''
lines=[];checks=0
for index,coefficients in enumerate(polys):
    lines.extend([f'  polynomial{index} = {polynomial(coefficients)}',
                  f'  simplified{index} = simplifyExpr(polynomial{index})',
                  f'  derivative{index} = deriveExpr(polynomial{index}, "x")',
                  f'  integral{index} = integratePolynomial(polynomial{index}, "x")',
                  f'  recovered{index} = deriveExpr(integral{index}, "x")'])
    for point in [F(0),F(1),F(-1),F(2,3),F(-7,5)]:
        value=sum((c*point**i for i,c in enumerate(coefficients)),F(0))
        derivative=sum((i*c*point**(i-1) for i,c in enumerate(coefficients) if i>0),F(0))
        integral=sum((c*point**(i+1)/(i+1) for i,c in enumerate(coefficients)),F(0))
        for tree,expected in [(f'polynomial{index}',value),(f'simplified{index}',value),(f'derivative{index}',derivative),(f'integral{index}',integral),(f'recovered{index}',value)]:
            lines.append(f'  _symbolicReference(counter, {tree}, {q(point)}, {q(expected)})');checks+=1
Path('test/math_symbolic_reference.quds').write_text(header+'\n'.join(lines)+
 f'\n  expect(counter.value, {checks})\n  print "QUDS SYMBOLIC CHECKS={checks} FAILURES=0"\n')
print(f'Quds symbolic references: {checks} on {len(polys)} polynomials')
