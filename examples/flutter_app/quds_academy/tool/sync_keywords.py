#!/usr/bin/env python3
"""Build the offline bilingual Quds reference from the repository guide."""
from pathlib import Path
import json
import re
import argparse

app = Path(__file__).resolve().parents[1]
root = app.parents[2]
reference = (root / 'docs/KEYWORD_REFERENCE.md').read_text()
arabic = json.loads((app / 'assets/keywords_ar.json').read_text())
entries = re.findall(r'^## `([^`]+)`\n\n(.*?)(?=^## |\Z)', reference, re.M | re.S)
if set(arabic) != {key for key, _ in entries}:
    raise SystemExit('Arabic keyword coverage differs from the English reference')
def literal(value):
    # Quds interpolation must not reinterpret documentation braces.
    return 'r' + json.dumps(value, ensure_ascii=False) if '\\' not in json.dumps(value)[1:-1] else 'r"""' + value + '"""'
lines = ['# Generated by tool/sync_keywords.py. Do not edit.', 'use catalog', '', 'keywordEntries() -> List<KeywordEntry>:', '  return [']
for key, body in entries:
    example = re.search(r'```quds\n(.*?)\n```', body, re.S).group(1)
    prose = body.split('```quds')[0].strip().replace('`', '').replace('**', '')
    values = [key, prose, arabic[key], example]
    # Raw triple strings retain source newlines and quote characters.
    encode = lambda x: "r'''" + x.replace("'''", '"""') + "'''"
    lines.append('    KeywordEntry(' + ', '.join(encode(x) for x in values) + '),')
lines.append('  ]\n')
text = '\n'.join(lines)
target = app / 'lib/src/keywords.quds'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
if parser.parse_args().check:
    if not target.exists() or target.read_text() != text:
        raise SystemExit('Stale academy reference; run tool/sync_keywords.py')
else:
    target.write_text(text)
