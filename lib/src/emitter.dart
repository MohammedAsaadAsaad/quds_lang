  void line(String text) {
    if (_redirect != null) {
      _redirect!.writeln('${'  ' * _depth}$text');
      return;
    }
    if (_span != null) {
      mappings.add((_nextOutputLine, _span!));
    }
    _out.writeln('${'  ' * _depth}$text');
    _nextOutputLine += '\n'.allMatches(text).length + 1;
  }

  String emit(Program program) {
    _programFile = program.span.file;
    _defaultBridges.addAll(model.providerDefaultFunctions);
    _defaultBridges.addAll(model.providerDefaultMethods.keys);
    _defaultBridges.addAll(model.qudsValueLowerings.values
        .map((lowering) => lowering.function)
        .where((function) =>
            function.span.file == program.span.file &&
            !function.parameters.any((p) => p.type.contains(' & ')) &&
            !model.classes.values.any((owner) =>
                owner.kind == 'interface' &&
                owner.methods.contains(function)) &&
            function.parameters.any((p) => p.needsAdapter)));
    _hasParts = program.statements.any((node) => node is PartDirective);
    _isPart =
        program.statements.any((node) => node is PartDirective && node.of);
    if (_hasParts) {
      final salt = sha256Hex(utf8.encode(program.span.file)).substring(0, 12);
      _defaultOmitted += '_$salt';
      _defaultOmittedClass += '_$salt';
      _knownGuardsName +=
          '_${sha256Hex(utf8.encode(program.span.file)).substring(0, 12)}';
      _requireReadonlyRuntime();
    }
    _directives(program.statements);
    _classes = {
      ...model.classes,
      for (final node in program.statements)
        if (node is ClassDeclaration) node.name: node
    };
    final configs = program.statements.whereType<ConfigDeclaration>().toList();
    if (configs.isNotEmpty) _emitConfigs(configs);
    for (final node in program.statements) {
      if (node is AnnotationDeclaration) _emitAnnotation(node);
      if (node is ClassDeclaration) emitClass(node);
      if (node is ExtensionDeclaration) emitExtension(node);
    }
    for (final owner in program.statements.whereType<ClassDeclaration>()) {
      if (owner.kind != 'interface') continue;
      for (final method in owner.methods) {
        if (model.providerDefaultMethods[method] == owner)
          _emitInterfaceDefaults(owner, method);
      }
    }
    _emitReflectableRegistry(program);
    for (final node in program.statements) {
      _out.writeln();
      _nextOutputLine++;
      if (node is FunctionDeclaration) {
        emitFunction(node);
      } else if (node is! ImportDeclaration &&
          node is! ClassDeclaration &&
          node is! ExtensionDeclaration &&
          node is! AliasDeclaration &&
          node is! AnnotationDeclaration &&
          node is! ConfigDeclaration) {
        statement(node);
      }
    }
    _emitPublicNames(program);
    if (_useReadonlyRuntime) _emitKnownReadonlyGuards(program);
    return _suppressUnreadConsts(_withHelpers(_out.toString()));
  }

  void _emitConfigs(List<ConfigDeclaration> items) {
    _useConfig = true;
    final root = _ConfigGroup();
    for (final item in items) {
      var node = root;
      final parts = item.name.split('.');
      for (var i = 0; i < parts.length; i++) {
        final child = node.children.putIfAbsent(parts[i], _ConfigGroup.new);
        if (i == parts.length - 1) child.leaf = item;
        node = child;
      }
    }
    line('class config {');
    _depth++;
    _emitConfigMembers(root, staticMembers: true, prefix: '');
    _depth--;
    line('}');
    _emitConfigClasses(root, '');
  }

  void _emitConfigMembers(_ConfigGroup node,
      {required bool staticMembers, required String prefix}) {
    for (final entry in node.children.entries) {
      final path = prefix.isEmpty ? entry.key : '$prefix.${entry.key}';
      final child = entry.value;
      if (child.leaf != null) {
        final item = child.leaf!;
        final env = path.toUpperCase().replaceAll('.', '_');
        final parsed = switch (item.type) {
          'int' => 'int.parse(raw)',
          'double' => 'double.parse(raw)',
          'bool' =>
            "raw == 'true' ? true : raw == 'false' ? false : throw FormatException('bool', raw)",
          _ => 'raw',
        };
        final missing = item.value == null
            ? "throw StateError('Missing required config $path')"
            : 'return ${expression(item.value!)}';
        final keyword = staticMembers ? 'static ' : '';
        line('$keyword'
            'late final ${_dartType(item.type)} ${entry.key} = () { '
            "final raw = _qConfigRaw('$env', '$path'); "
            'if (raw != null) return $parsed; $missing; }();');
      } else {
        final typeName = '_QudsConfig_${path.replaceAll('.', '_')}';
        final keyword = staticMembers ? 'static ' : '';
        line('$keyword'
            'final ${entry.key} = $typeName();');
      }
    }
  }

  void _emitConfigClasses(_ConfigGroup node, String prefix) {
    for (final entry in node.children.entries) {
      final path = prefix.isEmpty ? entry.key : '$prefix.${entry.key}';
      final child = entry.value;
      if (child.leaf != null) continue;
      final typeName = '_QudsConfig_${path.replaceAll('.', '_')}';
      line('class $typeName {');
      _depth++;
      _emitConfigMembers(child, staticMembers: false, prefix: path);
      _depth--;
      line('}');
      _emitConfigClasses(child, path);
    }
  }

  /// Logical const folding can remove the only read of a const. Keep the
  /// binding and silence Dart's unused warning for that declaration.
  String _suppressUnreadConsts(String source) {
    final unread = _constNames.difference(_usedNames);
    if (unread.isEmpty) return source;
    final lines = source.split('\n');
    final rewritten = <String>[];
    final shifts = <int>[0];
    var added = 0;
    for (final line in lines) {
      final trimmed = line.trimLeft();
      String? lint;
      for (final name in unread) {
        if (trimmed.startsWith('const ') && trimmed.contains(' $name =')) {
          lint = _topLevelConsts.contains(name)
              ? 'unused_element'
              : 'unused_local_variable';
          break;
        }
      }
      if (lint != null) {
        final indent = line.substring(0, line.length - trimmed.length);
        rewritten.add('$indent// ignore: $lint');
        added++;
      }
      shifts.add(added);
      rewritten.add(line);
    }
    for (var i = 0; i < mappings.length; i++) {
      final (line, span) = mappings[i];
      mappings[i] = (line + shifts[line.clamp(0, shifts.length - 1)], span);
    }
    return rewritten.join('\n');
  }

  String _sectionCombinator(
      ImportDeclaration node, List<String> sectionNames, String home) {
    if (node.export) {
      return sectionNames.isEmpty ? '' : ' show ${sectionNames.join(', ')}';
    }
    final used = model.usedSdkNames[home] ?? const <String>{};
    final show = [
      for (final name in sectionNames)
        if (used.contains(name)) name,
    ];
    return show.isEmpty ? '' : ' show ${show.join(', ')}';
  }

  void _emitPublicNames(Program program) {
    final groups = <String, List<FunctionDeclaration>>{};
    for (final node in program.statements) {
      if (node is! FunctionDeclaration || node.name == 'main') continue;
      if (node.name.startsWith('_') &&
          !program.statements.any((item) => item is PartDirective)) continue;
      groups.putIfAbsent(node.name, () => []).add(node);
    }
    for (final entry in groups.entries) {
      if (entry.value.length == 1) {
        final symbol = model.declarations[entry.value.single];
        if (symbol == null || symbol.dartName == entry.key) continue;
        line('final ${entry.key} = ${symbol.dartName};');
        continue;
      }
      for (var i = 0; i < entry.value.length; i++) {
        final symbol = model.declarations[entry.value[i]];
        if (symbol == null) continue;
        line('final ${entry.key}\$${i + 1} = ${symbol.dartName};');
      }
    }
  }

  List<String> _providerCombinator(
          List<String> names, ImportDeclaration node) =>
      [
        ...names,
        for (final function
            in model.providerDefaultImports[node] ?? <FunctionDeclaration>{})
          if (names.contains(function.name))
            providerDefaultBridgeName(function),
      ];

  void _directives(List<Statement> statements) {
    for (final node in statements) {
      if (model.skipped.contains(node)) continue;
      if (node is WhenStatement) {
        _directives(node.body);
        continue;
      }
      if (node is ImportDeclaration) {
        if (node.uri.startsWith('quds:')) {
          if (!emitsSdkImport(node, model)) continue;
          final uri = model.resolvedImports[node];
          if (uri == null) continue;
          final names = model.sdkDartNames[node.uri] ?? const <String>{};
          final sectioned =
              node.uri.startsWith('quds:') && node.uri.contains('::');
          final used = model.usedSdkNames[node.uri] ?? const <String>{};
          final show = sectioned
              ? [
                  for (final name in names)
                    if (used.contains(name)) name,
                ]
              : [
                  for (final name in node.show)
                    if (names.contains(name)) name,
                ];
          final hide = sectioned
              ? const <String>[]
              : [
                  for (final name in node.hide)
                    if (names.contains(name)) name,
                ];
          final combinator = show.isNotEmpty
              ? ' show ${show.join(', ')}'
              : hide.isNotEmpty
                  ? ' hide ${hide.join(', ')}'
                  : '';
          if (node.export) {
            _imports.add("export '$uri'$combinator;");
            continue;
          }
          final prefix = node.prefix == null
              ? ''
              : '${node.deferred ? ' deferred' : ''} as ${_dartImportPrefix(node.prefix!)}';
          // Inferred nominal results may use a backend type alias while the
          // automatically selected section still records that type dependency.
          final ignore = sectioned ? '// ignore: unused_shown_name\n' : '';
          _imports.add("${ignore}import '$uri'$prefix$combinator;");
          continue;
        }
        final target = libraryTarget(node.uri);
        final uri = model.resolvedImports[node] ??
            (target.endsWith('.quds')
                ? '${target.substring(0, target.length - 5)}.dart'
                : target);
        final sectionNames = model.sectionImports[node];
        final home = model.importHomes[node];
        final combinator = sectionNames != null && home != null
            ? _sectionCombinator(node, sectionNames, home)
            : node.show.isNotEmpty
                ? ' show ${_providerCombinator(node.show, node).join(', ')}'
                : node.hide.isNotEmpty
                    ? ' hide ${_providerCombinator(node.hide, node).join(', ')}'
                    : '';
        if (sectionNames != null && combinator.isEmpty) continue;
        if (node.export) {
          _imports.add("export '$uri'$combinator;");
          continue;
        }
        final prefix = node.prefix == null
            ? ''
            : '${node.deferred ? ' deferred' : ''} as ${_dartImportPrefix(node.prefix!)}';
        // An explicit filtered/prefixed dart:core import disables Dart's
        // implicit import. Quds primitive types and generated helpers still
        // need core; source-level show/hide remains enforced by semantics.
        if (uri == 'dart:core' &&
            (node.prefix != null ||
                node.show.isNotEmpty ||
                node.hide.isNotEmpty)) {
          _imports.add("import 'dart:core';");
        }
        final providerShow = node.show.isNotEmpty &&
            _providerCombinator(node.show, node).length > node.show.length;
        _imports.add(
            "${providerShow ? '// ignore: unused_shown_name\n' : ''}import '$uri'$prefix$combinator;");
      } else if (node is PartDirective) {
        final uri = model.resolvedParts[node] ??
            (node.uri.endsWith('.quds')
                ? '${node.uri.substring(0, node.uri.length - 5)}.dart'
                : node.uri);
        _parts.add(node.of ? "part of '$uri';" : "part '$uri';");
      }
    }
  }

  String _deferBody(Expression node) {
    if (node is AwaitExpression) {
      return 'await ${expression(node.operand)};';
    }
    return '${expression(node)};';
  }

  void statements(List<Statement> body) {
    final deferred = body.whereType<DeferStatement>().toList();
    final watched = body.whereType<WatchStatement>().isNotEmpty;
    if (deferred.isEmpty && !watched) {
      for (final node in body) {
        statement(node);
      }
      return;
    }
    final id = _temps++;
    final previousWatch = _watchList;
    final asyncScope = deferred.any(model.asyncDefers.contains);
    if (deferred.isNotEmpty) {
      final type = asyncScope ? 'Future<void> Function()' : 'void Function()';
      line('final _qd$id = <$type>[];');
    }
    if (watched) {
      _useWatch = true;
      _watchList = '_qw$id';
      line('final $_watchList = <void Function()>[];');
    }
    line('try {');
    _depth++;
    for (final node in body) {
      if (node is DeferStatement) {
        final closure = asyncScope ? '() async' : '()';
        line('_qd$id.add($closure { ${_deferBody(node.expression)} });');
      } else {
        statement(node);
      }
    }
    _depth--;
    final cleanup = <String>[];
    if (deferred.isNotEmpty) {
      cleanup.add(asyncScope
          ? 'for (final _action in _qd$id.reversed) { await _action(); }'
          : 'for (final _action in _qd$id.reversed) { _action(); }');
    }
    if (watched) {
      cleanup.add('for (final _stop in $_watchList) { _stop(); }');
    }
    line('} finally { ${cleanup.join(' ')} }');
    _watchList = previousWatch;
  }

  String _withHelpers(String source) {
    final helpers = StringBuffer();
    if (_useRange) {
      helpers.writeln(
          'Iterable<int> _qRange(int start, int end, bool inclusive, [int? step]) sync* {\n'
          '  final stride = step ?? (start > end ? -1 : 1);\n'
          '  if (stride == 0) throw RangeError.range(0, 1, null, "step");\n'
          '  final forward = stride > 0;\n'
          '  if (forward ? start > end : start < end) return;\n'
