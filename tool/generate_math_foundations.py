"""Frozen exact-rational references; Python stdlib only. Not needed to run tests."""
from fractions import Fraction as F
from pathlib import Path
import random

rng = random.Random(20261116)
checks = []
def number(x):
    s = repr(float(x))
    return s if '.' in s or 'e' in s else s + '.0'
def vector(v): return '[' + ', '.join(map(number, v)) + ']'
def check(call, expected): checks.append(f'  _foundationClose({call}, {number(expected)})')

for _ in range(32):
    xs = [F(rng.randrange(-20, 21), 4) for _ in range(rng.randrange(2, 9))]
    center = sum(xs) / len(xs)
    variance = sum((x-center)**2 for x in xs) / len(xs)
    for lag in range(len(xs)):
        cov = sum((xs[i]-center)*(xs[i-lag]-center) for i in range(lag,len(xs))) / len(xs)
        check(f'seriesAutocovariance({vector(xs)}, {lag})', cov)
        if variance:
            check(f'seriesAutocorrelation({vector(xs)}, {lag})', cov / variance)
for _ in range(32):
    prior, obs = F(rng.randrange(-10,11),2), F(rng.randrange(-10,11),2)
    variance, process, noise = F(rng.randrange(0,9),4), F(rng.randrange(0,9),4), F(rng.randrange(1,9),4)
    pred = variance + process
    gain = pred / (pred + noise)
    call = 'kalmanScalar(' + ', '.join(map(number,[prior,variance,obs,process,noise])) + ')'
    check(f'{call}.meanValue', prior + gain*(obs-prior))
    check(f'{call}.variance', pred*noise/(pred+noise))
    check(f'{call}.gain', gain)
for _ in range(32):
    a,b,p = [F(rng.randrange(0,9),8) for _ in range(3)]
    rows = [[a,1-a],[b,1-b]]
    rowtext = '[' + ', '.join(map(vector, rows)) + ']'
    probability = [p,1-p]
    for steps in range(1,4):
        probability = [sum(probability[i]*rows[i][j] for i in range(2)) for j in range(2)]
        expr = vector([p,1-p])
        for __ in range(steps): expr = f'markovStep({expr}, {rowtext})'
        check(expr+'[0]', probability[0])
        check(expr+'[1]', probability[1])
for _ in range(16):
    history = [F(rng.randrange(-4,5),2) for _ in range(2)]
    coefficients = [F(rng.randrange(-2,3),4) for _ in range(2)]
    intercept = F(rng.randrange(-2,3),4)
    values = history[:]
    for step in range(5):
        values.append(intercept+sum(coefficients[j]*values[-1-j] for j in range(2)))
        check(f'arForecast({vector(history)}, {vector(coefficients)}, {number(intercept)}, 5)[{step}]', values[-1])

text = '''# Generated by tool/generate_math_foundations.py using exact Fraction references.
use quds:math
_foundationClose(actual: double, expected: double):
  var scale = expected
  if scale < 0.0: scale = 0.0 - scale
  var gap = actual - expected
  if gap < 0.0: gap = 0.0 - gap
  expect(gap <= 1.0e-12 * (1.0 + scale), true)
test "exact-rational time-series and filtering references":
'''
text += '\n'.join(checks) + f'\n  print "QUDS FOUNDATIONS REFERENCES={len(checks)} FAILURES=0"\n'
Path('test/math_foundations_reference.quds').write_text(text)
print(len(checks))
