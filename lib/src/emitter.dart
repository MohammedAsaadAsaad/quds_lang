      for (final p in method.typeParameters)
        TypeParameter(p.name, p.span,
            bound: p.bound == null
                ? null
                : substituteBridgeType(p.bound!, _interfaceTypeBindings)),
    ];
    _span = method.span;
    _names = {..._names};
    _defaultReceiver = r'$qInterfaceReceiver';
    _openGenerics = {
      ..._openGenerics,
